/* Проверка сервера рейтинга без Cloudflare: подсовываем поддельный KV
   и дёргаем ручки напрямую. Запуск: node test_worker.js */

const fs = require('fs');
const vm = require('vm');

// --- поддельный KV: обычная Map плюс уважение к expirationTtl ---
function поддельныйKV() {
  const д = new Map();
  return {
    _д: д,
    async get(k) {
      const з = д.get(k);
      if (!з) return null;
      if (з.до && Date.now() > з.до) { д.delete(k); return null; }
      return з.v;
    },
    async put(k, v, о) {
      д.set(k, { v, до: о && о.expirationTtl ? Date.now() + о.expirationTtl * 1000 : 0 });
    }
  };
}

// worker.js написан модулем ES — превращаем export default в присваивание
const исходник = fs.readFileSync(__dirname + '/worker.js', 'utf8')
  .replace('export default', 'globalThis.ВОРКЕР =');

const песочница = { Response, Request, URL, JSON, Math, Date, Number, String, Array,
                    Object, console, TextEncoder, globalThis: null };
песочница.globalThis = песочница;
vm.createContext(песочница);
vm.runInContext(исходник, песочница, { filename: 'worker.js' });
const воркер = песочница.ВОРКЕР;

let всего = 0, провалов = 0;
function проверка(имя, условие, факт) {
  всего++;
  if (условие) console.log('  ОК     ' + имя);
  else { провалов++; console.log('  ПРОВАЛ ' + имя + (факт !== undefined ? '  -> ' + факт : '')); }
}
const раздел = (и) => console.log('\n' + и);

let env;
const адрес = (ip) => ({ 'CF-Connecting-IP': ip });

async function послать(тело, ip = '1.1.1.1') {
  const r = new Request('https://x/score', {
    method: 'POST', headers: адрес(ip), body: JSON.stringify(тело)
  });
  const о = await воркер.fetch(r, env);
  return { код: о.status, тело: await о.json() };
}
async function топ(n) {
  const r = new Request('https://x/top?n=' + (n || 10), { headers: адрес('1.1.1.1') });
  const о = await воркер.fetch(r, env);
  return { код: о.status, тело: await о.json() };
}
const забег = (ник, время, доп) => Object.assign({
  ник, время, уровень: Math.max(1, Math.round(время / 20)),
  убито: Math.round(время * 4), спасённых: Math.floor(время / 90), билд: 'ГАНТЕЛЯ 3'
}, доп || {});

(async () => {
  раздел('1. ЖИВОЙ И ОТВЕЧАЕТ');
  env = { RATING: поддельныйKV() };
  const з = await воркер.fetch(new Request('https://x/health'), env);
  проверка('ручка /health отвечает 200', з.status === 200, з.status);
  const нет = await воркер.fetch(new Request('https://x/чушь'), env);
  проверка('несуществующая ручка даёт 404', нет.status === 404, нет.status);
  const опции = await воркер.fetch(new Request('https://x/score', { method: 'OPTIONS' }), env);
  проверка('preflight CORS проходит', опции.status === 204, опции.status);
  проверка('CORS разрешает любой источник',
           опции.headers.get('Access-Control-Allow-Origin') === '*');

  раздел('2. ПРИЁМ РЕЗУЛЬТАТА И МЕСТО');
  env = { RATING: поддельныйKV() };
  let о = await послать(забег('ilya', 300));
  проверка('первый результат принят', о.код === 200, о.код + ' ' + JSON.stringify(о.тело));
  проверка('первый игрок — первое место', о.тело.место === 1, о.тело.место);
  проверка('всего игроков 1', о.тело.всего === 1, о.тело.всего);

  о = await послать(забег('leva2k', 200), '2.2.2.2');
  проверка('результат хуже — второе место', о.тело.место === 2, о.тело.место);
  о = await послать(забег('zzord', 400), '3.3.3.3');
  проверка('результат лучше всех — первое место', о.тело.место === 1, о.тело.место);
  проверка('всего игроков 3', о.тело.всего === 3, о.тело.всего);

  о = await послать(забег('d1pro4', 200), '4.4.4.4');
  проверка('одинаковое время — одинаковое место', о.тело.место === 3, о.тело.место);

  раздел('3. ОДНА СТРОКА НА НИК');
  env = { RATING: поддельныйKV() };
  await послать(забег('ilya', 100));
  await послать(забег('ilya', 300));
  await послать(забег('ilya', 200));
  let т = await топ(50);
  проверка('три забега одного ника — одна строка', т.тело.топ.length === 1, т.тело.топ.length);
  проверка('в строке лучший результат', т.тело.топ[0].время === 300, т.тело.топ[0].время);
  проверка('счётчик игроков не накрутился', т.тело.всего === 1, т.тело.всего);

  о = await послать(забег('ILYA', 350));
  т = await топ(50);
  проверка('регистр ника не плодит двойника', т.тело.топ.length === 1, т.тело.топ.length);
  проверка('лучший результат обновился', т.тело.топ[0].время === 350, т.тело.топ[0].время);

  раздел('4. ЧИСТКА НИКА');
  env = { RATING: поддельныйKV() };
  await послать(забег('', 100));
  т = await топ();
  проверка('пустой ник становится анонимом', т.тело.топ[0].ник === 'аноним', т.тело.топ[0].ник);

  env = { RATING: поддельныйKV() };
  await послать(забег('<script>alert(1)</script>', 100));
  т = await топ();
  проверка('теги вырезаются', !/[<>]/.test(т.тело.топ[0].ник), т.тело.топ[0].ник);

  env = { RATING: поддельныйKV() };
  await послать(забег('оченьдлинныйниккоторыйнелезет', 100));
  т = await топ();
  проверка('ник обрезан до 14 символов', т.тело.топ[0].ник.length <= 14,
           т.тело.топ[0].ник + ' (' + т.тело.топ[0].ник.length + ')');

  env = { RATING: поддельныйKV() };
  await послать(забег('ле​ва​2k', 100));
  т = await топ();
  проверка('невидимые символы вычищены', т.тело.топ[0].ник === 'лева2k', т.тело.топ[0].ник);

  env = { RATING: поддельныйKV() };
  await послать(забег('Дед Мороз', 100));
  т = await топ();
  проверка('нормальный русский ник с пробелом цел', т.тело.топ[0].ник === 'Дед Мороз', т.тело.топ[0].ник);

  раздел('5. ОТСЕВ ЧУШИ');
  env = { RATING: поддельныйKV() };
  const чушь = [
    ['время больше десяти минут', забег('чит', 99999)],
    ['отрицательное время',       забег('чит', -5)],
    ['время не число',            забег('чит', 'дохуя')],
    ['убитых больше физического', Object.assign(забег('чит', 10), { убито: 100000 })],
    ['уровень из воздуха',        Object.assign(забег('чит', 60), { уровень: 40, убито: 3 })],
    ['спасённых больше ивентов',  Object.assign(забег('чит', 60), { спасённых: 50 })]
  ];
  for (const [имя, тело] of чушь) {
    const р = await послать(тело, '9.9.9.' + Math.floor(Math.random() * 250));
    проверка('отклонено: ' + имя, р.код === 422, р.код + ' ' + JSON.stringify(р.тело));
  }
  т = await топ();
  проверка('ни одна подделка не попала в топ', т.тело.топ.length === 0, т.тело.топ.length);

  const кривой = await воркер.fetch(new Request('https://x/score', {
    method: 'POST', headers: адрес('8.8.8.8'), body: 'не json вообще'
  }), env);
  проверка('битое тело даёт 400, а не падение', кривой.status === 400, кривой.status);

  раздел('6. ЧАСТОТА ЗАПРОСОВ');
  env = { RATING: поддельныйKV() };
  let последний = 200;
  for (let n = 0; n < 12; n++) последний = (await послать(забег('спамер' + n, 100), '7.7.7.7')).код;
  проверка('после десяти запросов с адреса включается 429', последний === 429, последний);
  const другой = await послать(забег('честный', 100), '7.7.7.8');
  проверка('другому адресу это не мешает', другой.код === 200, другой.код);

  раздел('7. ОТДАЧА ТОПА');
  env = { RATING: поддельныйKV() };
  for (let n = 0; n < 25; n++) await послать(забег('игрок' + n, 100 + n), '5.5.5.' + n);
  т = await топ(10);
  проверка('по умолчанию отдаёт сколько попросили', т.тело.топ.length === 10, т.тело.топ.length);
  проверка('топ отсортирован по убыванию времени',
           т.тело.топ.every((р, i) => i === 0 || т.тело.топ[i - 1].время >= р.время));
  проверка('всего считает всех, а не только топ', т.тело.всего === 25, т.тело.всего);
  const много = await топ(9999);
  проверка('запрос ?n=9999 обрезан потолком', много.тело.топ.length <= 50, много.тело.топ.length);

  раздел('8. ПУСТОЙ СЕРВЕР');
  env = { RATING: поддельныйKV() };
  т = await топ();
  проверка('пустой топ не падает', т.код === 200 && т.тело.топ.length === 0, JSON.stringify(т.тело));

  env = { RATING: { async get(){ return 'это не json'; }, async put(){} } };
  т = await топ();
  проверка('битые данные в хранилище не роняют сервер', т.код === 200, т.код);

  раздел('9. РАВНОЕ ВРЕМЯ РАЗЛИЧАЕТСЯ УРОВНЕМ');
  env = { RATING: поддельныйKV() };
  // все трое дожили до конца — различать их может только уровень
  await послать(забег('слабый', 600, { уровень: 17, убито: 900 }), '7.7.7.1');
  await послать(забег('сильный', 600, { уровень: 52, убито: 2000 }), '7.7.7.2');
  await послать(забег('средний', 600, { уровень: 30, убито: 1200 }), '7.7.7.3');
  т = await топ(10);
  проверка('при равном времени топ упорядочен по уровню',
           т.тело.топ.map(р => р.ник).join(',') === 'сильный,средний,слабый',
           т.тело.топ.map(р => р.ник + ':' + р.уровень).join(' '));

  о = await послать(забег('новый', 600, { уровень: 40, убито: 1500 }), '7.7.7.4');
  проверка('место считается с учётом уровня, а не только времени',
           о.тело.место === 2, о.тело.место);

  // свою запись перебивает не только время, но и уровень при равном времени
  о = await послать(забег('слабый', 600, { уровень: 70, убито: 2500 }), '7.7.7.1');
  т = await топ(10);
  const слабый = т.тело.топ.find(р => р.ник === 'слабый');
  проверка('свой результат обновился по уровню при том же времени',
           слабый.уровень === 70, слабый && слабый.уровень);
  проверка('улучшение уровня поднимает в таблице',
           т.тело.топ[0].ник === 'слабый', т.тело.топ.map(р => р.ник).join(','));

  о = await послать(забег('слабый', 600, { уровень: 20, убито: 900 }), '7.7.7.1');
  т = await топ(10);
  проверка('худший уровень при том же времени свою запись не портит',
           т.тело.топ.find(р => р.ник === 'слабый').уровень === 70,
           т.тело.топ.find(р => р.ник === 'слабый').уровень);

  проверка('место совпадает с позицией строки в таблице',
           т.тело.топ.every((р, i) => i === 0 ||
             (т.тело.топ[i - 1].время > р.время ||
              (т.тело.топ[i - 1].время === р.время &&
               т.тело.топ[i - 1].уровень >= р.уровень))),
           т.тело.топ.map(р => р.время + '/' + р.уровень).join(' '));

  раздел('10. ХРАНИЛИЩЕ С ПОРЯДКОМ ОТ ПРЕЖНЕГО КОДА');
  /* Тот самый пропущенный случай. Правило «при равном времени выше уровень»
     приехало на сервер, а таблица не изменилась: в хранилище лежал список,
     отсортированный прежним кодом, и /top отдавал его как есть. Все прошлые
     проверки сначала ПОСЫЛАЛИ результат — а приём сортирует, поэтому баг
     ни в одну из них не попадал. */
  env = { RATING: поддельныйKV() };
  await env.RATING.put('топ', JSON.stringify([
    { ник: 'старый_первый', время: 600, уровень: 17, убито: 2332 },
    { ник: 'должен_быть_выше', время: 600, уровень: 55, убито: 2900 },
    { ник: 'середина', время: 600, уровень: 40, убито: 2800 }
  ]));
  await env.RATING.put('всего', '57');
  т = await топ(10);
  проверка('отдача сортирует то, что лежит в хранилище',
           т.тело.топ[0].ник === 'должен_быть_выше',
           т.тело.топ.map(р => р.ник + ':' + р.уровень).join(' '));
  проверка('порядок правильный целиком',
           т.тело.топ.map(р => р.ник).join(',') === 'должен_быть_выше,середина,старый_первый',
           т.тело.топ.map(р => р.ник).join(','));
  проверка('счётчик всего не потерялся', т.тело.всего === 57, т.тело.всего);
  // отдача ничего не должна переписывать: она только читает
  проверка('отдача не портит хранилище',
           JSON.parse(await env.RATING.get('топ')).length === 3);

  раздел('11. ЧИСЛО УБИТЫХ ПРОВЕРЯЕТСЯ ВСЕРЬЁЗ');
  /* Убитые стали третьим ключом сортировки, значит завышенное число теперь
     поднимает игрока в таблице. Прежний потолок 60 в секунду пропускал
     запись с 5000 убитых — она и висит в живом топе. */
  env = { RATING: поддельныйKV() };
  о = await послать(забег('честный', 600, { уровень: 25, убито: 2900 }), '8.8.8.1');
  проверка('настоящий результат за десять минут проходит', о.код === 200,
           о.код + ' ' + JSON.stringify(о.тело));
  о = await послать(забег('врун', 600, { уровень: 55, убито: 5000 }), '8.8.8.2');
  проверка('пять тысяч убитых за десять минут не принимаются', о.код === 422,
           о.код + ' ' + JSON.stringify(о.тело));
  о = await послать(забег('врун2', 30, { уровень: 20, убито: 900 }), '8.8.8.3');
  проверка('накрутка на коротком забеге не принимается', о.код === 422, о.код);
  о = await послать(забег('быстрый', 30, { уровень: 3, убито: 120 }), '8.8.8.4');
  проверка('бойкое начало короткого забега проходит', о.код === 200,
           о.код + ' ' + JSON.stringify(о.тело));
  т = await топ(10);
  проверка('врун в таблицу не попал',
           т.тело.топ.every(р => р.ник !== 'врун'),
           т.тело.топ.map(р => р.ник).join(','));

  раздел('12. НАКОПЛЕННАЯ ЧУШЬ НЕ ПОКАЗЫВАЕТСЯ');
  /* Пороги правдоподобия со временем меняются, а записи, прошедшие по
     прежним, остаются лежать. Пока порядок держался на одном времени, они
     просто висели в списке; когда убитые стали ключом сортировки, запись
     с 5000 убитых поехала бы на первое место. */
  env = { RATING: поддельныйKV() };
  await env.RATING.put('топ', JSON.stringify([
    { ник: 'накрутка', время: 600, уровень: 55, убито: 5000 },
    { ник: 'честный', время: 600, уровень: 25, убито: 2900 },
    { ник: 'тоже_честный', время: 600, уровень: 24, убито: 2700 }
  ]));
  т = await топ(10);
  проверка('накрутка из хранилища не отдаётся',
           т.тело.топ.every(р => р.ник !== 'накрутка'),
           т.тело.топ.map(р => р.ник).join(','));
  проверка('честные записи остались', т.тело.топ.length === 2, т.тело.топ.length);
  проверка('наверху честный лучший', т.тело.топ[0].ник === 'честный', т.тело.топ[0].ник);
  проверка('отсев не переписывает хранилище',
           JSON.parse(await env.RATING.get('топ')).length === 3);

  console.log('\n=== ' + (всего - провалов) + ' из ' + всего + ' проверок пройдено ===');
  process.exit(провалов ? 1 : 0);
})();
