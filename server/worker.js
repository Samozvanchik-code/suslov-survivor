/* ==========================================================================
   СЕРВЕР МИРОВОГО РЕЙТИНГА «СУСЛОВ: ВЫЖИВАЧ»
   Cloudflare Worker + KV. Бесплатного тарифа хватает с большим запасом.

   Три ручки:
     POST /score  — принять результат забега, вернуть место в мире
     GET  /top    — топ-N для экрана итогов
     GET  /health — жив ли, для проверки после деплоя

   Личность игрока — только ник. Никакой авторизации: это осознанный
   компромисс ради того, чтобы играли без регистрации. Отсюда два следствия,
   которые ниже и лечатся:
     1. Ники не уникальны — два разных человека могут взять один ник.
        Держим ОДНУ лучшую запись на ник: новый результат вытесняет старый
        того же ника, только если он лучше. Иначе топ забился бы одним
        человеком на десяти строках.
     2. Результат присылает браузер, значит его можно подделать руками.
        Полностью это лечится только просчётом забега на сервере, что для
        такой игры оверкилл. Здесь режем очевидную чушь проверками
        правдоподобия и частотой запросов с адреса.
   ========================================================================== */

const ДЛИНА_ЗАБЕГА = 600;          // 10 минут: дольше прожить нельзя, победа
const МАКС_В_ТОПЕ = 100;           // храним столько, отдаём сколько попросят
const МАКС_НИК = 14;               // столько же, сколько maxlength поля в игре
const МАКС_ОТДАЧИ = 50;            // потолок параметра ?n у ручки /top
const ОКНО_ЧАСТОТЫ = 60;           // сек
const ЗАПРОСОВ_В_ОКНО = 10;        // с одного адреса

const ЗАГОЛОВКИ = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  'Access-Control-Allow-Headers': 'Content-Type',
  'Cache-Control': 'no-store'
};

const ответ = (данные, код = 200) => new Response(JSON.stringify(данные), {
  status: код,
  headers: { 'Content-Type': 'application/json; charset=utf-8', ...ЗАГОЛОВКИ }
});

/* Ник чистим жёстко: он попадёт на экран другим игрокам. Оставляем буквы,
   цифры, пробел и несколько безобидных знаков — этого хватает для ников
   вроде «leva2k» и «Дед Мороз», но отсекает управляющие символы и попытки
   растянуть строку невидимыми пробелами. */
function чистыйНик(сырой) {
  let н = String(сырой == null ? '' : сырой).normalize('NFC');
  // невидимые символы: ими растягивают ник и ломают вёрстку таблицы
  н = н.replace(/[\u00ad\u200b-\u200f\u202a-\u202e\u2060\ufeff]/g, '');
  н = н.replace(/[^\p{L}\p{N} _.\-]/gu, '');
  н = н.replace(/\s+/g, ' ').trim();
  if (!н) н = 'аноним';
  return н.slice(0, МАКС_НИК);
}


/* Проверка правдоподобия. Не ловит умельца, который аккуратно подделает
   согласованный набор чисел, — ловит «9999 убитых за 3 секунды». Пороги
   с большим запасом вверх: лучше пропустить сомнительный рекорд, чем
   выкинуть честный. */
function похоженаПравду(р) {
  const время = Number(р.время);
  const уровень = Number(р.уровень);
  const убито = Number(р.убито);
  const спасённых = Number(р.спасённых || 0);

  if (![время, уровень, убито, спасённых].every(Number.isFinite)) return 'не число';
  if (время <= 0 || время > ДЛИНА_ЗАБЕГА + 1) return 'время вне диапазона';
  if (уровень < 1 || уровень > 90) return 'уровень вне диапазона';
  if (убито < 0 || убито > 60 * время) return 'убитых больше, чем успевает заспавниться';
  if (спасённых < 0 || спасённых > Math.ceil(время / 60)) return 'спасённых больше, чем было ивентов';
  // уровень растёт с опыта, опыт с убитых: 30 уровней на пустом счётчике не бывает
  if (уровень > 6 && убито < уровень * 2) return 'уровень не бьётся с числом убитых';
  return null;
}

async function прочитатьТоп(env) {
  const сырой = await env.RATING.get('топ');
  if (!сырой) return [];
  try {
    const т = JSON.parse(сырой);
    return Array.isArray(т) ? т : [];
  } catch (e) {
    return [];
  }
}

/* Порядок в топе: сначала время, при равном времени — уровень. Когда до
   конца доживают многие, одно время перестаёт различать игроков: у нескольких
   человек по десять минут при уровнях от 17 до 52.

   Такое же сравнение есть в engine.js (сравнитьРезультаты) для локального
   топа. Общего кода у них быть не может — воркер живёт отдельно и грузится
   не браузером; при правке править оба. */
function сравнитьРезультаты(a, b) {
  return (Number(b.время) - Number(a.время)) ||
         ((Number(b.уровень) || 0) - (Number(a.уровень) || 0));
}

/* Место считаем по СТРОГО лучшему результату: если у пятерых ровно 3:20 и
   ровно один уровень, все пятеро получают одно место, а не случайный
   порядок. Ключи те же и в том же порядке, что в сортировке, иначе место
   разойдётся с позицией строки в таблице. */
function местоВСписке(топ, запись) {
  let лучше = 0;
  for (const р of топ) if (сравнитьРезультаты(р, запись) < 0) лучше++;
  return лучше + 1;
}

async function принятьРезультат(request, env) {
  const адрес = request.headers.get('CF-Connecting-IP') || 'нет';

  // частота: дешёвая защита от скрипта, который льёт результаты пачкой
  const ключЧастоты = 'частота:' + адрес;
  const было = Number(await env.RATING.get(ключЧастоты)) || 0;
  if (было >= ЗАПРОСОВ_В_ОКНО) {
    return ответ({ ошибка: 'слишком часто' }, 429);
  }
  await env.RATING.put(ключЧастоты, String(было + 1), { expirationTtl: ОКНО_ЧАСТОТЫ });

  let тело;
  try {
    тело = await request.json();
  } catch (e) {
    return ответ({ ошибка: 'не json' }, 400);
  }

  const причина = похоженаПравду(тело);
  if (причина) return ответ({ ошибка: 'результат не принят', причина }, 422);

  const запись = {
    ник: чистыйНик(тело.ник),
    время: Math.round(Number(тело.время) * 10) / 10,
    уровень: Math.round(Number(тело.уровень)),
    убито: Math.round(Number(тело.убито)),
    спасённых: Math.round(Number(тело.спасённых || 0)),
    билд: String(тело.билд || '').slice(0, 120),
    дата: Date.now()
  };

  const топ = await прочитатьТоп(env);

  /* Одна строка на ник. Иначе один игрок за вечер занимает весь топ-10
     своими же забегами, и остальным туда не попасть — таблица перестаёт
     быть интересной всем, кроме него. */
  const свой = топ.findIndex(р => р.ник.toLowerCase() === запись.ник.toLowerCase());
  let улучшил = false;
  if (свой >= 0) {
    // «лучше» — по тем же ключам, что сортировка: время, потом уровень
    if (сравнитьРезультаты(запись, топ[свой]) < 0) { топ[свой] = запись; улучшил = true; }
  } else {
    топ.push(запись);
    улучшил = true;
  }

  топ.sort(сравнитьРезультаты);
  const обрезанный = топ.slice(0, МАКС_В_ТОПЕ);
  if (улучшил) await env.RATING.put('топ', JSON.stringify(обрезанный));

  /* Всего игроков — отдельный счётчик, а не длина топа: топ обрезан сотней,
     а «ты 47-й из 312» должно считаться от всех, кто вообще играл. */
  let всего = Number(await env.RATING.get('всего')) || 0;
  if (свой < 0) {
    всего += 1;
    await env.RATING.put('всего', String(всего));
  }

  const место = местоВСписке(обрезанный, запись);
  return ответ({
    место,
    всего: Math.max(всего, обрезанный.length),
    вТопе: место <= обрезанный.length,
    лучшийСвой: (свой >= 0 ? обрезанный.find(р => р.ник.toLowerCase() === запись.ник.toLowerCase()) : запись).время
  });
}

async function отдатьТоп(request, env) {
  const url = new URL(request.url);
  const сколько = Math.min(Math.max(Number(url.searchParams.get('n')) || 10, 1), МАКС_ОТДАЧИ);
  const топ = await прочитатьТоп(env);
  const всего = Number(await env.RATING.get('всего')) || топ.length;
  return ответ({ топ: топ.slice(0, сколько), всего });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (request.method === 'OPTIONS') {
      return new Response(null, { status: 204, headers: ЗАГОЛОВКИ });
    }
    if (url.pathname === '/health') {
      return ответ({ живой: true, время: new Date().toISOString() });
    }
    if (url.pathname === '/score' && request.method === 'POST') {
      try {
        return await принятьРезультат(request, env);
      } catch (e) {
        return ответ({ ошибка: 'внутренняя', текст: String(e && e.message) }, 500);
      }
    }
    if (url.pathname === '/top' && request.method === 'GET') {
      try {
        return await отдатьТоп(request, env);
      } catch (e) {
        return ответ({ ошибка: 'внутренняя', текст: String(e && e.message) }, 500);
      }
    }
    return ответ({ ошибка: 'нет такой ручки' }, 404);
  }
};
