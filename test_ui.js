/* Проверки интерфейса: подпись версии, экран изменений, мировой рейтинг.
   Рисование идёт в заглушку канваса — здесь важно не «как выглядит»,
   а что экраны не падают, кнопки регистрируются и клики срабатывают.
   Запуск: node test_ui.js */

const { поднять } = require('./test_env.js');
/* Поднимаем с ПУСТЫМ адресом рейтинга: этот набор проверяет, что игра
   полноценно живёт без сервера. Стык с живым сервером — test_integration.js. */
const { песочница, S, ИГРА } = поднять({ адресРейтинга: '' });

let всего = 0, провалов = 0;
function проверка(имя, условие, факт) {
  всего++;
  if (условие) console.log('  ОК     ' + имя);
  else { провалов++; console.log('  ПРОВАЛ ' + имя + (факт !== undefined ? '  -> ' + факт : '')); }
}
const раздел = (и) => console.log('\n' + и);

const кнопки = () => S.кнопки();
function кликнуть(x, y) {
  S.мышь.x = x; S.мышь.y = y; S.мышь.клик = true;
  S.обработатьКлик();
}

раздел('1. ВЕРСИЯ И ЧЕНДЖЛОГ — ДАННЫЕ');
проверка('версия задана строкой', typeof S.ВЕРСИЯ === 'string' && S.ВЕРСИЯ.length > 0, S.ВЕРСИЯ);
проверка('список изменений не пуст', S.ИЗМЕНЕНИЯ.length > 0, S.ИЗМЕНЕНИЯ.length);
проверка('верхняя запись совпадает с текущей версией',
         S.ИЗМЕНЕНИЯ[0].версия === S.ВЕРСИЯ, S.ИЗМЕНЕНИЯ[0].версия + ' vs ' + S.ВЕРСИЯ);
проверка('у каждой записи есть дата, заголовок и пункты',
         S.ИЗМЕНЕНИЯ.every(и => и.дата && и.заголовок && Array.isArray(и.пункты) && и.пункты.length));
const версии = S.ИЗМЕНЕНИЯ.map(и => и.версия);
проверка('версии не повторяются', new Set(версии).size === версии.length, версии.join(', '));
проверка('версии идут от новых к старым',
         версии.every((в, i) => i === 0 || parseFloat(версии[i - 1]) > parseFloat(в)), версии.join(' > '));

раздел('2. ПОДПИСЬ ВЕРСИИ КЛИКАБЕЛЬНА');
ИГРА.экран = 'старт';
S.экранСтарта();
S.нарисоватьВерсию();
const кнопкаВерсии = кнопки()[кнопки().length - 1];
проверка('подпись версии добавила кнопку', !!кнопкаВерсии);
проверка('кнопка в левом нижнем углу',
         кнопкаВерсии.x < 40 && кнопкаВерсии.y > 300,
         'x=' + Math.round(кнопкаВерсии.x) + ' y=' + Math.round(кнопкаВерсии.y));
проверка('кнопка не перекрывает пол-экрана', кнопкаВерсии.ш < 120 && кнопкаВерсии.в < 40,
         кнопкаВерсии.ш + 'x' + кнопкаВерсии.в);

кликнуть(кнопкаВерсии.x + 2, кнопкаВерсии.y + 2);
проверка('клик открывает список изменений', ИГРА.экран === 'изменения', ИГРА.экран);
проверка('запомнили, откуда пришли', ИГРА.экранДоИзменений === 'старт', ИГРА.экранДоИзменений);

раздел('3. ЭКРАН ИЗМЕНЕНИЙ');
let упал = null;
try { S.экранИзменений(); } catch (e) { упал = e.message; }
проверка('экран рисуется без ошибок', !упал, упал);
проверка('высота содержимого посчитана', ИГРА.высотаИзменений > 0, ИГРА.высотаИзменений);
проверка('на экране есть кнопка НАЗАД', кнопки().length >= 1, кнопки().length);

// прокрутка
ИГРА.прокруткаИзменений = 0;
S.прокрутитьИзменения(-500);
проверка('вверх за начало не уезжает', ИГРА.прокруткаИзменений === 0, ИГРА.прокруткаИзменений);
S.прокрутитьИзменения(100);
const послеПрокрутки = ИГРА.прокруткаИзменений;
проверка('прокрутка вниз работает', послеПрокрутки > 0, послеПрокрутки);
S.прокрутитьИзменения(100000);
S.экранИзменений();
проверка('вниз за конец не уезжает',
         ИГРА.прокруткаИзменений <= Math.max(0, ИГРА.высотаИзменений),
         ИГРА.прокруткаИзменений + ' при высоте ' + ИГРА.высотаИзменений);

// закрытие
S.нажатие('Escape');
проверка('Escape возвращает на прошлый экран', ИГРА.экран === 'старт', ИГРА.экран);

// возврат работает и с экрана итогов
ИГРА.экран = 'итоги';
S.открытьИзменения();
S.закрытьИзменения();
проверка('с итогов возвращает на итоги', ИГРА.экран === 'итоги', ИГРА.экран);

раздел('4. ГОРЯЧИЕ КЛАВИШИ НЕ ПРОТЕКАЮТ');
ИГРА.экран = 'изменения';
S.нажатие('Enter');
проверка('Enter на экране изменений закрывает, а не стартует забег',
         ИГРА.экран !== 'бой', ИГРА.экран);

раздел('5. МИРОВОЙ РЕЙТИНГ НА ЭКРАНЕ ИТОГОВ');
S.начатьЗабег();
ИГРА.время = 200; ИГРА.уровень = 9; ИГРА.убито = 300;
ИГРА.экран = 'итоги';

// сервер не отвечал — экран обязан работать как раньше
ИГРА.мировойСтатус = 'недоступен';
ИГРА.мировойТоп = [];
упал = null;
try { S.экранИтогов(); } catch (e) { упал = e.message; }
проверка('без сервера экран итогов цел', !упал, упал);

// сервер ответил
ИГРА.мировойСтатус = 'есть';
ИГРА.мировоеМесто = 47;
ИГРА.мировоВсего = 312;
ИГРА.мировойТоп = [];
for (let i = 0; i < 10; i++) {
  ИГРА.мировойТоп.push({ ник: 'игрок' + i, время: 500 - i * 20, уровень: 20 - i, спасённых: 2 });
}
упал = null;
try { S.экранИтогов(); } catch (e) { упал = e.message; }
проверка('с мировым топом экран итогов цел', !упал, упал);

// первое место — отдельная надпись
ИГРА.мировоеМесто = 1;
упал = null;
try { S.экранИтогов(); } catch (e) { упал = e.message; }
проверка('первое место рисуется без ошибок', !упал, упал);

// узкий экран (телефон)
const шБыло = песочница.window.innerWidth, вБыло = песочница.window.innerHeight;
песочница.window.innerWidth = 390; песочница.window.innerHeight = 844;
vmПересчёт();
упал = null;
try { S.экранИтогов(); S.экранИзменений(); } catch (e) { упал = e.message; }
проверка('на телефоне оба экрана целы', !упал, упал);
песочница.window.innerWidth = шБыло; песочница.window.innerHeight = вБыло;
vmПересчёт();

function vmПересчёт() {
  const vm = require('vm');
  vm.runInContext('пересчитатьРазмер();', песочница, { filename: 'пересчёт.js' });
}

раздел('6. ОТПРАВКА НА СЕРВЕР НЕ РОНЯЕТ ИГРУ');
// адрес не задан — обычный режим, работает локально
S.начатьЗабег();
ИГРА.время = 100;
упал = null;
try {
  S.отправитьРезультат({ ник: 'тест', время: 100, уровень: 5, убито: 50, спасённых: 0, билд: '' });
} catch (e) { упал = e.message; }
проверка('без адреса рейтинга отправка молчит и не падает', !упал, упал);
проверка('локальная таблица всё равно пишется', ИГРА.таблица.length > 0, ИГРА.таблица.length);
проверка('статус мирового рейтинга — выключен', ИГРА.мировойСтатус === 'выключен', ИГРА.мировойСтатус);

console.log('\n=== ' + (всего - провалов) + ' из ' + всего + ' проверок пройдено ===');
process.exit(провалов ? 1 : 0);
