/* Замер уровней за полный забег. Браузер не нужен.
   Запуск: node bench_levels.js
   Переменные: ПРОГОНОВ (по умолчанию 5), ДО (секунд забега, по умолчанию 600)

   Зачем: в мировом топе у людей с одинаковыми десятью минутами уровни от 1
   до 55. Пока время различало игроков, это было не видно; теперь уровень —
   второй ключ сортировки, и разброс в пятьдесят уровней означает, что
   таблицу выигрывает не тот, кто лучше играл, а тот, кто взял карту опыта.

   Мерим ДВЕ стратегии, потому что жалоба именно про разрыв между ними:

     случайный — берёт что попало. Это нижняя граница, «обычный игрок».
     опыт      — всегда предпочитает карты на опыт и на радиус сбора.
                 Это верхняя граница, те самые пятьдесят уровней.

   Смотреть надо на РАЗРЫВ между стратегиями, а не на средний уровень:
   именно он показывает, насколько уровень измеряет игру, а не одну карту.
*/

const { поднять } = require('./test_env.js');

const ШАГ = 1 / 60;
const ПРОГОНОВ = Number(process.env.ПРОГОНОВ || 5);
const ДО = Number(process.env.ДО || 600);

// карты, которые прямо или косвенно ускоряют набор опыта
const ОПЫТНЫЕ = ['mishlenie', 'prichoska', 'lyuks'];

function выбрать(S, ИГРА, стратегия) {
  const карточки = ИГРА.карточки;
  if (стратегия === 'опыт') {
    const i = карточки.findIndex(к => к.апгрейд && ОПЫТНЫЕ.includes(к.апгрейд.ид));
    if (i >= 0) return i;
  }
  return Math.floor(Math.random() * карточки.length);
}

function прогон(стратегия) {
  const { S, ИГРА } = поднять({ адресРейтинга: '' });
  S.начатьЗабег();
  const и = ИГРА.игрок;
  let угол = 0;
  const кадров = Math.round(ДО * 60);

  for (let к = 0; к < кадров; к++) {
    угол += 0.02;
    и.hp = и.максHp; и.неуязвим = 999;      // мерим набор опыта, а не выживание
    S.клавиши.KeyW = Math.sin(угол) < -0.3;
    S.клавиши.KeyS = Math.sin(угол) > 0.3;
    S.клавиши.KeyA = Math.cos(угол) < -0.3;
    S.клавиши.KeyD = Math.cos(угол) > 0.3;
    S.шагЛогики(ШАГ);
    while (ИГРА.экран === 'левелап' && ИГРА.карточки.length) {
      S.взятьКарточку(выбрать(S, ИГРА, стратегия));
      if (ИГРА.экран === 'замена') S.заменитьСоюзника(0);
    }
    if (ИГРА.экран !== 'бой') ИГРА.экран = 'бой';
  }

  const опытные = ОПЫТНЫЕ
    .filter(ид => и.апгрейды[ид])
    .map(ид => ид + ' ' + и.апгрейды[ид]).join(', ') || 'нет';

  return {
    уровень: ИГРА.уровень,
    опытВсего: Math.round(ИГРА.опытВсего),
    множитель: Math.round(и.множительОпыта * 100) / 100,
    убито: ИГРА.убито,
    опытные
  };
}

console.log('Замер уровней: ' + ПРОГОНОВ + ' прогонов на стратегию, забег ' + ДО + ' сек.\n');

const итоги = {};
for (const стратегия of ['случайный', 'опыт']) {
  console.log('=== стратегия: ' + стратегия);
  const уровни = [];
  for (let n = 0; n < ПРОГОНОВ; n++) {
    const р = прогон(стратегия);
    уровни.push(р.уровень);
    console.log('  уровень ' + String(р.уровень).padStart(3) +
                '   опыта ' + String(р.опытВсего).padStart(6) +
                '   множитель x' + р.множитель +
                '   убито ' + р.убито +
                '   карты опыта: ' + р.опытные);
  }
  уровни.sort((a, b) => a - b);
  const мед = уровни[Math.floor(уровни.length / 2)];
  итоги[стратегия] = мед;
  console.log('  медиана ' + мед + ', разброс ' + уровни[0] + '-' + уровни[уровни.length - 1] + '\n');
}

const разрыв = итоги['опыт'] - итоги['случайный'];
console.log('РАЗРЫВ между стратегиями: ' + разрыв + ' уровней' +
            ' (x' + (Math.round(итоги['опыт'] / Math.max(итоги['случайный'], 1) * 100) / 100) + ')');
console.log(разрыв > 12
  ? 'ШИРОКО: уровень измеряет карту опыта, а не игру.'
  : 'в норме: карта опыта помогает, но не решает.');
