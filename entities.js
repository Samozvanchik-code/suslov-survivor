function запуститьИвент(ключ) {
  const д = ДОНАТЕРЫ[ключ];
  if (!д) return;
  const и = ИГРА.игрок;
  const угол = случ(0, ДВА_ПИ);
  const r = случ(ИВЕНТ.дистанцияОт, ИВЕНТ.дистанцияДо);
  const кx = и.x + Math.cos(угол) * r, кy = и.y + Math.sin(угол) * r;

  const клетка = {
    ключ, донатер: д, x: кx, y: кy,
    осталось: ИВЕНТ.времяНаСпасение,
    прогресс: 0, взламывается: false,
    таймерПодкрепления: ИВЕНТ.подкреплениеРаз,
    пробуждён: false, открыта: false, тает: 0,
    фаза: случ(0, ДВА_ПИ)
  };
  ИГРА.клетка = клетка;
  ИГРА.занятыеДонатеры.push(ключ);

  // гарнизон стоит постом вокруг клетки и не преследует, пока игрок не вошёл
  const сколько = Math.round(случ(ИВЕНТ.гарнизонОт, ИВЕНТ.гарнизонДо)) * (д.злее || 1);
  for (let n = 0; n < сколько; n++) {
    const у = (n / сколько) * ДВА_ПИ + случ(-0.15, 0.15);
    const рп = случ(90, 210);
    const пx = кx + Math.cos(у) * рп, пy = кy + Math.sin(у) * рп;
    const тип = д.злее ? изМассива(['anon', 'anon', 'zhirniy', 'maska']) : изМассива(['anon', 'anon', 'anon', 'meloch']);
    создатьВрага(тип, ВРАГИ[тип], { x: пx, y: пy }, {
      гарнизон: клетка, постX: пx, постY: пy, спит: true
    });
  }
  звук('спасение', 0.7);
}

function обновитьРасписаниеИвентов(дт) {
  const и = ИГРА.игрок;

  // Пока жив босс — откладываем. Игрок не должен разрываться между двумя
  // обязательными делами, зная, что не успеет ни одного.
  if (ИГРА.босс && !ИГРА.босс.мёртв) { ИГРА.пауза_после_босса = ИВЕНТ.задержкаПослеБосса; return; }
  if (ИГРА.пауза_после_босса > 0) { ИГРА.пауза_после_босса -= дт; return; }
  if (ИГРА.клетка) return;

  // galiopola выходит на 330-й: по ТЗ около пятой минуты, но там Шварц,
  // поэтому сразу после него.
  if (!ИГРА.былаGaliopola && ИГРА.время >= 330) {
    ИГРА.былаGaliopola = true;
    ИГРА.таймерИвента = ИВЕНТ.интервал;
    запуститьИвент('galiopola');
    return;
  }

  ИГРА.таймерИвента -= дт;
  if (ИГРА.таймерИвента > 0) return;
  ИГРА.таймерИвента = ИВЕНТ.интервал;
  const пул = свободныеДонатеры();
  if (пул.length) запуститьИвент(изМассива(пул));
}

function обновитьКлетку(дт) {
  const к = ИГРА.клетка;
  if (!к) return;
  const и = ИГРА.игрок;
  к.фаза += дт * 2;

  if (к.тает > 0) {                       // провалили: клетка растворяется
    к.тает -= дт;
    if (к.тает <= 0) ИГРА.клетка = null;
    return;
  }
  if (к.открыта) { ИГРА.клетка = null; return; }

  к.осталось -= дт;
  if (к.осталось <= 0) { провалитьИвент(к); return; }

  if (!к.пробуждён && дистанция(и.x, и.y, к.x, к.y) < ИВЕНТ.радиусПробуждения) {
    к.пробуждён = true;
    for (const в of ИГРА.враги) if (в.гарнизон === к) в.спит = false;
  }

  // остался ли кто из гарнизона
  let живГарнизон = 0;
  for (const в of ИГРА.враги) if (в.гарнизон === к && в.гаснет <= 0) живГарнизон++;

  const вКруге = дистанция(и.x, и.y, к.x, к.y) < ИВЕНТ.радиусВзлома;
  к.взламывается = вКруге && живГарнизон === 0;

  if (к.взламывается) {
    к.прогресс += дт;
    // пока стоишь — прёт подкрепление, и прёт ОТ КЛЕТКИ, чтобы видно откуда
    к.таймерПодкрепления -= дт;
    if (к.таймерПодкрепления <= 0) {
      к.таймерПодкрепления = ИВЕНТ.подкреплениеРаз;
      const сколько = 3;
      for (let n = 0; n < сколько; n++) {
        const у = случ(0, ДВА_ПИ);
        создатьВрага('anon', ВРАГИ.anon,
          { x: к.x + Math.cos(у) * 40, y: к.y + Math.sin(у) * 40 },
          { встаёт: 0.35 });
      }
      брызги(к.x, к.y, '#8e8a9c', 8);
    }
    if (к.прогресс >= ИВЕНТ.времяВзлома) спастиДонатера(к);
  } else if (к.прогресс > 0) {
    // откат плавный: случайный шаг в сторону не должен обнулять четыре секунды
    к.прогресс = Math.max(0, к.прогресс - дт * ИВЕНТ.скоростьОтката);
  }
}

