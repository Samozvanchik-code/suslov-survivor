/* Общий множитель урона: очки, ПРАЙМ и режим Шварца. */
function боевойМножитель(и) {
  return и.множительУрона
       * (и.уронЗаУровни || 1)
       * (и.праймОсталось > 0 ? 2 : 1)
       * (и.шварц > 0 ? ЧЕРЕП.урон : 1)
       * (и.баффБелуги > 0 ? 1 + БЕЛУГА.баффУрона : 1);
}

function ближайшийВраг(x, y, максД) {
  let лучший = null, лучшаяД = максД !== undefined ? максД : Infinity;
  for (const в of ИГРА.враги) {
    if (в.гаснет > 0) continue;               // вытесняемого не берём в прицел
    const д = дистанция(x, y, в.x, в.y);
    if (д < лучшаяД) { лучшаяД = д; лучший = в; }
  }
  return лучший;
}

// --- ГАНТЕЛЯ ---
function бросокГантели() {
  const и = ИГРА.игрок;
  const ур = и.апгрейды.gantelya || 1;
  const к = ГАНТЕЛЯ.уровни[ур - 1];

  const цель = ближайшийВраг(и.x, и.y - и.в * 0.4);
  const дальность = к.дальность * и.множительДальности;
  const сy = и.y - и.в * 0.55;

  /* Целимся в точку перехвата, а не в текущее положение врага.
     Дрищ на скорости 320 успевал уйти из точки броска, и гантеля
     пролетала мимо — он выглядел неубиваемым. */
  let угол;
  if (цель) угол = уголПерехвата(и.x, сy, цель, дальность);
  else угол = Math.atan2(и.напрY, и.напрX);
  const разлёт = (к.разлёт * Math.PI) / 180;
  const старт = -(к.штук - 1) / 2;

  for (let n = 0; n < к.штук; n++) {
    const а = угол + (старт + n) * разлёт;
    ИГРА.гантели.push({
      x: и.x, y: сy,
      углX: Math.cos(а), углY: Math.sin(а),
      скорость: ГАНТЕЛЯ.скоростьБроска,
      // равномерное торможение до нуля ровно на заданной дальности
      замедление: (ГАНТЕЛЯ.скоростьБроска * ГАНТЕЛЯ.скоростьБроска) / (2 * дальность),
      возвратX: к.возвратX,
      урон: к.урон,
      поворот: случ(0, 6.28),
      фаза: 'вперёд',
      задетые: new Map(),        // ид врага -> сколько ждать до следующего урона
      жизнь: 6
    });
  }
  и.сторона = Math.cos(угол) < 0 ? -1 : 1;
  звук('бросок', случ(0.95, 1.08));
}

/* Сколько летит гантеля до расстояния d. Она тормозит равномерно
   от скоростиБроска до нуля ровно на дальности D, значит
   d = v0*t - a*t^2/2 при a = v0^2/(2D). Обращаем и берём меньший корень. */
function времяПолёта(d, дальность) {
  const v0 = ГАНТЕЛЯ.скоростьБроска;
  const a = (v0 * v0) / (2 * дальность);
  const под = v0 * v0 - 2 * a * d;
  if (под <= 0) return v0 / a;                 // дальше не достаёт — берём полный разгон
  return (v0 - Math.sqrt(под)) / a;
}

function уголПерехвата(отX, отY, цель, дальность) {
  const цy = цель.y - цель.высотаСпрайта * 0.45;
  let тx = цель.x, тy = цy;
  const vx = цель.скорX || 0, vy = цель.скорY || 0;
  // две итерации хватает: сходится быстро, а цель всё равно виляет
  for (let i = 0; i < 2; i++) {
    const t = времяПолёта(дистанция(отX, отY, тx, тy), дальность);
    тx = цель.x + vx * t;
    тy = цy + vy * t;
  }
  return Math.atan2(тy - отY, тx - отX);
}

function обновитьГантели(дт) {
  const и = ИГРА.игрок;
  const г = габариты('weapon_gantelya');
  const радиусГантели = Math.max(г.ш, г.в) * 0.42;

  for (let i = ИГРА.гантели.length - 1; i >= 0; i--) {
    const гн = ИГРА.гантели[i];
    гн.поворот += дт * ГАНТЕЛЯ.вращение;
    гн.жизнь -= дт;

    if (гн.фаза === 'вперёд') {
      гн.скорость -= гн.замедление * дт;
      if (гн.скорость <= 0) { гн.скорость = 0; гн.фаза = 'назад'; }
      гн.x += гн.углX * гн.скорость * дт;
      гн.y += гн.углY * гн.скорость * дт;
    } else {
      // догоняет игрока по его ТЕКУЩЕЙ позиции, разгоняясь
      const цx = и.x, цy = и.y - и.в * 0.55;
      const д = дистанция(гн.x, гн.y, цx, цy) || 1;
      гн.скорость = Math.min(гн.скорость + 1400 * дт,
                             ГАНТЕЛЯ.скоростьВозврата * гн.возвратX);
      гн.x += ((цx - гн.x) / д) * гн.скорость * дт;
      гн.y += ((цy - гн.y) / д) * гн.скорость * дт;
      if (д < 34) { ИГРА.гантели.splice(i, 1); continue; }
    }

    if (гн.жизнь <= 0) { ИГРА.гантели.splice(i, 1); continue; }

    // остывание по каждому задетому врагу
    for (const [ид, т] of гн.задетые) {
      const н = т - дт;
      if (н <= 0) гн.задетые.delete(ид); else гн.задетые.set(ид, н);
    }

    // попадания: гантеля пробивает насквозь и врагов не толкает
    for (let j = ИГРА.враги.length - 1; j >= 0; j--) {
      const в = ИГРА.враги[j];
      if (в.гаснет > 0 || гн.задетые.has(в.ид)) continue;
      const вцy = в.y - в.высотаСпрайта * 0.45;
      if (Math.abs(гн.x - в.x) < (радиусГантели + в.ш * 0.5) &&
          Math.abs(гн.y - вцy) < (радиусГантели + в.в * 0.6)) {

        let урон = гн.урон * боевойМножитель(и);
        if (гн.фаза === 'назад' && гн.возвратX > 1) урон *= 2;
        const крит = и.шансКрита > 0 && Math.random() < и.шансКрита;
        if (крит) урон *= и.множительКрита;

        const былЖирный = в.шаблон.hp >= 40;
        уронВрагу(в, урон, гн.x, гн.y);
        /* Кулдаун ставим ПОСЛЕ удара. Раньше он взводился до вызова и
           поэтому съедался заблокированным попаданием в лоб: возвратный
           заход гантели по спине маски приходился ровно на этот кулдаун
           и пропадал. Из-за этого маска и была неубиваемой. */
        гн.задетые.set(в.ид, ГАНТЕЛЯ.кулдаунПоВрагу);
        if (крит) всплывашка(в.x, вцy - 26, 'КРИТ', ЦВЕТ.золото, 18);
        // бросок должен быть весомым: по жирному экран вздрагивает
        if (былЖирный) ИГРА.тряска = Math.max(ИГРА.тряска, 5);
      }
    }
  }
}

// --- КРИК ---
function крикнуть() {
  const и = ИГРА.игрок;
  const ур = и.апгрейды.krik;
  const к = КРИК.уровни[ур - 1];
  const радиус = к.радиус * и.множительДальности;
  const цy = и.y - и.в * 0.45;

  ИГРА.кольца.push({ x: и.x, y: цy, r: 20, макс: радиус, жизнь: 0.42, всего: 0.42 });
  ИГРА.тряска = Math.max(ИГРА.тряска, 4);
  звук('крик');

  for (let j = ИГРА.враги.length - 1; j >= 0; j--) {
    const в = ИГРА.враги[j];
    if (в.гаснет > 0) continue;
    const д = дистанция(в.x, в.y, и.x, и.y);
    if (д > радиус) continue;
    const урон = к.урон * боевойМножитель(и);
    уронВрагу(в, урон, и.x, и.y - и.в * 0.45);
    if (!в.мёртв) {
      const нx = (в.x - и.x) / (д || 1), нy = (в.y - и.y) / (д || 1);
      в.оттолкX += нx * к.отброс; в.оттолкY += нy * к.отброс;
    }
  }
}

function обновитьКольца(дт) {
  for (let i = ИГРА.кольца.length - 1; i >= 0; i--) {
    const к = ИГРА.кольца[i];
    к.жизнь -= дт;
    const доля = 1 - к.жизнь / к.всего;
    к.r = 20 + (к.макс - 20) * (1 - Math.pow(1 - доля, 2));   // рывком наружу, потом плавно
    if (к.жизнь <= 0) ИГРА.кольца.splice(i, 1);
  }
}

/* ==========================================================================
   ТЕЛЕГРАФЫ И СНАРЯДЫ БОССОВ

   Телеграф — это заранее показанная область удара: замах, видимая зона,
   потом урон. Без него босс отличается от жирного анона только полоской hp,
   и чат прямым текстом писал «он ни хуя не делает, просто умирает».

   Телеграф живёт СВОИМ списком, а не полем врага. Причина: удар обязан
   дойти, даже если босса добили на замахе. Иначе игрок учится не уходить
   из зоны, а дожимать урон, и телеграф перестаёт быть выбором — а он и есть
   единственное, что делает босса боссом.
   ========================================================================== */

/* Область по игроку. Круг — по расстоянию до центра, полоса — по проекции
   на отрезок: у полосы есть длина и ширина, и «внутри» считается честно,
   а не «в радиусе от середины». */
function точкаВЗоне(з, x, y) {
  if (з.вид === 'круг') return дистанция(x, y, з.x, з.y) <= з.радиус;
  const дx = з.доX - з.x, дy = з.доY - з.y;
  const длина2 = дx * дx + дy * дy;
  if (длина2 < 1e-6) return дистанция(x, y, з.x, з.y) <= з.ширина / 2;
  // t — где на отрезке ближайшая точка, зажатая концами
  const t = зажать(((x - з.x) * дx + (y - з.y) * дy) / длина2, 0, 1);
  return дистанция(x, y, з.x + дx * t, з.y + дy * t) <= з.ширина / 2;
}

/* Завести телеграф. Замах насильно не короче ТЕЛЕГРАФ.минЗамах: 0.6 сек —
   порог, на котором человек успевает увидеть зону и выйти. */
function завестиТелеграф(о) {
  const т = Object.assign({
    вид: 'круг', x: 0, y: 0, радиус: 100, доX: 0, доY: 0, ширина: 100,
    урон: 1, подпись: '', источник: null, послеУдара: null
  }, о);
  т.всего = Math.max(ТЕЛЕГРАФ.минЗамах, о.замах || ТЕЛЕГРАФ.минЗамах);
  т.замах = т.всего;
  ИГРА.телеграфы.push(т);
  return т;
}

function обновитьТелеграфы(дт) {
  for (let i = ИГРА.телеграфы.length - 1; i >= 0; i--) {
    const т = ИГРА.телеграфы[i];
    т.замах -= дт;
    if (т.замах > 0) continue;
    ИГРА.телеграфы.splice(i, 1);
    сработатьТелеграф(т);
  }
}

function сработатьТелеграф(т) {
  const и = ИГРА.игрок;
  ИГРА.тряска = Math.max(ИГРА.тряска, 9);
  звук('крик', 0.5);

  if (т.вид === 'круг') {
    ИГРА.кольца.push({
      x: т.x, y: т.y, r: 24, макс: т.радиус,
      жизнь: 0.32, всего: 0.32, цвет: ТЕЛЕГРАФ.цветЗоны
    });
    брызги(т.x, т.y, '#ff8a5a', 14);
  } else {
    // полоса: пыль по её длине, иначе удар не читается как прошедший
    const шагов = 5;
    for (let n = 0; n <= шагов; n++) {
      const д = n / шагов;
      брызги(т.x + (т.доX - т.x) * д, т.y + (т.доY - т.y) * д, '#ff8a5a', 4);
    }
  }

  if (и && !и.мёртв && точкаВЗоне(т, и.x, и.y)) ранитьИгрока(т.урон, т.источник);
  if (т.послеУдара) т.послеУдара(т);
}

/* Прямой снаряд. Не наводится намеренно: наводящийся снаряд от босса,
   который и так давит, читается как несправедливость, а не как атака. */
function запуститьСнаряд(x, y, угол, о) {
  о = о || {};
  const скорость = о.скорость || СНАРЯД.скорость;
  ИГРА.снаряды.push({
    x, y,
    скорX: Math.cos(угол) * скорость,
    скорY: Math.sin(угол) * скорость,
    радиус: о.радиус || СНАРЯД.радиус,
    урон: о.урон !== undefined ? о.урон : СНАРЯД.урон,
    жизнь: о.жизнь || СНАРЯД.жизнь,
    поворот: случ(0, ДВА_ПИ),
    вращение: случ(-8, 8),
    вид: о.вид || 'кусок',
    источник: о.источник || null
  });
}

function обновитьСнаряды(дт) {
  const и = ИГРА.игрок;
  for (let i = ИГРА.снаряды.length - 1; i >= 0; i--) {
    const с = ИГРА.снаряды[i];
    с.x += с.скорX * дт;
    с.y += с.скорY * дт;
    с.поворот += с.вращение * дт;
    с.жизнь -= дт;
    if (с.жизнь <= 0) { ИГРА.снаряды.splice(i, 1); continue; }
    if (и && !и.мёртв &&
        дистанция(с.x, с.y, и.x, и.y - и.в * 0.35) < с.радиус + и.ш * 0.4) {
      ранитьИгрока(с.урон, с.источник);
      брызги(с.x, с.y, '#ff7a45', 8);
      ИГРА.снаряды.splice(i, 1);
    }
  }
}

/* ==========================================================================
   ПОВЕДЕНИЕ БОССОВ

   Возвращает true, если босс занят замахом или рывком — тогда общий код
   движения врагов этот кадр пропускается. Стоять на замахе обязательно:
   стоящий босс и есть предупреждение, а босс, который замахивается на бегу,
   не даёт разорвать дистанцию.

   Ориентир по hp — не абсолютные числа, а время жизни: 20–35 секунд при
   среднем билде своей минуты. Меньше 20 — не ощущается боссом, больше 35 —
   становится скучным. Замеряется автопилотом, см. bench_boss.js.
   ========================================================================== */
function обновитьБосса(в, дт) {
  const ш = в.шаблон;
  if (!ш.атака) return false;
  const и = ИГРА.игрок;

  // Переход во вторую фазу на половине hp
  if (!в.фаза2 && ш.фаза2 && в.hp <= в.максHp * 0.5) {
    в.фаза2 = true;
    в.таймерАтаки = Math.min(в.таймерАтаки || 0, 1.2);   // не сразу, но скоро
    в.таймерЗалпа = ш.фаза2.интервалЗалпа || 0;
    ИГРА.тряска = Math.max(ИГРА.тряска, 13);
    ИГРА.вспышкаЭкрана = Math.max(ИГРА.вспышкаЭкрана, 0.35);
    звук('босс');
    if (ш.фаза2.фраза) {
      всплывашка(в.x, в.y - в.высотаСпрайта - 20, ш.фаза2.фраза, ЦВЕТ.хп, 30);
    }
    отправитьСобытие('босс_вторая_фаза', { босс: ш.имя, время: Math.round(ИГРА.время) });
  }

  // --- рывок второй фазы ШВАРЦА: летит по показанной полосе ---
  if (в.рывокОсталось > 0) {
    в.рывокОсталось -= дт;
    в.x += в.рывокX * дт;
    в.y += в.рывокY * дт;
    в.скорX = в.рывокX; в.скорY = в.рывокY;
    в.фаза += дт * 10;
    if (в.рывокОсталось <= 0) в.таймерАтаки = интервалАтакиБосса(в);
    return true;
  }

  // --- замах: стоит на месте, зона уже видна ---
  if (в.замахБосса > 0) {
    в.замахБосса -= дт;
    в.скорX = 0; в.скорY = 0;
    в.фаза += дт * 2.5;                    // подрагивает, но не идёт
    return true;
  }

  в.таймерАтаки = (в.таймерАтаки === undefined ? ш.атака.интервал : в.таймерАтаки) - дт;

  // --- залп кусками: вторая фаза ТОЛПЫ ---
  if (в.фаза2 && ш.фаза2 && ш.фаза2.интервалЗалпа) {
    в.таймерЗалпа = (в.таймерЗалпа === undefined ? ш.фаза2.интервалЗалпа : в.таймерЗалпа) - дт;
    if (в.таймерЗалпа <= 0) {
      в.таймерЗалпа = ш.фаза2.интервалЗалпа;
      залпКусками(в, ш.фаза2);
    }
  }

  if (в.таймерАтаки > 0) return false;

  const дист = дистанция(в.x, в.y, и.x, и.y);
  const рывок = в.фаза2 && ш.фаза2 && ш.фаза2.скоростьРывка;

  // Дистанция замаха: рывок бьёт через экран, обычный удар — только вблизи
  if (!рывок && ш.атака.дистанция && дист > ш.атака.дистанция) return false;
  if (ш.атака.вид === 'круг' && !рывок && дист > ш.атака.радиус * 1.6) return false;

  начатьАтакуБосса(в, рывок);
  return true;
}

function интервалАтакиБосса(в) {
  const ш = в.шаблон;
  if (в.фаза2 && ш.фаза2 && ш.фаза2.интервал) return ш.фаза2.интервал;
  return ш.атака.интервал;
}

function начатьАтакуБосса(в, рывок) {
  const ш = в.шаблон;
  const и = ИГРА.игрок;
  const а = ш.атака;
  const ф = в.фаза2 && ш.фаза2 ? ш.фаза2 : null;
  const замах = рывок && ф && ф.замах ? ф.замах : а.замах;

  в.замахБосса = Math.max(ТЕЛЕГРАФ.минЗамах, замах);
  в.таймерАтаки = интервалАтакиБосса(в);
  звук('бросок', 0.7);

  if (а.вид === 'круг' && !рывок) {
    /* Зона привязана к боссу, а не к игроку: игрок должен ВЫЙТИ из-под
       массы, а не убегать от точки, которую он сам же и задал. */
    завестиТелеграф({
      вид: 'круг', x: в.x, y: в.y, радиус: а.радиус,
      замах: в.замахБосса, урон: а.урон, источник: в, подпись: а.подпись
    });
    return;
  }

  // полоса: курс берём один раз, на замахе он уже не доворачивается
  const угол = Math.atan2(и.y - в.y, и.x - в.x);
  const длина = рывок && ф ? ф.длина : а.длина;
  const ширина = рывок && ф ? ф.ширина : а.ширина;
  const урон = рывок && ф && ф.урон !== undefined ? ф.урон : а.урон;
  в.сторона = Math.cos(угол) < 0 ? -1 : 1;
  в.лицоX = Math.cos(угол); в.лицоY = Math.sin(угол);

  const т = завестиТелеграф({
    вид: 'полоса', x: в.x, y: в.y,
    доX: в.x + Math.cos(угол) * длина,
    доY: в.y + Math.sin(угол) * длина,
    ширина, замах: в.замахБосса, урон, источник: в,
    подпись: рывок && ф ? ф.подпись : а.подпись
  });

  /* Рывок: полоса — это маршрут, и босс по нему действительно проносится.
     Урон в момент удара уже посчитан телеграфом, поэтому рывок — про
     позицию босса после, а не про второй заход по тем же клеткам. */
  if (рывок && ф) {
    т.послеУдара = () => {
      if (в.мёртв) return;
      в.рывокX = Math.cos(угол) * ф.скоростьРывка;
      в.рывокY = Math.sin(угол) * ф.скоростьРывка;
      в.рывокОсталось = ф.длина / ф.скоростьРывка;
      звук('бросок', 1.3);
    };
  }
}

/* Залп кусками: веером в игрока. Куски у ТОЛПЫ и так отваливаются — во
   второй фазе они идут не в эскорт, а в лицо. */
function залпКусками(в, ф) {
  const и = ИГРА.игрок;
  const центр = Math.atan2(и.y - в.y, и.x - в.x);
  const сколько = ф.снарядов || 3;
  const цy = в.y - в.высотаСпрайта * 0.45;
  for (let n = 0; n < сколько; n++) {
    const смещение = сколько === 1 ? 0 : (n / (сколько - 1) - 0.5) * 2 * (ф.разлёт || 0.3);
    запуститьСнаряд(в.x, цy, центр + смещение, { источник: в });
  }
  брызги(в.x, цy, '#c8b8a0', 8);
  звук('бросок', 1.1);
}

// --- ОТЧЁТ ОТПРАВЛЕН ---
function отправитьОтчёт() {
  const и = ИГРА.игрок;
  const к = ОТЧЁТ.уровни[и.апгрейды.otchet - 1];
  const кандидаты = ИГРА.враги.filter(в => в.гаснет <= 0 && дистанция(в.x, в.y, и.x, и.y) < к.радиус);
  if (кандидаты.length === 0) { и.таймерОтчёта = 0.5; return; }   // некому — пробуем скоро снова

  for (let n = 0; n < к.целей && кандидаты.length > 0; n++) {
    const инд = Math.floor(Math.random() * кандидаты.length);
    const в = кандидаты.splice(инд, 1)[0];
    const цy = в.y - в.высотаСпрайта * 0.5;
    всплывашка(в.x, цy, 'отчёт отправлен', ЦВЕТ.золото, 18);
    брызги(в.x, цy, ЦВЕТ.золото, 14);
    убитьВрага(в);
  }
}

function обновитьОружие(дт) {
  const и = ИГРА.игрок;
  const мп = и.множительПерезарядки * (и.праймОсталось > 0 ? 0.5 : 1);

  // гантеля: новый бросок, когда откатилась перезарядка и все вернулись
  и.таймерГантели -= дт;
  if (и.таймерГантели <= 0 && ИГРА.гантели.length === 0) {
    бросокГантели();
    и.таймерГантели = ГАНТЕЛЯ.перезарядка * мп;
  }

  if (и.апгрейды.krik) {
    и.таймерКрика -= дт;
    if (и.таймерКрика <= 0) { крикнуть(); и.таймерКрика = КРИК.перезарядка * мп; }
  }
  if (и.апгрейды.otchet) {
    и.таймерОтчёта -= дт;
    if (и.таймерОтчёта <= 0) {
      отправитьОтчёт();
      if (и.таймерОтчёта <= 0) и.таймерОтчёта = ОТЧЁТ.уровни[и.апгрейды.otchet - 1].перезарядка * мп;
    }
  }
  if (и.апгрейды.praim) {
    const к = ПРАЙМ.уровни[и.апгрейды.praim - 1];
    и.таймерПрайма -= дт;
    if (и.таймерПрайма <= 0) {
      и.праймОсталось = к.длительность;
      и.таймерПрайма = к.перезарядка;
      всплывашка(и.x, и.y - и.в - 30, 'ПРАЙМ', ЦВЕТ.золото, 26);
      звук('левелап');
    }
  }
  if (и.праймОсталось > 0) и.праймОсталось -= дт;

  if (и.баффБелуги > 0) и.баффБелуги -= дт;

  // пассивки по таймеру
  if (и.регенИнтервал > 0) {
    и.таймерРегена -= дт;
    if (и.таймерРегена <= 0) {
      и.таймерРегена = и.регенИнтервал;
      if (и.hp < и.максHp) {
        // hp дробное, поэтому обязательно подрезаем: иначе 2.6 + 1 = 3.6
        и.hp = Math.min(и.максHp, и.hp + 1);
        всплывашка(и.x, и.y - и.в - 10, '+1', ЦВЕТ.зелёный, 20);
      }
    }
  }
  if (и.щитИнтервал > 0 && !и.щитЗаряжен) {
    и.таймерЩита -= дт;
    if (и.таймерЩита <= 0) { и.щитЗаряжен = true; и.таймерЩита = и.щитИнтервал; }
  }
}


