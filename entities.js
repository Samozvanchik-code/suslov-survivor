function частица(x, y, цвет, о = {}) {
  ИГРА.частицы.push({
    x, y,
    вx: о.вx !== undefined ? о.вx : случ(-120, 120),
    вy: о.вy !== undefined ? о.вy : случ(-200, -40),
    жизнь: о.жизнь || случ(0.3, 0.6),
    всего: 0,
    размер: о.размер || случ(3, 6),
    цвет,
    гравитация: о.гравитация !== undefined ? о.гравитация : 500
  });
  const ч = ИГРА.частицы[ИГРА.частицы.length - 1];
  ч.всего = ч.жизнь;
}

function брызги(x, y, цвет, сколько = 8) {
  for (let i = 0; i < сколько; i++) частица(x, y, цвет);
}

function всплывашка(x, y, строка, цвет, размер = 20) {
  ИГРА.всплывашки.push({ x, y, строка, цвет, размер, жизнь: 0.8, всего: 0.8 });
}

// Реплика над головой. Не оружие, урона нет, чистый юмор.
function пузырь(цельТип, цель, строка) {
  ИГРА.пузыри.push({ цельТип, цель, строка, жизнь: 2.2, всего: 2.2 });
}

function обновитьЭффекты(дт) {
  for (let i = ИГРА.частицы.length - 1; i >= 0; i--) {
    const ч = ИГРА.частицы[i];
    ч.вy += ч.гравитация * дт;
    ч.x += ч.вx * дт; ч.y += ч.вy * дт;
    ч.жизнь -= дт;
    if (ч.жизнь <= 0) ИГРА.частицы.splice(i, 1);
  }
  for (let i = ИГРА.всплывашки.length - 1; i >= 0; i--) {
    const в = ИГРА.всплывашки[i];
    в.y -= 55 * дт; в.жизнь -= дт;
    if (в.жизнь <= 0) ИГРА.всплывашки.splice(i, 1);
  }
  for (let i = ИГРА.пузыри.length - 1; i >= 0; i--) {
    const п = ИГРА.пузыри[i];
    п.жизнь -= дт;
    // враг умер — пузырь уходит вместе с ним
    if (п.жизнь <= 0 || (п.цельТип === 'враг' && п.цель.мёртв)) ИГРА.пузыри.splice(i, 1);
  }

  // случайная реплика раз в 4-6 сек над случайным участником боя
  ИГРА.таймерРеплики -= дт;
  if (ИГРА.таймерРеплики <= 0) {
    ИГРА.таймерРеплики = случ(РЕПЛИКИ_ИНТЕРВАЛ[0], РЕПЛИКИ_ИНТЕРВАЛ[1]);
    // говорит только Илья; в режиме Шварца — своим пулом
    const пул = ИГРА.игрок.шварц > 0 ? РЕПЛИКИ_ШВАРЦА : РЕПЛИКИ_ИЛЬИ;
    пузырь('игрок', ИГРА.игрок, изМассива(пул));
  }
}

function наЭкране(x, y, запас = 0) {
  const эx = мирВЭкранX(x), эy = мирВЭкранY(y);
  return эx > -запас && эx < ЭКР.ш + запас && эy > -запас && эy < ЭКР.в + запас;
}


