проверка('в объявлении ник донатера',
         ИГРА.объяваИвента && ИГРА.объяваИвента.ник === 'galiopola',
         ИГРА.объяваИвента && ИГРА.объяваИвента.ник);
проверка('живёт ровно две секунды по ТЗ', S.ОБЪЯВА_ИВЕНТА.жизнь === 2, S.ОБЪЯВА_ИВЕНТА.жизнь);
S.обновитьОбъяву(1.0);
проверка('через секунду ещё висит', !!ИГРА.объяваИвента);
S.обновитьОбъяву(1.1);
проверка('после двух секунд начала уезжать',
         !!ИГРА.объяваИвента && ИГРА.объяваИвента.жизнь < 0, ИГРА.объяваИвента);
S.обновитьОбъяву(1.0);
проверка('и убралась совсем', ИГРА.объяваИвента === null, ИГРА.объяваИвента);

// на телефоне полоса не выше 12% высоты и не лезет в центр
S.запуститьИвент('haunted');
for (const [ш, в] of [[390, 844], [360, 640], [310, 650]]) {
  песочница.window.innerWidth = ш; песочница.window.innerHeight = в;
  vmПересчёт();
  const кт = песочница.window._элементы['экран'].getContext('2d');
  кт._очиститьЖурнал();
  let ошибка = null;
  try { S.нарисоватьОбъяву(); } catch (e) { ошибка = e.message; }
  const полосы = кт._журнал.filter(з => з.вид === 'заливка');
  const низ = полосы.reduce((м, з) => Math.max(м, з.y + з.в), 0);
  проверка('на ' + ш + 'x' + в + ' плашка не выше 12% и не в центре',
           !ошибка && низ <= в * 0.12 + 8 && низ < в / 2,
           ошибка || ('низ плашки ' + Math.round(низ) + ' из ' + в));
}
песочница.window.innerWidth = 1280; песочница.window.innerHeight = 720;
vmПересчёт();

раздел('27. БЕСКОНЕЧКА ПОСЛЕ ПОБЕДЫ');
S.начатьЗабег();
ИГРА.игрок.неуязвим = 999;
проверка('в начале забега бесконечки нет', ИГРА.бесконечка === false);
const двойник = S.вызватьБосса('ДВОЙНИК');
S.убитьВрага(двойник);
проверка('после двойника развилка', ИГРА.экран === 'победа', ИГРА.экран);
S.продолжитьЗабег();
проверка('ОСТАТЬСЯ возвращает в бой', ИГРА.экран === 'бой', ИГРА.экран);
проверка('бесконечка включена', ИГРА.бесконечка === true);
проверка('победа при этом уже в кармане', ИГРА.победаОдержана === true);

// время после победы копится отдельно от дополнительного
ИГРА.время = S.БАЛАНС.длинаЗабега;
const допБыло = ИГРА.дополнительное, бескБыло = ИГРА.бесконечное;
for (let к = 0; к < 60; к++) S.шагЛогики(1 / 60);
проверка('дополнительное растёт', ИГРА.дополнительное > допБыло,
         ИГРА.дополнительное.toFixed(1));
проверка('бесконечное растёт вместе с ним', ИГРА.бесконечное > бескБыло,
         ИГРА.бесконечное.toFixed(1));
проверка('часы забега стоят на 600', ИГРА.время === S.БАЛАНС.длинаЗабега, ИГРА.время);

// боссы цикла идут и без живого двойника
ИГРА.босс = null;
ИГРА.таймерЦикла = 0.01;
const боссовБыло = ИГРА.боссовЦикла;
S.обновитьФинал(0.02);
проверка('в бесконечке боссы цикла приходят',
         ИГРА.боссовЦикла === боссовБыло + 1, ИГРА.боссовЦикла + ' было ' + боссовБыло);
проверка('интервал цикла — две минуты', S.ФИНАЛ.интервалЦикла === 120, S.ФИНАЛ.интервалЦикла);

// смерть в бесконечке победу не отбирает
ИГРА.игрок.неуязвим = 0;
S.ранитьИгрока(99999, null);
проверка('умер в бесконечке — в итогах всё равно победа',
         ИГРА.победа === true && ИГРА.экран === 'итоги',
         ИГРА.победа + ' / ' + ИГРА.экран);

// сортировка: бесконечное — второй ключ, но только оно, не дополнительное
const сА = { время: 600, бесконечное: 120, уровень: 20, убито: 1000 };
const сБ = { время: 600, бесконечное: 0, уровень: 55, убито: 5000 };
проверка('в таблице выше тот, кто дольше держался ПОСЛЕ победы',
         S.сравнитьРезультаты(сА, сБ) < 0, S.сравнитьРезультаты(сА, сБ));
const сВ = { время: 600, доп: 500, бесконечное: 0, уровень: 30 };
const сГ = { время: 600, доп: 0, бесконечное: 0, уровень: 31 };
проверка('пересиживание финала без победы преимущества не даёт',
         S.сравнитьРезультаты(сГ, сВ) < 0, S.сравнитьРезультаты(сГ, сВ));
проверка('в таблице время показывается с приставкой бесконечки',
         S.времяЗаписи(сА).indexOf('+') > 0, S.времяЗаписи(сА));
проверка('без бесконечки приписки нет',
         S.времяЗаписи(сБ).indexOf('+') < 0, S.времяЗаписи(сБ));

раздел('28. СКИНЫ: ТОЛЬКО ВНЕШНОСТЬ');
/* Железное правило: ни одного стата. Как только скин что-то даёт, наверху
   таблицы оказываются не те, кто лучше играет, а те, кто больше накрутил. */
S.начатьЗабег();
const хитбоксБыл = { ш: ИГРА.игрок.ш, в: ИГРА.игрок.в };
const уронБыл = S.ГАНТЕЛЯ.урон, откатБыл = S.ГАНТЕЛЯ.перезарядка;
ИГРА.шкаф.открыто.персонаж.push('tarakan');
S.надетьСкин('персонаж', 'tarakan');
проверка('скин надет', S.выбранныйСкин('персонаж').ид === 'tarakan',
         S.выбранныйСкин('персонаж').ид);
проверка('спрайт игрока сменился', S.спрайтИгрока() === 'skin_tarakan', S.спрайтИгрока());
S.начатьЗабег();
проверка('хитбокс игрока не изменился',
         ИГРА.игрок.ш === хитбоксБыл.ш && ИГРА.игрок.в === хитбоксБыл.в,
         ИГРА.игрок.ш + 'x' + ИГРА.игрок.в);
проверка('урон и откат гантели не изменились',
         S.ГАНТЕЛЯ.урон === уронБыл && S.ГАНТЕЛЯ.перезарядка === откатБыл);
проверка('ни у одного скина нет полей со статами',
         [].concat(S.СКИНЫ.персонаж, S.СКИНЫ.оружие).every(с =>
           Object.keys(с).every(к => ['ид', 'спрайт', 'имя', 'редкость', 'база'].indexOf(к) >= 0)),
         JSON.stringify(S.СКИНЫ.персонаж[1]));

// закрытый скин надеть нельзя
проверка('закрытый скин не надевается', S.надетьСкин('персонаж', 'lyuks') === false);
проверка('выбранным остался прежний', S.выбранныйСкин('персонаж').ид === 'tarakan');
// скин без спрайта откатывается на базовый
ИГРА.шкаф.открыто.персонаж.push('нетакого');
ИГРА.шкаф.выбран.персонаж = 'нетакого';
проверка('несуществующий скин откатывается на базовый',
         S.выбранныйСкин('персонаж').база === true, S.выбранныйСкин('персонаж').ид);
ИГРА.шкаф.выбран.персонаж = 'ilya';

проверка('все скины помечены необязательными в манифесте',
         [].concat(S.СКИНЫ.персонаж, S.СКИНЫ.оружие)
           .filter(с => !с.база)
           .every(с => S.МАНИФЕСТ[с.спрайт] && S.МАНИФЕСТ[с.спрайт].необязательный),
         [].concat(S.СКИНЫ.персонаж, S.СКИНЫ.оружие)
           .filter(с => !с.база && !(S.МАНИФЕСТ[с.спрайт] || {}).необязательный)
           .map(с => с.спрайт).join(', '));

раздел('29. КОЛЕСО: ПРОКРУТЫ ТОЛЬКО С БОССОВ');
S.начатьЗабег();
ИГРА.шкаф = S.загрузитьШкаф();
ИГРА.шкаф.прокруты = 0;
ИГРА.игрок.неуязвим = 999;
проверка('крутить без прокрутов нельзя', S.крутануть() === null);

// обычный враг прокрут не даёт
const обычный = S.создатьВрага('anon', S.ВРАГИ.anon, { x: 100, y: 100 }, {});
S.убитьВрага(обычный);
проверка('за обычного анона прокрута нет', ИГРА.шкаф.прокруты === 0, ИГРА.шкаф.прокруты);

// босс даёт
const босс = S.вызватьБосса('ТОЛПА');
S.убитьВрага(босс);
проверка('за босса дают прокрут', ИГРА.шкаф.прокруты === 1, ИГРА.шкаф.прокруты);

// уровень и время не дают
const прокрутыДо = ИГРА.шкаф.прокруты;
for (let к = 0; к < 600; к++) S.шагЛогики(1 / 60);
проверка('за время прокруты не капают', ИГРА.шкаф.прокруты === прокрутыДо,
         ИГРА.шкаф.прокруты);

// крутка открывает скин и тратит прокрут
ИГРА.шкаф.прокруты = 1;
const прокрутИтог = S.крутануть();
проверка('крутка что-то выдала', !!прокрутИтог && !!прокрутИтог.скин, прокрутИтог);
проверка('прокрут потрачен', ИГРА.шкаф.прокруты === 0, ИГРА.шкаф.прокруты);
проверка('выпавший скин открыт или засчитан дублем',
         прокрутИтог.дубль ? ИГРА.шкаф.дубли > 0 : S.открытЛи(прокрутИтог.вид, прокрутИтог.скин.ид),
         JSON.stringify({ дубль: прокрутИтог.дубль, дубли: ИГРА.шкаф.дубли }));
проверка('в пуле только скины с реально загруженным спрайтом',
         S.пулКолеса('обычный').every(э => S.скинГотов(э.скин)));
проверка('базовые скины в колесо не попадают',
         S.пулКолеса('обычный').every(э => !э.скин.база));

// двойник даёт гарантию редкого
ИГРА.шкаф.гарантии = 0;
S.датьПрокрут(true);
проверка('за двойника записана гарантия', ИГРА.шкаф.гарантии === 1, ИГРА.шкаф.гарантии);
const порядок = S.РЕДКОСТИ ? ['базовый', 'обычный', 'редкий', 'легендарный'] : [];
const попался = S.крутануть();
проверка('по гарантии выпал редкий или выше',
         !!попался && порядок.indexOf(попался.скин.редкость) >= 2,
         попался && попался.скин.редкость);

// пять дублей меняются на любой скин.
// Шкаф чистим руками: предыдущие крутки уже что-то открыли и сохранили,
// а обмен проверяется именно на ЗАКРЫТОМ скине.
S.хранПисать('суслов_шкаф', '');
ИГРА.шкаф = S.загрузитьШкаф();
ИГРА.шкаф.дубли = 4;
проверка('на четырёх дублях обмена нет', S.обменятьДубли('персонаж', 'lyuks') === false);
ИГРА.шкаф.дубли = 5;
проверка('пять дублей открывают выбранный скин',
         S.обменятьДубли('персонаж', 'lyuks') === true);
проверка('дубли списаны', ИГРА.шкаф.дубли === 0, ИГРА.шкаф.дубли);
проверка('скин действительно открыт', S.открытЛи('персонаж', 'lyuks'));
проверка('уже открытый за дубли не покупается',
         S.обменятьДубли('персонаж', 'lyuks') === false);

// шкаф переживает перезаход и не падает от мусора в хранилище
S.надетьСкин('персонаж', 'lyuks');
const снова = S.загрузитьШкаф();
проверка('шкаф сохраняется между сессиями',
         снова.выбран.персонаж === 'lyuks' && снова.открыто.персонаж.indexOf('lyuks') >= 0,
         JSON.stringify(снова.выбран));
S.хранПисать('суслов_шкаф', '{это не json');
const после = S.загрузитьШкаф();
проверка('битое хранилище не роняет игру',
         после.выбран.персонаж === 'ilya' && после.открыто.персонаж.length === 1,
         JSON.stringify(после));
S.хранПисать('суслов_шкаф', JSON.stringify({ открыто: { персонаж: ['чужое', 'lyuks'] } }));
const чужое = S.загрузитьШкаф();
проверка('чужие идентификаторы из хранилища выбрасываются',
         чужое.открыто.персонаж.indexOf('чужое') < 0 && чужое.открыто.персонаж.indexOf('lyuks') >= 0,
         JSON.stringify(чужое.открыто.персонаж));

/* Пока PNG скинов не доехали, крутить нечего — и кнопка КОЛЕСО на итогах не
   должна появляться: нажатие на неё не делало бы ничего. */
const спрайтыСкинов = S.СКИНЫ.персонаж.filter(с => !с.база).map(с => S.СПРАЙТ[с.спрайт]);
const готовностьБыла = спрайтыСкинов.map(сп => сп && сп.готов);
for (const сп of спрайтыСкинов) if (сп) сп.готов = false;
ИГРА.шкаф.прокруты = 3;
ИГРА.экран = 'итоги';
S.экранИтогов();
проверка('без загруженных скинов кнопки колеса нет',
         !S.кнопки().find(к => к.действие === S.открытьКолесо), S.кнопки().length);
проверка('и сама крутка в этом случае ничего не выдаёт', S.крутануть() === null);
спрайтыСкинов.forEach((сп, i) => { if (сп) сп.готов = готовностьБыла[i]; });
ИГРА.шкаф.прокруты = 1;
S.экранИтогов();
проверка('со скинами кнопка колеса появляется',
         !!S.кнопки().find(к => к.действие === S.открытьКолесо), S.кнопки().length);
ИГРА.шкаф.прокруты = 0;

раздел('30. ЭКРАНЫ КОЛЕСА И ШКАФА РИСУЮТСЯ');
ИГРА.шкаф = S.загрузитьШкаф();
for (const [ш, в] of [[390, 844], [1280, 800], [310, 650]]) {
  песочница.window.innerWidth = ш; песочница.window.innerHeight = в;
  vmПересчёт();
  ИГРА.шкаф.прокруты = 1;
  ИГРА.экран = 'итоги';
  S.открытьКолесо();
  let ошибка = null;
  try { for (let к = 0; к < 200; к++) S.экранКолеса(); } catch (e) { ошибка = e.message; }
  проверка('колесо докрутилось и не упало на ' + ш + 'x' + в,
           !ошибка && ИГРА.колесо && ИГРА.колесо.t >= 1, ошибка || (ИГРА.колесо && ИГРА.колесо.t));
  S.закрытьКолесо();
  проверка('после колеса вернулись на итоги ' + ш + 'x' + в, ИГРА.экран === 'итоги', ИГРА.экран);

  ИГРА.экран = 'старт';
  S.открытьШкаф();
  ошибка = null;
  try { S.экранШкафа(); } catch (e) { ошибка = e.message; }
  проверка('шкаф рисуется на ' + ш + 'x' + в, !ошибка, ошибка);
  проверка('в шкафу карточки кликабельны ' + ш + 'x' + в, S.кнопки().length > 2, S.кнопки().length);
  /* Пять скинов персонажа на 390 px уезжали за правый край: размер карточки
     считался от ширины экрана наугад, а не от самой длинной полки. */
  const карточки = S.кнопки().filter(к => к.в === к.ш);
  проверка('карточки шкафа не вылезают за края ' + ш + 'x' + в,
           карточки.every(к => к.x >= 0 && к.x + к.ш <= ш),
           карточки.map(к => Math.round(к.x) + '..' + Math.round(к.x + к.ш)).join(' '));
  проверка('карточки не мельче 48 px ' + ш + 'x' + в,
           карточки.every(к => к.ш >= 48), карточки.length && Math.round(карточки[0].ш));
  S.закрытьШкаф();
  проверка('из шкафа вернулись в меню ' + ш + 'x' + в, ИГРА.экран === 'старт', ИГРА.экран);
}
песочница.window.innerWidth = 1280; песочница.window.innerHeight = 720;
vmПересчёт();

console.log('\n=== ' + (всего - провалов) + ' из ' + всего + ' проверок пройдено ===');
process.exit(провалов ? 1 : 0);
