/* Стык игры и сервера рейтинга целиком, без сети и без Cloudflare.
   Игра грузится с подставленным АДРЕС_РЕЙТИНГА, её fetch заворачивается
   прямо в код воркера, воркер работает на настоящем SQLite в памяти с той
   же schema.sql, что уезжает в Cloudflare D1.
   Так проверяется настоящий контракт: какой путь дёргает игра, что шлёт,
   что понимает в ответе.
   Запуск: node test_integration.js */

const fs = require('fs');
const vm = require('vm');
const { поднять } = require('./test_env.js');

// --- поднимаем воркер на настоящем SQLite вместо D1 ---
/* Раньше здесь стоял мок KV: обычная Map, потому что KV — и есть Map. После
   переезда топа на D1 подсовываем встроенный в Node модуль node:sqlite и ту
   же схему, что и в Cloudflare, — иначе тест стыка проверял бы мой
   самописный интерпретатор SQL, а не воркер. Требует Node 22.5+. */
const { DatabaseSync } = require('node:sqlite');

function поддельныйD1() {
  const бд = new DatabaseSync(':memory:');
  бд.exec(fs.readFileSync(__dirname + '/server/schema.sql', 'utf8'));
  бд.exec("UPDATE meta SET v = '0' WHERE k = 'total'");   // в тестах счёт с нуля
  return {
    prepare(sql) {
      let привязка = [];
      const о = {
        bind(...а) { привязка = а; return о; },
        async all() { return { results: бд.prepare(sql).all(...привязка) }; },
        async first() {
          const р = бд.prepare(sql).all(...привязка);
          return р.length ? р[0] : null;
        },
        async run() {
          const р = бд.prepare(sql).run(...привязка);
          return { success: true, meta: { changes: Number(р.changes) || 0 } };
        }
      };
      return о;
    }
  };
}

/* Счётчик частоты уехал из хранилища в Cache API — мокаем и его. */
const хранКэша = new Map();
const поддельныйКэш = { default: {
  async match(запрос) {
    const з = хранКэша.get(запрос.url);
    if (!з || Date.now() > з.до) { хранКэша.delete(запрос.url); return undefined; }
    return new Response(з.v);
  },
  async put(запрос, о) {
    const м = /max-age=(\d+)/.exec(о.headers.get('Cache-Control') || '');
    хранКэша.set(запрос.url, { v: await о.text(), до: Date.now() + (м ? Number(м[1]) : 60) * 1000 });
  }
} };

const исходникВоркера = fs.readFileSync(__dirname + '/server/worker.js', 'utf8')
  .replace('export default', 'globalThis.ВОРКЕР =');
