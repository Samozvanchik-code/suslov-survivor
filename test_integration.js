/* Стык игры и сервера рейтинга целиком, без сети и без Cloudflare.
   Игра грузится с подставленным АДРЕС_РЕЙТИНГА, её fetch заворачивается
   прямо в код воркера, воркер работает на поддельном KV.
   Так проверяется настоящий контракт: какой путь дёргает игра, что шлёт,
   что понимает в ответе.
   Запуск: node test_integration.js */

const fs = require('fs');
const vm = require('vm');
const { поднять } = require('./test_env.js');

// --- поднимаем воркер на поддельном хранилище ---
function поддельныйKV() {
  const д = new Map();
  return {
    async get(k) {
      const з = д.get(k);
      if (!з) return null;
      if (з.до && Date.now() > з.до) { д.delete(k); return null; }
      return з.v;
    },
    async put(k, v, о) {
      д.set(k, { v, до: о && о.expirationTtl ? Date.now() + о.expirationTtl * 1000 : 0 });
    }
  };
}

const исходникВоркера = fs.readFileSync(__dirname + '/server/worker.js', 'utf8')
  .replace('export default', 'globalThis.ВОРКЕР =');
const песочницаВоркера = { Response, Request, URL, JSON, Math, Date, Number, String,
                           Array, Object, console, globalThis: null };
песочницаВоркера.globalThis = песочницаВоркера;
vm.createContext(песочницаВоркера);
vm.runInContext(исходникВоркера, песочницаВоркера, { filename: 'worker.js' });
const воркер = песочницаВоркера.ВОРКЕР;
const env = { RATING: поддельныйKV() };

// что реально запросила игра — пригодится для проверки путей
const запросы = [];

const АДРЕС = 'https://рейтинг.тест';

/* fetch игры направляем в воркер. Это ровно тот путь, который игра
   построит в бою, — если она ошибётся с '/score', тест это увидит. */
let серверЛежит = false;      // переключатель для проверки «сервер недоступен»

function поддельныйFetch(url, опции) {
  опции = опции || {};
  // запрос записываем ДО проверки: игра его сделала, даже если сеть отвалилась
  запросы.push({ url: String(url), метод: опции.method || 'GET', тело: опции.body });
  if (серверЛежит) return Promise.reject(new Error('сеть отвалилась'));
  const запрос = new Request(String(url), {
    method: опции.method || 'GET',
    headers: Object.assign({ 'CF-Connecting-IP': '1.2.3.4' }, опции.headers || {}),
    body: опции.body
  });
  return воркер.fetch(запрос, env);
}

const { S, ИГРА } = поднять({ адресРейтинга: АДРЕС, fetch: поддельныйFetch });

let всего = 0, провалов = 0;
function проверка(имя, условие, факт) {
  всего++;
  if (условие) console.log('  ОК     ' + имя);
  else { провалов++; console.log('  ПРОВАЛ ' + имя + (факт !== undefined ? '  -> ' + факт : '')); }
}
const раздел = (и) => console.log('\n' + и);
const подождать = () => new Promise(r => setTimeout(r, 30));

function сыгратьЗабег(ник, время) {
  S.начатьЗабег();
  ИГРА.время = время;
  ИГРА.уровень = Math.max(1, Math.round(время / 25));
  ИГРА.убито = Math.round(время * 4);
  S.отправитьРезультат({
    ник, время, уровень: ИГРА.уровень, убито: ИГРА.убито,
    спасённых: 0, билд: 'ГАНТЕЛЯ 3', дата: Date.now()
  });
}

(async () => {
  раздел('1. ПЕРВЫЙ ЗАБЕГ УХОДИТ НА СЕРВЕР');
  сыгратьЗабег('ilya', 200);
  проверка('статус переключился в ожидание', ИГРА.мировойСтатус === 'ждём', ИГРА.мировойСтатус);
  await подождать();

  проверка('игра дёрнула именно /score',
           запросы[0].url === АДРЕС + '/score', запросы[0].url);
  проверка('метод POST', запросы[0].метод === 'POST', запросы[0].метод);
  const отправлено = JSON.parse(запросы[0].тело);
  проверка('в теле есть ник, время, уровень, убито',
           отправлено.ник === 'ilya' && отправлено.время === 200 &&
           'уровень' in отправлено && 'убито' in отправлено,
           JSON.stringify(отправлено));

  проверка('сервер ответил и статус стал «есть»', ИГРА.мировойСтатус === 'есть', ИГРА.мировойСтатус);
  проверка('первый игрок — первое место', ИГРА.мировоеМесто === 1, ИГРА.мировоеМесто);
  проверка('всего игроков 1', ИГРА.мировоВсего === 1, ИГРА.мировоВсего);

  await подождать();
  проверка('следом подтянулся мировой топ', ИГРА.мировойТоп.length === 1, ИГРА.мировойТоп.length);
  проверка('в топе наш ник', ИГРА.мировойТоп[0].ник === 'ilya', ИГРА.мировойТоп[0].ник);

  раздел('2. МЕСТО СЧИТАЕТСЯ ОТ ЧУЖИХ РЕЗУЛЬТАТОВ');
  for (const [ник, t] of [['leva2k', 400], ['zzord', 350], ['d1pro4', 300]]) {
    сыгратьЗабег(ник, t);
    await подождать(); await подождать();
  }
  сыгратьЗабег('новичок', 100);
  await подождать(); await подождать();
  проверка('слабый результат встал последним', ИГРА.мировоеМесто === 5, ИГРА.мировоеМесто);
  проверка('всего игроков 5', ИГРА.мировоВсего === 5, ИГРА.мировоВсего);

  сыгратьЗабег('чемпион', 599);
  await подождать(); await подождать();
  проверка('лучший результат берёт первое место', ИГРА.мировоеМесто === 1, ИГРА.мировоеМесто);
  проверка('топ отсортирован по убыванию',
           ИГРА.мировойТоп.every((р, i) => i === 0 || ИГРА.мировойТоп[i - 1].время >= р.время),
           ИГРА.мировойТоп.map(р => р.время).join(', '));

  раздел('3. ЭКРАН ИТОГОВ С ЖИВЫМИ ДАННЫМИ');
  ИГРА.экран = 'итоги';
  let упал = null;
  try { S.экранИтогов(); } catch (e) { упал = e.message; }
  проверка('экран итогов рисуется с мировым топом', !упал, упал);

  раздел('4. СЕРВЕР ЛЁГ — ИГРА ЖИВЁТ');
  ИГРА.мировойТоп = [];
  const былоЗапросов = запросы.length;
  серверЛежит = true;
  сыгратьЗабег('невезучий', 150);
  await подождать(); await подождать();
  проверка('статус стал «недоступен»', ИГРА.мировойСтатус === 'недоступен', ИГРА.мировойСтатус);
  проверка('места нет, но и падения нет', ИГРА.мировоеМесто === null, ИГРА.мировоеМесто);
  проверка('локальная таблица всё равно записана', ИГРА.таблица.length > 0, ИГРА.таблица.length);
  упал = null;
  try { S.экранИтогов(); } catch (e) { упал = e.message; }
  проверка('экран итогов цел при мёртвом сервере', !упал, упал);
  проверка('запрос всё-таки был отправлен', запросы.length > былоЗапросов);
  серверЛежит = false;

  раздел('5. ОТВЕТ НА ПРОШЛЫЙ ЗАБЕГ НЕ ПУТАЕТСЯ С НОВЫМ');
  сыгратьЗабег('первый', 500);
  сыгратьЗабег('второй', 120);          // второй забег начат до ответа на первый
  await подождать(); await подождать();
  проверка('показано место ВТОРОГО забега, а не первого',
           ИГРА.мировоеМесто > 1, 'место ' + ИГРА.мировоеМесто);

  раздел('6. ПОДДЕЛКУ СЕРВЕР НЕ ПРИНИМАЕТ');
  const былоВТопе = (await (await воркер.fetch(new Request(АДРЕС + '/top?n=50',
      { headers: { 'CF-Connecting-IP': '9.9.9.9' } }), env)).json()).топ.length;
  S.начатьЗабег();
  S.отправитьРезультат({ ник: 'читер', время: 99999, уровень: 999, убито: 999999,
                          спасённых: 999, билд: '', дата: Date.now() });
  await подождать(); await подождать();
  проверка('игра пометила рейтинг недоступным, а не показала фейк',
           ИГРА.мировоеМесто === null, ИГРА.мировоеМесто);
  const сталоВТопе = (await (await воркер.fetch(new Request(АДРЕС + '/top?n=50',
      { headers: { 'CF-Connecting-IP': '9.9.9.8' } }), env)).json()).топ.length;
  проверка('подделка не попала в топ', сталоВТопе === былоВТопе,
           былоВТопе + ' -> ' + сталоВТопе);

  /* ------------------------------------------------------------------------
     ФИНАЛ: часы забега встали на 600, бой шёл в дополнительное время. Стык
     тут не косметический — сервер по полю «доп» считает потолки убитых и
     уровня, и без него честный финалист получает 422 вместо записи.
     ------------------------------------------------------------------------ */
  раздел('7. ФИНАЛ: ДОПОЛНИТЕЛЬНОЕ ВРЕМЯ ДОХОДИТ ДО СЕРВЕРА');
  S.начатьЗабег();
  ИГРА.игрок.неуязвим = 999;
  ИГРА.время = S.БАЛАНС.длинаЗабега;
  ИГРА.дополнительное = 240;                 // четыре минуты в финале
  ИГРА.уровень = 32;                         // столько без финала не принял бы
  ИГРА.убито = 4900;                         // и столько тоже
  const былоДоФинала = запросы.length;
  S.завершитьЗабег(true);
  await подождать(); await подождать();

  // последним уходит GET за топом, поэтому ищем именно отправку результата
  const постФинала = запросы.filter(з => з.метод === 'POST').pop();
  const финал = JSON.parse(постФинала.тело);
  проверка('забег финалиста ушёл на сервер', запросы.length > былоДоФинала);
  проверка('в теле есть дополнительное время', финал.доп === 240, финал.доп);
  проверка('время в теле не больше длины забега',
           финал.время <= S.БАЛАНС.длинаЗабега, финал.время);
  проверка('сервер принял финалиста с 4900 убитых и уровнем 32',
           ИГРА.мировойСтатус === 'есть' && ИГРА.мировоеМесто > 0,
           ИГРА.мировойСтатус + ' место ' + ИГРА.мировоеМесто);

  console.log('\n=== ' + (всего - провалов) + ' из ' + всего + ' проверок пройдено ===');
  process.exit(провалов ? 1 : 0);
})();
