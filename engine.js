/* Прокрутка длинных списков: что нового и мировой топ. Живёт только на этих
   экранах: в бою колесо не должно делать ничего вообще.

   Один механизм на два экрана намеренно. Мировой топ приезжает на 50 записей
   и в окно не влезает никогда, а прокрутка пальцем и колесом здесь уже
   отлажена — второй, свой, разъехался бы с этим при первой же правке. */
const СПИСКИ = ['изменения', 'топ'];
function списочныйЭкран() { return СПИСКИ.indexOf(ИГРА.экран) >= 0; }

function прокрутитьСписок(на) {
  const видно = ЭКР.в - 74 * ЭКР.uiМасштаб - 78;
  if (ИГРА.экран === 'топ') {
    const предел = Math.max(0, ИГРА.высотаТопа - видно);
    ИГРА.прокруткаТопа = зажать(ИГРА.прокруткаТопа + на, 0, предел);
    return;
  }
  const предел = Math.max(0, ИГРА.высотаИзменений - видно);
  ИГРА.прокруткаИзменений = зажать(ИГРА.прокруткаИзменений + на, 0, предел);
}
// прежнее имя: на него ссылаются тесты и старые вызовы
function прокрутитьИзменения(на) { прокрутитьСписок(на); }
канвас.addEventListener('wheel', (e) => {
  if (!списочныйЭкран()) return;
  e.preventDefault();
  прокрутитьСписок(e.deltaY);
}, { passive: false });

/* ==========================================================================
   ТАЧ-ВВОД: плавающий джойстик
   Касание в любом месте создаёт стик там, где палец. Никаких фиксированных
   зон: на телефоне игрок не глядя кладёт палец куда удобно.
   ========================================================================== */
const джойстик = {
  активен: false, ид: null,
  базаX: 0, базаY: 0, x: 0, y: 0,
  дx: 0, дy: 0,
  радиус: 78, мёртваяЗона: 12
};

if (МОБИЛЬНЫЙ) БАЛАНС.потолокВрагов = 150;   // телефон 300 врагов не вывезет

function точкаКасания(t) {
  const r = канвас.getBoundingClientRect();
  return { x: t.clientX - r.left, y: t.clientY - r.top };
}

function пересчитатьДжойстик() {
  const дx = джойстик.x - джойстик.базаX;
  const дy = джойстик.y - джойстик.базаY;
  const д = Math.hypot(дx, дy);
  if (д < джойстик.мёртваяЗона) { джойстик.дx = 0; джойстик.дy = 0; return; }
  джойстик.дx = дx / д;
  джойстик.дy = дy / д;
}

канвас.addEventListener('touchstart', (e) => {
  e.preventDefault();
  разбудитьЗвук();                     // iOS даёт звук только по жесту пользователя
  const t = e.changedTouches[0];
  const п = точкаКасания(t);

  /* Список изменений тянется пальцем. Клик по нему тоже нужен (кнопка
     НАЗАД), поэтому засчитываем его на отпускании — если палец почти
     не двигался. */
  if (списочныйЭкран()) {
    мышь.x = п.x; мышь.y = п.y;
    тягаСписка.активна = true; тягаСписка.ид = t.identifier;
    тягаСписка.y = п.y; тягаСписка.сдвиг = 0;
    return;
  }

  // на экранах меню касание работает как клик по кнопке
  if (ИГРА.экран !== 'бой') { мышь.x = п.x; мышь.y = п.y; мышь.клик = true; return; }

  джойстик.активен = true; джойстик.ид = t.identifier;
  джойстик.базаX = п.x; джойстик.базаY = п.y;
  джойстик.x = п.x; джойстик.y = п.y;
  джойстик.дx = 0; джойстик.дy = 0;
}, { passive: false });

канвас.addEventListener('touchmove', (e) => {
  e.preventDefault();
  if (тягаСписка.активна) {
    for (const t of e.changedTouches) {
      if (t.identifier !== тягаСписка.ид) continue;
      const п = точкаКасания(t);
      прокрутитьСписок(тягаСписка.y - п.y);
      тягаСписка.сдвиг += Math.abs(тягаСписка.y - п.y);
      тягаСписка.y = п.y;
      мышь.x = п.x; мышь.y = п.y;
    }
    return;
  }
  if (!джойстик.активен) return;
  for (const t of e.changedTouches) {
    if (t.identifier !== джойстик.ид) continue;
    const п = точкаКасания(t);
    джойстик.x = п.x; джойстик.y = п.y;
    // база подтягивается, если палец ушёл дальше радиуса — стик не «залипает»
    const дx = джойстик.x - джойстик.базаX, дy = джойстик.y - джойстик.базаY;
    const д = Math.hypot(дx, дy);
    if (д > джойстик.радиус) {
      джойстик.базаX = джойстик.x - (дx / д) * джойстик.радиус;
      джойстик.базаY = джойстик.y - (дy / д) * джойстик.радиус;
    }
    пересчитатьДжойстик();
  }
}, { passive: false });

// палец, тянущий список изменений
const тягаСписка = { активна: false, ид: null, y: 0, сдвиг: 0 };

function отпуститьДжойстик(e) {
  if (e) e.preventDefault();
  if (тягаСписка.активна) {
    // почти не двигался — значит это был тап по кнопке, а не прокрутка
    if (тягаСписка.сдвиг < 10) мышь.клик = true;
    тягаСписка.активна = false; тягаСписка.ид = null;
  }
  джойстик.активен = false; джойстик.ид = null;
  джойстик.дx = 0; джойстик.дy = 0;
}
