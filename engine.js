/* Зум мира. На узком экране аноны в масштабе 1:1 превращаются в точки,
   поэтому чем уже экран, тем крупнее мир. Ограничения с двух сторон:
   снизу — фигура игрока не меньше 1/9 высоты экрана (требование ТЗ),
   сверху — не крупнее 1/4.5, иначе в альбомной ориентации персонаж
   занимает пол-экрана и не видно, откуда бегут. */
const ЗУМ = {
  опора: 760,        // ширина, с которой начинается увеличение
  максимум: 1.7,
  доляСнизу: 9,
  доляСверху: 4.5
};

function пересчитатьЗум() {
  const высотаИгрока = 192 * МАСШТАБ_МИРА;          // спрайт Ильи в мировых px
  const желаемый = зажать(ЗУМ.опора / Math.max(1, Math.min(ЭКР.ш, ЭКР.в)), 1, ЗУМ.максимум);
  const потолок  = (ЭКР.в / ЗУМ.доляСверху) / высотаИгрока;
  const пол      = (ЭКР.в / ЗУМ.доляСнизу)  / высотаИгрока;
  ЭКР.зум = зажать(Math.max(желаемый, пол), 1, Math.max(1, потолок));
}

// Мир -> экран с учётом зума. Нужно всему, что живёт в экранных координатах:
// стрелке к клетке, взлетающему нику, проверке «в кадре ли».
function мирВЭкранX(x) { return (x - ИГРА.камера.x - ЭКР.ш / 2) * ЭКР.зум + ЭКР.ш / 2; }
function мирВЭкранY(y) { return (y - ИГРА.камера.y - ЭКР.в / 2) * ЭКР.зум + ЭКР.в / 2; }

function пересчитатьРазмер() {
  ЭКР.дпр = Math.min(window.devicePixelRatio || 1, 2);   // выше 2 смысла нет, только жрёт
  // Сначала размеры, и только потом всё, что от них считается:
  // раньше масштаб интерфейса и зум брались от прошлых значений.
  ЭКР.ш = window.innerWidth;
  ЭКР.в = window.innerHeight;
  ЭКР.диагональ = Math.hypot(ЭКР.ш, ЭКР.в);
  // На узком экране интерфейс крупнее: с телефона в руке цифры должны читаться
  ЭКР.uiМасштаб = зажать(1150 / Math.max(ЭКР.ш, 1), 1, 1.85);
  пересчитатьЗум();
  канвас.width  = Math.round(ЭКР.ш * ЭКР.дпр);
  канвас.height = Math.round(ЭКР.в * ЭКР.дпр);
  кт.setTransform(ЭКР.дпр, 0, 0, ЭКР.дпр, 0, 0);
  кт.imageSmoothingEnabled = true;
  кт.imageSmoothingQuality = 'high';
}
