// Короткий шумовой щелчок: он даёт удару «мясо», одним осциллятором не выйдет.
let буферШума = null;
function шум(длина, громкость, частотаФильтра, t0) {
  if (!аудио) return;
  if (!буферШума) {
    const кадров = Math.floor(аудио.sampleRate * 0.4);
    буферШума = аудио.createBuffer(1, кадров, аудио.sampleRate);
    const данные = буферШума.getChannelData(0);
    for (let i = 0; i < кадров; i++) данные[i] = Math.random() * 2 - 1;
  }
  const ист = аудио.createBufferSource();
  ист.buffer = буферШума;
  const фильтр = аудио.createBiquadFilter();
  фильтр.type = 'lowpass';
  фильтр.frequency.setValueAtTime(частотаФильтра, t0);
  фильтр.frequency.exponentialRampToValueAtTime(Math.max(80, частотаФильтра * 0.25), t0 + длина);
  const гейн = аудио.createGain();
  гейн.gain.setValueAtTime(громкость, t0);
  гейн.gain.exponentialRampToValueAtTime(0.0001, t0 + длина);
  ист.connect(фильтр).connect(гейн).connect(мастерЗвука || аудио.destination);
  ист.start(t0); ист.stop(t0 + длина + 0.02);
}

function тон(форма, от, до, длина, громкость, t0) {
  const осц = аудио.createOscillator();
  const гейн = аудио.createGain();
  осц.type = форма;
  осц.frequency.setValueAtTime(Math.max(20, от), t0);
  осц.frequency.exponentialRampToValueAtTime(Math.max(20, до), t0 + длина);
  гейн.gain.setValueAtTime(громкость, t0);
  гейн.gain.exponentialRampToValueAtTime(0.0001, t0 + длина);
  осц.connect(гейн).connect(мастерЗвука || аудио.destination);
  осц.start(t0); осц.stop(t0 + длина + 0.02);
}

function звук(имя, сдвигТона = 1) {
  if (!аудио || аудио.state !== 'running') return;
  if (проиграть(имя)) return;          // на это имя есть файл — играем его
  const t = аудио.currentTime;

  /* Три звука собраны вручную — по отзыву «советую звуки другие».
     Остальные остаются простыми биперами из таблицы. */
  if (имя === 'попадание') {
    // низкий удар плюс короткий шумовой щелчок сверху
    тон('sine', 190 * сдвигТона, 60 * сдвигТона, 0.09, 0.16, t);
    тон('square', 380 * сдвигТона, 150 * сдвигТона, 0.04, 0.05, t);
    шум(0.05, 0.10, 2600 * сдвигТона, t);
    return;
  }
  if (имя === 'смертьВрага') {
    // глуше: мягкий низ и придушенный шум, без писка
    тон('sine', 150 * сдвигТона, 48 * сдвигТона, 0.16, 0.13, t);
    шум(0.11, 0.07, 900 * сдвигТона, t);
    return;
  }
  if (имя === 'бульк') {
    /* Глоток: два коротких низких «бульпа» с быстрым подъёмом тона —
       так ухо слышит именно бутылку, а не очередной бипер. */
    тон('sine', 150 * сдвигТона, 420 * сдвигТона, 0.09, 0.16, t);
    тон('sine', 120 * сдвигТона, 360 * сдвигТона, 0.10, 0.13, t + 0.11);
    шум(0.05, 0.04, 700 * сдвигТона, t + 0.02);
    return;
  }
  if (имя === 'левелап') {
    // восходящий аккорд вместо писка: до-ми-соль-до
    const ноты = [523.25, 659.25, 783.99, 1046.5];
    ноты.forEach((ч, i) => тон('triangle', ч, ч, 0.30 - i * 0.03, 0.10, t + i * 0.055));
    тон('sine', 261.6, 261.6, 0.42, 0.07, t);
    return;
  }

  const с = ЗВУКИ[имя];
  if (!с) return;
  тон(с.форма, с.от * сдвигТона, с.до * сдвигТона, с.длина, с.громкость, t);
}


