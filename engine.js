function хеш(x, y) {
  let h = x * 374761393 + y * 668265263;
  h = (h ^ (h >> 13)) * 1274126177;
  return ((h ^ (h >> 16)) >>> 0) / 4294967295;
}

// --- Текст с обводкой: должен читаться поверх хаоса из спрайтов ---
function текст(строка, x, y, о = {}) {
  const размер = о.размер || 18;
  кт.font = (о.вес || '800') + ' ' + размер + 'px system-ui, "Segoe UI", Roboto, Arial, sans-serif';
  кт.textAlign = о.выравн || 'left';
  кт.textBaseline = о.базовая || 'top';
  if (о.обводка !== false) {
    кт.lineWidth = о.толщинаОбводки || Math.max(3, размер * 0.22);
    кт.lineJoin = 'round';
    кт.strokeStyle = о.цветОбводки || ЦВЕТ.обводка;
    кт.strokeText(строка, x, y);
  }
  кт.fillStyle = о.цвет || ЦВЕТ.текст;
  кт.fillText(строка, x, y);
}

function ширинаТекста(строка, размер = 18, вес = '800') {
  кт.font = вес + ' ' + размер + 'px system-ui, "Segoe UI", Roboto, Arial, sans-serif';
  return кт.measureText(строка).width;
}

function скруглённыйПрямоугольник(x, y, ш, в, r) {
  кт.beginPath();
  кт.moveTo(x + r, y);
  кт.arcTo(x + ш, y,     x + ш, y + в, r);
  кт.arcTo(x + ш, y + в, x,     y + в, r);
  кт.arcTo(x,     y + в, x,     y,     r);
  кт.arcTo(x,     y,     x + ш, y,     r);
  кт.closePath();
}


