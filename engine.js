/* localStorage бывает недоступен: песочница iframe, приватный режим,
   иногда file://. Тогда держим данные в памяти — забег хотя бы покажет
   свою таблицу, а не пустоту. */
const памятьХранилища = {};
let хранилищеРаботает = true;

function хранЧитать(ключ) {
  if (хранилищеРаботает) {
    try { return localStorage.getItem(ключ); }
    catch (e) { хранилищеРаботает = false; }
  }
  return памятьХранилища[ключ] !== undefined ? памятьХранилища[ключ] : null;
}
/* Возвращает, доехало ли значение до НАСТОЯЩЕГО хранилища.

   Раньше функция молча возвращала undefined, и вызывающий не мог отличить
   «сохранил» от «сохранил в память, которая умрёт с вкладкой». Для рекорда
   это терпимо, для шкафа со скинами — нет: игрок крутит колесо, забирает
   скин, перезагружает страницу и не находит его, причём без единого слова
   объяснения. Молчащая ошибка — худший вид ошибки. */
function хранПисать(ключ, значение) {
  памятьХранилища[ключ] = значение;
  if (!хранилищеРаботает) return false;
  try { localStorage.setItem(ключ, значение); return true; }
  catch (e) { хранилищеРаботает = false; return false; }
}

