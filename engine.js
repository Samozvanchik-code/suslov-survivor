function поднятьМетрику() {
  if (!НОМЕР_МЕТРИКИ) return;
  try {
    (function(m,e,t,r,i,k,a){
      m[i] = m[i] || function(){ (m[i].a = m[i].a || []).push(arguments); };
      m[i].l = 1 * new Date();
      k = e.createElement(t); a = e.getElementsByTagName(t)[0];
      k.async = 1; k.src = r; a.parentNode.insertBefore(k, a);
    })(window, document, 'script', 'https://mc.yandex.ru/metrika/tag.js', 'ym');
    window.ym(НОМЕР_МЕТРИКИ, 'init', {
      clickmap: true, trackLinks: true, accurateTrackBounce: true
    });
  } catch (e) {}
}

function отправитьСобытие(имя, данные) {
  try {
    if (!НОМЕР_МЕТРИКИ || typeof window.ym !== 'function') return;
    window.ym(НОМЕР_МЕТРИКИ, 'reachGoal', имя, данные || {});
  } catch (e) {}          // аналитика не имеет права ронять забег
}

