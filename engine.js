let кадровВОкне = 0, окноНачало = 0;

function кадр(сейчас) {
  requestAnimationFrame(кадр);

  кадровВОкне++;
  if (сейчас - окноНачало >= 500) {
    ИГРА.fps = Math.round(кадровВОкне * 1000 / (сейчас - окноНачало));
    кадровВОкне = 0; окноНачало = сейчас;
  }
  let дельта = (сейчас - прошлое) / 1000;
  прошлое = сейчас;
  if (дельта > 0.25) дельта = 0.25;
  // короткое замедление в момент спасения
  let темп = ИГРА.множительВремени;
  if (ИГРА.замедление > 0) { ИГРА.замедление -= дельта; темп *= 0.25; }
  накопитель += дельта * темп;
  const пределШагов = 8 * ИГРА.множительВремени;
  void темп;
  let защита = 0;
  while (накопитель >= ШАГ && защита < пределШагов) { шагЛогики(ШАГ); накопитель -= ШАГ; защита++; }

  кт.imageSmoothingEnabled = true;
  if (ИГРА.экран === 'загрузка')      экранЗагрузки();
  else if (ИГРА.экран === 'старт')    экранСтарта();
  else if (ИГРА.экран === 'левелап')  экранЛевелапа();
  else if (ИГРА.экран === 'замена')   экранЗамены();
  else if (ИГРА.экран === 'итоги')    экранИтогов();
  else { нарисоватьМир(); нарисоватьИнтерфейс(); нарисоватьСпасение(); нарисоватьДжойстик(); кнопки = []; }
  обновитьСсылку();
  обработатьКлик();
}

