const случ      = (a, b) => a + Math.random() * (b - a);
const изМассива = (м) => м[Math.floor(Math.random() * м.length)];
const зажать    = (v, a, b) => v < a ? a : (v > b ? b : v);
const дистанция = (ax, ay, bx, by) => Math.hypot(ax - bx, ay - by);

const канвас = document.getElementById('экран');
const кт = канвас.getContext('2d', { alpha: false });

/* Мобильный режим определяем по типу указателя, а не по строке браузера:
   строку подделывают, а coarse-pointer честно говорит, что тыкают пальцем.
   ?mobile=1 в адресе форсирует режим для проверки с настольного браузера. */
const МОБИЛЬНЫЙ = (window.matchMedia && window.matchMedia('(pointer: coarse)').matches)
                  || /[?&]mobile=1/.test(location.search);

const ЭКР = { ш: 800, в: 450, дпр: 1, диагональ: 918, uiМасштаб: 1, зум: 1 };

/* Зум мира выводится из ОБЗОРА, а не из размера фигуры игрока.

   Раньше ориентиром была высота Ильи на экране («не меньше 1/9»), и это
   был неверный ориентир: на телефоне он давал зум до 1.7, камера прижималась
   вплотную, и игрок не видел, что на него летит. Жалоба «камера слишком
   близко» повторялась даже после первой правки, потому что правили не то.

   Теперь условие простое и проверяемое: в КАЖДУЮ сторону от игрока должно
   быть видно минимум ЗУМ.обзор мировых пикселей. Камера центрирована на
   игроке, значит половина экрана в мировых координатах — это (ЭКР/2)/зум,
   и она обязана быть не меньше обзора. Отсюда потолок зума:

       (min(ш, в) / 2) / зум >= обзор     =>     зум <= min(ш, в) / (2*обзор)

   Ограничение считается по УЗКОЙ стороне: если брать по широкой, в портрете
   сверху и снизу обзора не хватит, а прилетает именно оттуда. */
const ЗУМ = {
  обзор: 300,        // мировых пикселей вокруг игрока в каждую сторону
  /* 0.5 подобран под требование обзора: чтобы 300 px влезли в каждую
     сторону, нужен зум не выше ширина/600, и на экране в 300 px это ровно
     0.5. Ниже опускаться незачем — там аноны становятся точками. */
  минимум: 0.5,
  максимум: 1.7      // выше — незачем: обзора и так с запасом
};

function пересчитатьЗум() {
  const узкаяСторона = Math.max(1, Math.min(ЭКР.ш, ЭКР.в));
  const потолокОбзора = узкаяСторона / (2 * ЗУМ.обзор);
  /* Приближать сверх единицы можно только если обзор это позволяет:
     на большом мониторе мир мелковат, там лёгкое приближение уместно. */
  ЭКР.зум = зажать(Math.min(1, потолокОбзора), ЗУМ.минимум, ЗУМ.максимум);
}

// Сколько мировых пикселей видно от игрока в каждую сторону. Нужно тестам
// и отладке: одно число вместо пересчёта формулы в трёх местах.
function обзорВокругИгрока() {
  return {
    поГоризонтали: (ЭКР.ш / 2) / ЭКР.зум,
    поВертикали:   (ЭКР.в / 2) / ЭКР.зум
  };
}

// Мир -> экран с учётом зума. Нужно всему, что живёт в экранных координатах:
// стрелке к клетке, взлетающему нику, проверке «в кадре ли».
function мирВЭкранX(x) { return (x - ИГРА.камера.x - ЭКР.ш / 2) * ЭКР.зум + ЭКР.ш / 2; }
function мирВЭкранY(y) { return (y - ИГРА.камера.y - ЭКР.в / 2) * ЭКР.зум + ЭКР.в / 2; }

function пересчитатьРазмер() {
  ЭКР.дпр = Math.min(window.devicePixelRatio || 1, 2);   // выше 2 смысла нет, только жрёт
  // Сначала размеры, и только потом всё, что от них считается:
  // раньше масштаб интерфейса и зум брались от прошлых значений.
  ЭКР.ш = window.innerWidth;
  ЭКР.в = window.innerHeight;
  ЭКР.диагональ = Math.hypot(ЭКР.ш, ЭКР.в);
  // На узком экране интерфейс крупнее: с телефона в руке цифры должны читаться
  ЭКР.uiМасштаб = зажать(1150 / Math.max(ЭКР.ш, 1), 1, 1.85);
  пересчитатьЗум();
  канвас.width  = Math.round(ЭКР.ш * ЭКР.дпр);
  канвас.height = Math.round(ЭКР.в * ЭКР.дпр);
  кт.setTransform(ЭКР.дпр, 0, 0, ЭКР.дпр, 0, 0);
  кт.imageSmoothingEnabled = true;
  кт.imageSmoothingQuality = 'high';
}
window.addEventListener('resize', пересчитатьРазмер);
пересчитатьРазмер();


