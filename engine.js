/* Единственная точка входа для результата забега.
   Пишет локальный топ и, если задан адрес, шлёт на внешний рейтинг.
   Отправка никогда не блокирует игру: у части игроков блокировщики,
   и ожидание ответа означало бы, что у них игра просто не пойдёт. */
function отправитьРезультат(результат) {
  const строки = прочитатьТаблицу();
  строки.push(результат);
  строки.sort((a, b) => b.время - a.время);
  const топ = строки.slice(0, 10);
  хранПисать('суслов_таблица', JSON.stringify(топ));
  ИГРА.таблица = топ;
  ИГРА.местоВТаблице = топ.indexOf(результат);

  отправитьНаСервер(результат);
  return топ;
}

function отправитьНаСервер(результат) {
  if (!АДРЕС_РЕЙТИНГА) return;              // адрес не задан — работаем локально
  try {
    const тело = JSON.stringify(результат);
    // keepalive: результат уходит, даже если вкладку закрывают сразу после смерти
    if (navigator.sendBeacon) {
      navigator.sendBeacon(АДРЕС_РЕЙТИНГА, new Blob([тело], { type: 'application/json' }));
      return;
    }
    fetch(АДРЕС_РЕЙТИНГА, {
      method: 'POST', mode: 'cors', keepalive: true,
      headers: { 'Content-Type': 'application/json' }, body: тело
    }).catch(() => {});                      // молча: рейтинг не должен ронять забег
  } catch (e) {}
}

