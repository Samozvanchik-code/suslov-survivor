/* ГРОМКОСТЬ. Два независимых регулятора: звуки игры и музыка. Хранятся в
   localStorage — настройка звука относится к устройству, а не к забегу, и
   переспрашивать её каждый заход было бы издевательством.

   Звуки идут через один мастер-гейн, а не каждый в destination: иначе
   регулятор пришлось бы протаскивать в каждый вызов тона, шума и файла. */
const КЛЮЧ_ГРОМКОСТИ = 'суслов_громкость';
const ГРОМКОСТЬ = { звук: 1, музыка: 0.45 };

function загрузитьГромкость() {
  try {
    const с = JSON.parse(хранЧитать(КЛЮЧ_ГРОМКОСТИ) || 'null');
    if (с && typeof с === 'object') {
      if (isFinite(с.звук)) ГРОМКОСТЬ.звук = зажать(Number(с.звук), 0, 1);
      if (isFinite(с.музыка)) ГРОМКОСТЬ.музыка = зажать(Number(с.музыка), 0, 1);
    }
  } catch (e) { /* битая запись — остаются значения по умолчанию */ }
}

function сохранитьГромкость() {
  хранПисать(КЛЮЧ_ГРОМКОСТИ, JSON.stringify(ГРОМКОСТЬ));
}

function применитьГромкость() {
  if (мастерЗвука) мастерЗвука.gain.value = ГРОМКОСТЬ.звук;
  if (музыкаЭлемент) музыкаЭлемент.volume = ГРОМКОСТЬ.музыка;
}

function задатьГромкость(вид, значение) {
  ГРОМКОСТЬ[вид] = зажать(Number(значение) || 0, 0, 1);
  применитьГромкость();
  сохранитьГромкость();
  return ГРОМКОСТЬ[вид];
}

function разбудитьЗвук() {
  if (!аудио) {
    const AC = window.AudioContext || window.webkitAudioContext;
    if (AC) {
      аудио = new AC();
      try {
        мастерЗвука = аудио.createGain();
        мастерЗвука.gain.value = ГРОМКОСТЬ.звук;
        мастерЗвука.connect(аудио.destination);
      } catch (e) { мастерЗвука = null; }
    }
    расшифроватьЗвуки();          // ждали контекст, чтобы разжать скачанное
  }
  if (аудио && аудио.state === 'suspended') аудио.resume();
  // музыку тоже можно запускать только после жеста — браузеры иначе не дают
  обновитьМузыку();
}

/* ==========================================================================
   МУЗЫКА

   Обычный <audio>, а не WebAudio: нужен только зациклённый фон с громкостью,
   а тянуть трёхминутный трек в буфер и держать его разжатым в памяти телефона
   ради этого незачем.

   Сейчас трек ОДИН и играет везде. Раньше их было два — джингл в меню и
   отдельный боевой, — но боевой из проекта убрали, а ссылка на файл осталась,
   и в бою наступила полная тишина: файла нет, ошибка глотается молча (см.
   ниже, это осознанно), и заметить это можно только по 404 в сети.

   Поэтому оба вида смотрят на один файл. Заодно ушла причина, по которой
   боевой не качался на старте: качать нечего, трек уже в кэше после меню, и
   музыка в бою начинается мгновенно вместо паузы на загрузку четырёх
   мегабайт. Появится новый боевой трек — вернуть сюда вторую строку. */
const МУЗЫКА = {
  меню: 'sounds/music_sport.mp3',
  бой:  'sounds/music_sport.mp3'
};
let музыкаЭлемент = null;
let музыкаФайл = null;

function нуженВидМузыки() {
  const э = ИГРА.экран;
  if (э === 'бой' || э === 'левелап' || э === 'замена' || э === 'победа') return 'бой';
  if (э === 'загрузка') return null;
  return 'меню';
}

function обновитьМузыку() {
  if (typeof Audio !== 'function') return;      // тестовая среда без DOM-аудио
  const вид = нуженВидМузыки();
  if (!вид) return;
  /* Сравниваем ФАЙЛ, а не вид экрана. Пока трек один на всё, переход из меню
     в бой не должен дёргать музыку: по виду он выглядит как смена трека, и
     сравнение по виду перезапускало бы одну и ту же песню с нуля ровно в
     момент старта забега. */
  const файл = МУЗЫКА[вид];
  if (файл === музыкаФайл && музыкаЭлемент) {
    if (музыкаЭлемент.paused) музыкаЭлемент.play().catch(() => {});
    return;
  }
  try {
    if (музыкаЭлемент) { музыкаЭлемент.pause(); музыкаЭлемент.src = ''; }
    музыкаЭлемент = new Audio(файл);
    музыкаЭлемент.loop = true;
    музыкаЭлемент.volume = ГРОМКОСТЬ.музыка;
    музыкаФайл = файл;
    /* Ошибку глотаем молча: файла может не быть (кладутся руками), автоплей
       может быть запрещён до жеста, блокировщик может срезать запрос. Игра
       обязана работать без музыки так же, как работает без звука. */
    музыкаЭлемент.play().catch(() => {});
  } catch (e) { музыкаЭлемент = null; музыкаФайл = null; }
}

/* ==========================================================================
   ЗВУКОВЫЕ ФАЙЛЫ (голоса Суслова)

   Порядок такой: качаем файлы сразу при запуске, а РАЗЖИМАЕМ их только когда
   появится звуковой контекст. Контекст нельзя создать до первого касания или
   клика — браузеры это запрещают, а на iOS запрещают жёстко. Если качать и
   разжимать в одном месте, на телефоне не сыграет ничего.

   Ни одна ошибка тут не должна ломать игру: файла нет, сеть отвалилась,
   блокировщик срезал запрос, формат не поддержан — во всех случаях просто
   остаётся прежний бипер, а забег идёт дальше.
   ========================================================================== */
const сырыеЗвуки = {};        // имя -> ArrayBuffer, ждёт контекста
const буферыЗвука = {};       // имя -> AudioBuffer, готов к проигрыванию
let голосДо = 0;              // время, до которого занят голосовой канал

function загрузитьЗвуки() {
  if (typeof МАНИФЕСТ_ЗВУКОВ !== 'object' || typeof fetch !== 'function') return;
  for (const имя in МАНИФЕСТ_ЗВУКОВ) {
    const запись = МАНИФЕСТ_ЗВУКОВ[имя];
    try {
      const ответ = fetch(запись.файл);
      if (!ответ || typeof ответ.then !== 'function') continue;
      ответ.then((о) => {
        if (!о || !о.ok || typeof о.arrayBuffer !== 'function') return null;
        return о.arrayBuffer();
      }).then((байты) => {
        if (!байты) return;
        сырыеЗвуки[имя] = байты;
        расшифроватьЗвуки();
      }).catch(() => {});
    } catch (e) {}
  }
}

function расшифроватьЗвуки() {
  if (!аудио || typeof аудио.decodeAudioData !== 'function') return;
  for (const имя in сырыеЗвуки) {
    const байты = сырыеЗвуки[имя];
    delete сырыеЗвуки[имя];                 // вторая попытка не нужна
    try {
      /* Старый Safari умеет только форму с колбэками и возвращает undefined
         вместо обещания — поддерживаем оба вида, иначе на части айфонов
         голоса молча не заведутся. */
      const итог = аудио.decodeAudioData(байты,
        (буфер) => { буферыЗвука[имя] = буфер; },
        () => {});
      if (итог && typeof итог.then === 'function') {
        итог.then((буфер) => { буферыЗвука[имя] = буфер; }).catch(() => {});
      }
    } catch (e) {}
  }
}

/* Проиграть файл. Возвращает true, если сыграл — тогда звук() не добавляет
   поверх свой бипер.

   Голосовой канал ОДИН. Две реплики разом звучат как сломанная игра, а не
   как два события: слов не разобрать ни в одной. Пока предыдущая не
   закончилась, новую пропускаем — кроме «главных» (победа, смерть), они
   обрывают текущую, потому что важнее всего, что было сказано последним. */
function проиграть(имя) {
  const запись = (typeof МАНИФЕСТ_ЗВУКОВ === 'object') ? МАНИФЕСТ_ЗВУКОВ[имя] : null;
  if (!запись) return false;
  const буфер = буферыЗвука[имя];
  if (!буфер || !аудио || аудио.state !== 'running') return false;

  const сейчас = аудио.currentTime;
  if (запись.голос) {
    if (!запись.главный && сейчас < голосДо) return true;   // канал занят
    if (запись.шансГолоса !== undefined && Math.random() > запись.шансГолоса) return true;
    голосДо = сейчас + буфер.duration;
  }
  try {
    const ист = аудио.createBufferSource();
    const гейн = аудио.createGain();
    ист.buffer = буфер;
    гейн.gain.value = запись.громкость === undefined ? 0.9 : запись.громкость;
    ист.connect(гейн).connect(мастерЗвука || аудио.destination);
    ист.start(сейчас);
  } catch (e) { return false; }
  return true;
}

