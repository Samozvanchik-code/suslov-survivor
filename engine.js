/* Игра внутри рамки? Обращение к window.top на чужом домене само по себе
   безопасно, но перестраховываемся: если доступ закрыт, считаем, что
   встроены — это более осторожное предположение. */
const ВСТРОЕНО = (() => {
  try { return window.self !== window.top; } catch (e) { return true; }
})();

const кнопкаФС = document.getElementById('fs');

/* Умеет ли браузер полный экран для обычных элементов.

   Проверяем ВОЗМОЖНОСТЬ, а не строку браузера. На iPhone Fullscreen API не
   работает ни для чего, кроме видео, и там requestFullscreen у элемента
   просто отсутствует — проверка это и поймает, без разбора userAgent,
   который врёт и меняется. */
function полныйЭкранДоступен() {
  const к = document.documentElement;
  return !!(к && (к.requestFullscreen || к.webkitRequestFullscreen));
}

function вПолномЭкране() {
  return !!(document.fullscreenElement || document.webkitFullscreenElement);
}

/* Сообщение наверх. Родительский сайт по нему растягивает рамку сам —
   это единственный путь на iPhone, где Fullscreen API недоступен.
   Отправка наша, приём — забота встраивающего сайта. */
function сообщитьНаверх(вкл) {
  try {
    if (window.parent && window.parent !== window) {
      window.parent.postMessage({ type: 'suslov-fullscreen', on: !!вкл }, '*');
    }
  } catch (e) {}          // родитель может быть недоступен — это не наша беда
}

function переключитьПолныйЭкран() {
  const хотим = !вПолномЭкране();
  сообщитьНаверх(хотим);                  // шлём всегда, даже если умеем сами

  if (!полныйЭкранДоступен()) return;     // iPhone: остаётся только сообщение
  try {
    if (хотим) {
      const к = document.documentElement;
      (к.requestFullscreen || к.webkitRequestFullscreen).call(к);
    } else {
      (document.exitFullscreen || document.webkitExitFullscreen).call(document);
    }
  } catch (e) {}
  /* Размеры меняются не мгновенно. Событие fullscreenchange ловим ниже, но
     в части браузеров оно приходит ДО фактического ресайза, поэтому там же
     подстраховываемся отложенным пересчётом. */
}

