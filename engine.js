/* Кнопка видна ВСЕГДА, на любом экране, включая бой.

   Сначала её не было в бою — из осторожности: на телефоне угол экрана это
   зона джойстика, и кнопка там съедает касание. Практика оказалась сильнее
   осторожности: играют внутри рамки на чужом сайте, и решение «развернуть»
   приходит уже в бою, когда мелко. Уходить для этого на экран смерти —
   абсурд.

   Плата за это: на телефоне правый верхний угол размером 42 px перестаёт
   быть зоной джойстика. Угол выбран как наименее используемый — палец
   держат ниже и левее.

   Скрывается кнопка только когда она бесполезна: браузер не умеет полный
   экран И игра не в рамке (то есть некому даже отправить сообщение). */
function обновитьКнопкуФС() {
  if (!кнопкаФС) return;
  const полезна = ИГРА.экран !== 'загрузка' &&
                  (полныйЭкранДоступен() || ВСТРОЕНО);
  const нужно = полезна ? 'block' : 'none';
  if (кнопкаФС.style.display !== нужно) кнопкаФС.style.display = нужно;

  // в бою приглушаем: кнопка не должна спорить со счётчиком и с боем
  const вБою = ИГРА.экран === 'бой';
  if (кнопкаФС._вбою !== вБою) {
    кнопкаФС._вбою = вБою;
    if (кнопкаФС.classList) кнопкаФС.classList.toggle('вбою', вБою);
  }
}

/* ФОКУС КЛАВИАТУРЫ.

   Внутри рамки события клавиш приходят игре только когда фокус внутри неё.
   Ставим фокус на канвас при загрузке и при каждом касании или клике. */
function вернутьФокус() {
  try { канвас.focus({ preventScroll: true }); } catch (e) {
    try { канвас.focus(); } catch (e2) {}
  }
}

/* Есть ли у игры фокус клавиатуры. document.hasFocus() отвечает за весь
   документ рамки — этого достаточно: если фокус ушёл на родительскую
   страницу, стрелки уходят туда же. */
function фокусЕсть() {
  try {
    if (document.hasFocus && !document.hasFocus()) return false;
  } catch (e) {}
  return true;
}

/* Нужна ли плашка «КЛИКНИ, ЧТОБЫ ИГРАТЬ».

   Только для встроенной игры: на отдельной странице фокус и так на ней, и
   плашка была бы ложной тревогой. И только когда фокуса действительно нет —
   иначе это реклама поверх собственной игры. */
function нуженПризывКликнуть() {
  return ВСТРОЕНО && !фокусЕсть();
}

канвас.addEventListener('mousedown', вернутьФокус);
канвас.addEventListener('touchstart', вернутьФокус, { passive: true });
window.addEventListener('focus', вернутьФокус);

