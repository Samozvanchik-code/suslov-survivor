/* Пол печём один раз в офскрин-холст и дальше кладём паттерном.
   Иначе каждый кадр уходило ~600 отдельных заливок только на крапины,
   а при 200+ врагах на экране этот бюджет нужен на спрайты.
   Блок 4x4 клетки: шахматка при чётном размере блока стыкуется без шва. */
const ПЛИТКА = 128, БЛОК = 4, ПЕРИОД = ПЛИТКА * БЛОК;
let полПаттерн = null;

function построитьПол() {
  const холст = document.createElement('canvas');
  холст.width = холст.height = ПЕРИОД;
  const к = холст.getContext('2d');
  for (let тx = 0; тx < БЛОК; тx++) {
    for (let тy = 0; тy < БЛОК; тy++) {
      к.fillStyle = ((тx + тy) & 1) ? ЦВЕТ.полСветлый : ЦВЕТ.полТёмный;
      к.fillRect(тx * ПЛИТКА, тy * ПЛИТКА, ПЛИТКА, ПЛИТКА);
      к.fillStyle = ЦВЕТ.крапина;
      for (let с = 0; с < 5; с++) {
        const рx = хеш(тx * 7 + с, тy * 13), рy = хеш(тx * 13, тy * 7 + с);
        const р = 1 + хеш(тx + с, тy) * 2;
        к.fillRect(тx * ПЛИТКА + рx * ПЛИТКА, тy * ПЛИТКА + рy * ПЛИТКА, р, р);
      }
    }
  }
  полПаттерн = кт.createPattern(холст, 'repeat');
}

function нарисоватьПол(кx, кy) {
  if (!полПаттерн) построитьПол();
  const сдвигX = -(((кx % ПЕРИОД) + ПЕРИОД) % ПЕРИОД);
  const сдвигY = -(((кy % ПЕРИОД) + ПЕРИОД) % ПЕРИОД);
  кт.save();
  кт.translate(сдвигX, сдвигY);
  кт.fillStyle = полПаттерн;
  кт.fillRect(0, 0, ЭКР.ш - сдвигX + ПЕРИОД, ЭКР.в - сдвигY + ПЕРИОД);
  кт.restore();
}

/* Кристалл со свечением — один запечённый канвас. Их на экране бывает под
   сотню, и отдельная заливка свечения на каждый обходится дороже самого блита. */
let холстКристалла = null;
function готовыйКристалл() {
  if (холстКристалла) return холстКристалла;
  const г = габариты('item_xp');
  const с = СПРАЙТ.item_xp;
  const ш = Math.ceil(г.ш) + 8, в = Math.ceil(г.в) + 8;
  const холст = document.createElement('canvas');
  холст.width = ш; холст.height = в;
  const к = холст.getContext('2d');
  к.imageSmoothingEnabled = true;
  к.imageSmoothingQuality = 'high';
  к.globalAlpha = 0.35;
  к.fillStyle = ЦВЕТ.опыт;
  к.beginPath();
  к.ellipse(ш / 2, в / 2 + г.в * 0.15, г.ш * 0.5, г.ш * 0.22, 0, 0, Math.PI * 2);
  к.fill();
  к.globalAlpha = 1;
  if (с && с.готов) к.drawImage(с.картинка, (ш - г.ш) / 2, (в - г.в) / 2, г.ш, г.в);
  else { к.fillStyle = ЦВЕТ.опыт; к.fillRect(ш / 2 - 5, в / 2 - 7, 10, 14); }
  холстКристалла = { холст, полуШ: ш / 2, полуВ: в / 2 };
  return холстКристалла;
}

function нарисоватьКристалл(к, кx, кy) {
  const г = готовыйКристалл();
  const парение = Math.sin(к.фаза) * 3;
  кт.drawImage(г.холст, (к.x - кx - г.полуШ) | 0, (к.y - кy + парение - г.полуВ) | 0);
}

