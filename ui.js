function форматВремени(сек) {
  const м = Math.floor(сек / 60), с = Math.floor(сек % 60);
  return м + ':' + (с < 10 ? '0' : '') + с;
}

function полоска(x, y, ш, в, доля, цвет, фон, r = 5) {
  кт.fillStyle = фон;
  скруглённыйПрямоугольник(x, y, ш, в, r); кт.fill();
  const д = зажать(доля, 0, 1);
  if (д > 0) {
    кт.save();
    скруглённыйПрямоугольник(x, y, ш, в, r); кт.clip();
    кт.fillStyle = цвет;
    кт.fillRect(x, y, ш * д, в);
    кт.restore();
  }
  кт.strokeStyle = 'rgba(0,0,0,0.55)'; кт.lineWidth = 2;
  скруглённыйПрямоугольник(x, y, ш, в, r); кт.stroke();
}

// Иконка апгрейда: спрайт, если он есть, иначе цветной кружок с буквой.
