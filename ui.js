function нарисоватьМир() {
  const тx = ИГРА.тряска > 0 ? случ(-ИГРА.тряска, ИГРА.тряска) : 0;
  const тy = ИГРА.тряска > 0 ? случ(-ИГРА.тряска, ИГРА.тряска) : 0;
  const кx = ИГРА.камера.x + тx, кy = ИГРА.камера.y + тy;

  // Зум применяем ко всему миру одним трансформом. Интерфейс рисуется
  // отдельно и в экранных координатах, поэтому его это не задевает.
  const зум = ЭКР.зум;
  /* Качка от белуги: плавный крен и снос, отдельный трансформ поверх зума.
     Затухает сам, поэтому в конце эффекта картинка возвращается ровно. */
  const качка = ИГРА.качка > 0;
  if (зум !== 1 || качка) {
    кт.save();
    кт.translate(ЭКР.ш / 2, ЭКР.в / 2);
    if (зум !== 1) кт.scale(зум, зум);
    if (качка) {
      const сила = ИГРА.качка / 0.4;                 // 1 в начале, 0 в конце
      const ф = ИГРА.времяВсего * 11;
      кт.rotate(Math.sin(ф) * 0.035 * сила);
      кт.translate(Math.sin(ф * 0.7) * 14 * сила, Math.cos(ф) * 6 * сила);
    }
    кт.translate(-ЭКР.ш / 2, -ЭКР.в / 2);
  }

  нарисоватьПол(кx, кy);

  for (const к of ИГРА.кристаллы) {
    if (наЭкране(к.x, к.y, 60)) нарисоватьКристалл(к, кx, кy);
  }

  // Сортировка по Y: кто ниже — тот ближе к камере и рисуется поверх.
  // Массив переиспользуем, чтобы не выделять его заново каждый кадр.
  порядок.length = 0;
  const враги = ИГРА.враги;
  for (let i = 0; i < враги.length; i++) {
    const в = враги[i];
    if (наЭкране(в.x, в.y, 220)) { в._сорт = в.y; в._вид = 0; порядок.push(в); }
  }
  const и = ИГРА.игрок;
  /* Свита сортируется по глубине вместе с врагами, но её ключ подрезан по
     игроку: спутник никогда не рисуется поверх Ильи, даже стоя ниже него. */
  const потолокСвиты = и.y - 0.5;
  for (const т of ИГРА.тараканы) {
    if (!наЭкране(т.x, т.y, 120)) continue;
    т._сорт = Math.min(т.y, потолокСвиты); т._вид = 1; порядок.push(т);
  }
  for (const щ of ИГРА.щенки) {
    if (щ.выбыл > 0 || !наЭкране(щ.x, щ.y, 120)) continue;
    щ._сорт = Math.min(щ.y, потолокСвиты); щ._вид = 2; порядок.push(щ);
  }
  /* Пацаны сортируются честно по своему y, без потолка: стоящий выше Ильи
     рисуется за ним, стоящий ниже — перед ним. С подрезкой по игроку весь
     отряд всегда оказывался позади, и Илья на их фоне читался плоско.
     Тараканы и щенки потолок сохраняют — их много и они мелкие,
     перекрывать ими героя незачем. */
  for (const с of ИГРА.союзники) {
    if (!наЭкране(с.x, с.y, 200)) continue;
    с._сорт = с.y; с._вид = 3; порядок.push(с);
  }
  и._сорт = и.y; и._вид = 4;
  порядок.push(и);
  порядок.sort(поY);

  for (const о of порядок) {
    switch (о._вид) {
      case 0: нарисоватьВрага(о, кx, кy); break;
      case 1: нарисоватьТаракана(о, кx, кy); break;
      case 2: нарисоватьЩенка(о, кx, кy); break;
      case 3: нарисоватьСоюзника(о, кx, кy); break;
      default: нарисоватьИгрока(кx, кy);
    }
  }

  // аура zzord: видно, где аноны вязнут
  const аура = ИГРА.аураЗамедления;
  if (аура) {
    кт.save();
    кт.globalAlpha = 0.16;
    кт.strokeStyle = '#7fd6e8'; кт.lineWidth = 3;
    кт.beginPath();
    кт.ellipse(аура.x - кx, аура.y - кy, аура.радиус, аура.радиус * 0.45, 0, 0, ДВА_ПИ);
    кт.stroke();
    кт.restore();
  }

  // пули снайпера
  for (const в of ИГРА.выстрелы) {
    кт.save();
    кт.fillStyle = '#dff0ff';
    кт.beginPath(); кт.arc(в.x - кx, в.y - кy, 4, 0, ДВА_ПИ); кт.fill();
    кт.globalAlpha = 0.4;
    кт.beginPath(); кт.arc(в.x - кx, в.y - кy, 8, 0, ДВА_ПИ); кт.fill();
    кт.restore();
  }

  // --- клетка донатера ---
  const кл = ИГРА.клетка;
  if (кл) {
    const альфа = кл.тает > 0 ? зажать(кл.тает / 1.2, 0, 1) : 1;
    const x = кл.x - кx, y = кл.y - кy;

    // круг взлома на земле
    кт.save();
    кт.globalAlpha = (кл.взламывается ? 0.55 : 0.25) * альфа;
    кт.strokeStyle = кл.взламывается ? '#6cff9a' : '#8fb6ff';
    кт.lineWidth = 3;
    кт.setLineDash([14, 10]);
    кт.lineDashOffset = -кл.фаза * 14;
    кт.beginPath();
    кт.ellipse(x, y, ИВЕНТ.радиусВзлома, ИВЕНТ.радиусВзлома * 0.45, 0, 0, ДВА_ПИ);
    кт.stroke();
    кт.restore();

    const гк = готовыйСпрайт('obj_kletka', 1.7, 1, null);
    if (гк) {
      кт.save();
      кт.globalAlpha = альфа;
      кт.drawImage(гк.холст, (x - гк.ш / 2) | 0, (y - гк.в) | 0);
      кт.restore();
    }

    // Полоска взлома НАД КЛЕТКОЙ, а не в интерфейсе: взгляд игрока
    // в этот момент прикован к своему персонажу и к клетке.
    if (кл.прогресс > 0 && кл.тает <= 0) {
      const ш = 150, в = 16;
      const пy = y - (гк ? гк.в : 90) - 34;
      полоска(x - ш / 2, пy, ш, в, кл.прогресс / ИВЕНТ.времяВзлома,
              кл.взламывается ? '#6cff9a' : '#c9a227', '#1d2a22', 5);
      текст('ВЗЛОМ', x, пy - 18, { размер: 15, выравн: 'center', цвет: ЦВЕТ.текстТускл });
    }

    // ник донатера над клеткой
    if (кл.тает <= 0) {
      нарисоватьНик(кл.донатер.ник, x, y - (гк ? гк.в : 90) - (кл.прогресс > 0 ? 56 : 12));
    }
  }

  // --- убегающие донатеры ---
  for (const у of ИГРА.убегающие) {
    const качание = у.машет > 0 ? Math.sin(у.фаза) * 0.25 : 0;
    кт.save();
    кт.globalAlpha = зажать(у.жизнь / 1.2, 0, 1);
    кт.translate(у.x - кx, у.y - кy);
    кт.rotate(качание);
    кт.scale(у.сторона, 1);
    const г = габариты(у.спрайт, 1, 1);
    const с = СПРАЙТ[у.спрайт];
    if (с && с.готов) кт.drawImage(с.картинка, -г.ш / 2, -г.в, г.ш, г.в);
    кт.restore();
  }

  // лут на карте
  for (const п of ИГРА.предметы) {
    const ключ = п.вид === 'cherep' ? 'item_cherep' : 'item_beluga';
    const гп = готовыйСпрайт(ключ, 1, 1, null);
    const парение = Math.sin(п.фаза) * 5;
    /* Последние секунды предмет мигает: иначе он просто исчезает под носом
       и игрок не понимает, что у лута вообще есть срок. */
    const мигает = п.жизнь < ЛУТ.мигание;
    const альфа = мигает
      ? 0.35 + Math.abs(Math.sin(ИГРА.времяВсего * 9)) * 0.65
      : 1;
    const свет = п.вид === 'cherep' ? '#6cff9a' : '#8fd8ff';
    кт.save();
    кт.globalAlpha = 0.3 * альфа;
    кт.fillStyle = свет;
    кт.beginPath();
    кт.ellipse(п.x - кx, п.y - кy, 26, 10, 0, 0, ДВА_ПИ);
    кт.fill();
    кт.restore();
    if (гп) {
      кт.save();
      кт.globalAlpha = альфа;
      кт.drawImage(гп.холст, (п.x - кx - гп.ш / 2) | 0, (п.y - кy - гп.в - парение) | 0);
      кт.restore();
    }
  }

  // ОЧКИ на максимуме — видно врагов сквозь толпу
  if (и.видитСквозьТолпу) {
    кт.save();
    кт.globalAlpha = 0.5; кт.strokeStyle = '#5cff9a'; кт.lineWidth = 2;
    for (const в of порядок) {
      if (в === и) continue;
      кт.beginPath();
      кт.ellipse(в.x - кx, в.y - кy, в.ш * 0.5, в.ш * 0.22, 0, 0, Math.PI * 2);
      кт.stroke();
    }
    кт.restore();
  }

  /* Метка приземления для НАВЕДЁННОГО броска (у него есть к.урон).
     Тень под летящим куском показывает, где он сейчас, а не куда упадёт,
     и увернуться по ней невозможно: игроки писали «прилетело в ебло,
     я даже не понял как умер». Кольцо стягивается к моменту падения —
     видно и точку, и оставшееся время. */
  for (const к of ИГРА.куски) {
    if (!к.урон) continue;
    const t = зажать(к.t, 0, 1);
    const r = БРОСОК.радиусУрона * (1.35 - t * 0.35);
    кт.save();
    кт.globalAlpha = 0.25 + t * 0.5;
    кт.strokeStyle = '#ff5a5a';
    кт.lineWidth = 2 + t * 2;
    кт.beginPath();
    кт.ellipse(к.доX - кx, к.доY - кy, r, r * 0.45, 0, 0, ДВА_ПИ);
    кт.stroke();
    // перекрестие в центре, чтобы точка читалась даже в гуще анонов
    кт.globalAlpha = 0.5 + t * 0.4;
    кт.lineWidth = 2;
    кт.beginPath();
    кт.moveTo(к.доX - кx - 9, к.доY - кy); кт.lineTo(к.доX - кx + 9, к.доY - кy);
    кт.moveTo(к.доX - кx, к.доY - кy - 5); кт.lineTo(к.доX - кx, к.доY - кy + 5);
    кт.stroke();
    кт.restore();
  }

  // куски ТОЛПЫ в полёте: летят по дуге, вращаясь
  for (const к of ИГРА.куски) {
    const t = зажать(к.t, 0, 1);
    const x = к.отX + (к.доX - к.отX) * t;
    const назем = к.отY + (к.доY - к.отY) * t;
    const дуга = Math.sin(Math.PI * t) * КУСОК.высотаДуги;
    const готовый = готовыйСпрайт('anon', 0.5, 1, null);
    кт.save();
    кт.globalAlpha = 0.32;
    кт.fillStyle = '#000000';
    кт.beginPath();
    кт.ellipse(x - кx, назем - кy, 14 * (1 - дуга / (КУСОК.высотаДуги * 1.6)), 5, 0, 0, ДВА_ПИ);
    кт.fill();
    кт.restore();
    if (готовый) {
      кт.save();
      кт.translate(x - кx, назем - дуга - кy - готовый.в / 2);
      кт.rotate(к.поворот);
      кт.drawImage(готовый.холст, -готовый.ш / 2, -готовый.в / 2);
      кт.restore();
    }
  }

  for (const гн of ИГРА.гантели) нарисоватьГантелю(гн, кx, кy);

  // кольца КРИКа
  for (const к of ИГРА.кольца) {
    кт.save();
    кт.globalAlpha = зажать(к.жизнь / к.всего, 0, 1) * 0.85;
    кт.strokeStyle = к.цвет || ЦВЕТ.крик;
    кт.lineWidth = 7 * (к.жизнь / к.всего) + 2;
    кт.beginPath();
    кт.ellipse(к.x - кx, к.y - кy, к.r, к.r * 0.42, 0, 0, Math.PI * 2);
    кт.stroke();
    кт.restore();
  }

  // частицы
  for (const ч of ИГРА.частицы) {
    кт.globalAlpha = зажать(ч.жизнь / ч.всего, 0, 1);
    кт.fillStyle = ч.цвет;
    кт.fillRect(ч.x - кx - ч.размер / 2, ч.y - кy - ч.размер / 2, ч.размер, ч.размер);
  }
  кт.globalAlpha = 1;

  нарисоватьПузыри(кx, кy);

  // всплывающие цифры
  for (const в of ИГРА.всплывашки) {
    кт.globalAlpha = зажать(в.жизнь / в.всего * 1.5, 0, 1);
    текст(в.строка, в.x - кx, в.y - кy, {
      размер: в.размер, цвет: в.цвет, выравн: 'center', базовая: 'middle'
    });
  }
  кт.globalAlpha = 1;

  if (зум !== 1 || качка) кт.restore();
}


