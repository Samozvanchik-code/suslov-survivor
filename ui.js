      // компактная строка: иконка слева, название и описание справа
      нарисоватьИконку(а.иконка, x + 46, yЭ + вК / 2, Math.min(56, вК - 18));
      let рИ = 21;
      while (ширинаТекста(а.имя, рИ) > шК - 110 && рИ > 13) рИ -= 1;
      текст(а.имя, x + 86, yЭ + вК / 2 - 20, { размер: рИ });
