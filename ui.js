/* Во сколько раз своя строка выше остальных. Больше 1.4 — на телефоне из
   пяти строк остаётся четыре, меньше 1.2 — разница не читается. */
const ДОЛЯ_СВОЕЙ = 1.35;

/* Окно таблицы: с какой строки показывать, если влезает не всё.

   Своя строка обязана попасть в окно. Раньше список всегда резался сверху, и
   игрок минуту искал себя в таблице, будучи на первом месте — на телефоне
   влезает пять строк из десяти, и своя запись просто оставалась за краем. */
function окноТаблицы(всего, свой, вместимость) {
  if (вместимость >= всего || свой < вместимость) return 0;
  // своя строка по центру окна, но за края списка не выезжаем
  return Math.max(0, Math.min(всего - вместимость,
                              свой - Math.floor((вместимость - 1) / 2)));
}

/* Какие строки рисовать. Отдельно от отрисовки, чтобы порядок и попадание
   своей строки проверялись тестом, а не глазами на телефоне.

   Если игрока в топе нет вообще (сервер отдаёт первую сотню), последняя
   строка отдаётся ему: его настоящее место из ответа сервера плюс разрыв
   над строкой. Пустой поиск себя в списке — та же жалоба, что и обрезанное
   окно, только неисправимая прокруткой. */
function строкиТаблицы(таблица, свой, вместимость, своя, местоСвоей) {
  const хвост = свой < 0 && !!своя && местоСвоей > таблица.length;
  const мест = хвост ? Math.max(1, вместимость - 1) : вместимость;
  const начало = окноТаблицы(таблица.length, свой, мест);
  const строки = [];
  for (let i = начало; i < Math.min(таблица.length, начало + мест); i++) {
    строки.push({ номер: i + 1, р: таблица[i], этот: i === свой, разрыв: false });
  }
  if (хвост) строки.push({ номер: местоСвоей, р: своя, этот: true, разрыв: true });
  return строки;
}

/* Локальный топ-10 по этому устройству. Пишется через отправитьРезультат —
   единственную точку входа, куда позже встанет внешний сервер рейтингов. */
function нарисоватьТаблицу(узкий, цx, левыйСтолбец, колонкаШ, у, yПотока) {
  /* Если мировой топ приехал — показываем его: он интереснее списка своих
     же забегов. Не приехал (сервер не задан, лежит или его режет
     блокировщик) — молча откатываемся на локальный, как было. */
  const мировой = ИГРА.мировойТоп.length > 0;
  const таблица = мировой
    ? ИГРА.мировойТоп
    : (ИГРА.таблица.length ? ИГРА.таблица : прочитатьТаблицу());
  if (!таблица.length) return;

  // своя строка в мировом топе ищется по нику и времени этого забега
  const свойНик = текущийНик().toLowerCase();
  const своёВремя = Math.round(ИГРА.время * 10) / 10;
  const свой = мировой
    ? таблица.findIndex(р => (р.ник || '').toLowerCase() === свойНик &&
                             Math.abs(р.время - своёВремя) < 0.05)
    : ИГРА.местоВТаблице;

  const шаг0 = 26 * у;
  const ш = узкий ? колонкаШ : 420;
  const x = узкий ? левыйСтолбец : цx + 30;
  let y = узкий ? yПотока : ЭКР.в * 0.16;

  // на узком экране показываем столько строк, сколько влезает над кнопкой
  const низДоступный = ЭКР.в - 96 - Math.max(56, 60 * у) - 16;
  const вПодписей = 20 * у;
  let шаг = шаг0;
  let строк;
  if (узкий) {
    /* Своя строка выше остальных, и место под неё резервируется ДО подсчёта
       вместимости: иначе последняя строка вылезает на кнопку ЕЩЁ РАЗ. */
    const место = низДоступный - y - 28 * у - вПодписей - шаг * (ДОЛЯ_СВОЕЙ - 1);
    строк = Math.min(5, таблица.length, Math.max(0, Math.floor(место / шаг)));
    // не влезает даже тройка — ужимаем строку, но таблицу показываем
    if (строк < Math.min(3, таблица.length) && место > 40) {
      строк = Math.min(3, таблица.length);
      шаг = Math.max(17, место / строк);
    }
  } else {
    строк = Math.min(10, таблица.length);
  }
  if (строк <= 0) return;

  const заголовок = мировой
    ? (узкий ? 'ТОП МИРА' : 'ТОП-10 В МИРЕ' +
       (ИГРА.мировоВсего ? '   ИГРОКОВ: ' + ИГРА.мировоВсего : ''))
    : (узкий ? 'ТОП' : 'ТОП-10 НА ЭТОМ УСТРОЙСТВЕ');
  текст(заголовок, x, y, {
    размер: 17 * у, цвет: мировой ? ЦВЕТ.золото : ЦВЕТ.текстТускл
  });
  y += 28 * у;

  /* Подписи столбцов. До них люди угадывали, что за цифры в строке:
     «2 это ХП?», «че значит 5». Короткие варианты — только когда столбцы
     физически не помещаются, гадать по ним всё равно не приходится. */
  const тесно = ш < 380;
  const рП = Math.max(11, 13 * у);
  const цП = 'rgba(160,155,180,0.85)';
  текст('НИК', x + 30 * у, y, { размер: рП, цвет: цП });
  текст('ВРЕМЯ', x + ш * 0.58, y, { размер: рП, цвет: цП, выравн: 'right' });
  текст(тесно ? 'УР' : 'УРОВЕНЬ', x + ш * 0.78, y, { размер: рП, цвет: цП, выравн: 'right' });
  текст(тесно ? 'СПАС' : 'СПАСЕНО', x + ш, y, { размер: рП, цвет: цП, выравн: 'right' });
  y += вПодписей;
  кт.save();
  кт.strokeStyle = 'rgba(160,155,180,0.25)'; кт.lineWidth = 1;
  кт.beginPath(); кт.moveTo(x, y - 4 * у); кт.lineTo(x + ш, y - 4 * у); кт.stroke();
  кт.restore();

  const своя = ИГРА.игрок ? {
    ник: текущийНик(), время: своёВремя,
    уровень: ИГРА.уровень, спасённых: ИГРА.спасённые.length
  } : null;
  const строки = строкиТаблицы(таблица, свой, строк, своя, ИГРА.мировоеМесто);

  for (const с of строки) {
    const р = с.р;
    const этот = с.этот;
    const высота = этот ? шаг * ДОЛЯ_СВОЕЙ : шаг;

    // разрыв: между топом и своей строкой, стоящей далеко ниже
    if (с.разрыв) {
      текст('· · ·', x + ш / 2, y - 2, {
        размер: рП, цвет: 'rgba(160,155,180,0.5)', выравн: 'center'
      });
    }

    if (этот) {
      кт.save();
      кт.fillStyle = 'rgba(90,120,200,0.34)';
      скруглённыйПрямоугольник(x - 8, y - 2, ш + 16, высота - 2, 6);
      кт.fill();
      кт.strokeStyle = '#8fb0ff'; кт.lineWidth = 2;
      скруглённыйПрямоугольник(x - 8, y - 2, ш + 16, высота - 2, 6);
      кт.stroke(); кт.restore();
    }

    const цвет = этот ? '#ffffff' : (с.номер === 1 ? ЦВЕТ.золото : ЦВЕТ.текстТускл);
    const размер = этот
      ? Math.min(20 * у, высота - 6)
      : Math.min(16 * у, шаг - 6);
    const цy = y + (высота - шаг) / 2;   // крупная строка сидит по центру своей полосы

    текст(с.номер + '.', x, цy, { размер, цвет });
    текст(р.ник, x + 30 * у, цy, { размер, цвет });
    текст(форматВремени(р.время), x + ш * 0.58, цy, { размер, цвет, выравн: 'right' });
    текст('' + (р.уровень || 1), x + ш * 0.78, цy, { размер, цвет, выравн: 'right' });
    текст('' + (р.спасённых || 0), x + ш, цy, { размер, цвет, выравн: 'right' });

    /* Подпись ТЫ. Жёлтой подсветки оказалось мало: игрок минуту искал себя,
       стоя на первом месте. Метка висит слева от строки, а на узком экране
       уезжает внутрь — за краем колонки её было бы не видно. */
    if (этот) {
      текст('ТЫ', тесно ? x + ш * 0.30 : x - 14, цy + 2, {
        размер: Math.max(11, 13 * у), цвет: '#8fb0ff',
        выравн: тесно ? 'left' : 'right'
      });
    }

    y += высота;
  }
}

/* Ссылка на автора — обычный HTML поверх канваса, иначе по ней нельзя кликнуть.
   Видна только на ПОДРУБ и ИТОГАХ; в бою скрыта, чтобы не перехватывала клики. */
const ссылкаОтзыва = document.getElementById('fb');
function обновитьСсылку() {
  let низ = null;
  if (ИГРА.экран === 'старт')      низ = Math.round(ЭКР.в * 0.82) + 96;
  else if (ИГРА.экран === 'итоги') низ = ЭКР.в - 64;
  if (низ === null) {
    if (ссылкаОтзыва.style.display !== 'none') ссылкаОтзыва.style.display = 'none';
  } else {
    if (ссылкаОтзыва.style.display !== 'block') ссылкаОтзыва.style.display = 'block';
    ссылкаОтзыва.style.top = низ + 'px';
  }

  // поле ника живёт только на стартовом экране
  if (ИГРА.экран === 'старт') {
    if (полеНика.style.display !== 'block') полеНика.style.display = 'block';
    полеНика.style.top = Math.round(ЭКР.в * 0.82) - 62 + 'px';
  } else if (полеНика.style.display !== 'none') {
    полеНика.blur();
    полеНика.style.display = 'none';
  }
}

/* Момент спасения: вспышка экрана и крупный ник, взлетающий вверх.
   Это тот кадр, который постят в чат, поэтому он рисуется поверх всего. */
function нарисоватьСпасение() {
  // Пока Шварц не отпустил — вся картинка в зелёном. Не заметить нельзя.
  const и = ИГРА.игрок;
  if (и && и.шварц > 0) {
    const гаснет = и.шварц < 3 ? и.шварц / 3 : 1;       // мигает под конец
    const пульс = и.шварц < 3 ? 0.5 + Math.abs(Math.sin(ИГРА.времяВсего * 9)) * 0.5 : 1;
    кт.fillStyle = 'rgba(60,255,140,' + (0.13 * гаснет * пульс) + ')';
    кт.fillRect(0, 0, ЭКР.ш, ЭКР.в);
    текст('ШВАРЦ ' + и.шварц.toFixed(1), ЭКР.ш / 2, ЭКР.в - 108, {
      размер: 22 * ЭКР.uiМасштаб, выравн: 'center', базовая: 'middle', цвет: '#6cff9a'
    });
  }
  if (ИГРА.вспышкаЭкрана > 0) {
    кт.fillStyle = 'rgba(255,255,255,' + зажать(ИГРА.вспышкаЭкрана * 0.55, 0, 0.55) + ')';
    кт.fillRect(0, 0, ЭКР.ш, ЭКР.в);
  }
  const н = ИГРА.взлетающийНик;
  if (н) {
    const доля = н.жизнь / н.всего;
    кт.save();
    кт.globalAlpha = зажать(доля * 1.4, 0, 1);
    const размер = (н.топ ? 76 : 56) * (1.25 - доля * 0.25);
    текст(н.текст, мирВЭкранX(н.x), мирВЭкранY(н.y), {
      размер, выравн: 'center', базовая: 'middle',
      цвет: н.зелёный ? '#6cff9a' : (н.топ ? ЦВЕТ.золото : ЦВЕТ.зелёный)
    });
    if (!н.зелёный) {
      текст('СПАСЁН', мирВЭкранX(н.x), мирВЭкранY(н.y) + размер * 0.75, {
        размер: размер * 0.34, выравн: 'center', базовая: 'middle', цвет: '#f2f0f6'
      });
    }
    кт.restore();
  }
}

function нарисоватьДжойстик() {
  if (!джойстик.активен) return;
  кт.save();
  кт.globalAlpha = 0.28;
  кт.strokeStyle = '#eef3ff'; кт.lineWidth = 3;
  кт.beginPath(); кт.arc(джойстик.базаX, джойстик.базаY, джойстик.радиус, 0, ДВА_ПИ); кт.stroke();
  кт.globalAlpha = 0.12;
  кт.fillStyle = '#eef3ff'; кт.fill();

  const дx = джойстик.x - джойстик.базаX, дy = джойстик.y - джойстик.базаY;
  const д = Math.min(Math.hypot(дx, дy), джойстик.радиус) || 0;
  const у = Math.atan2(дy, дx);
  кт.globalAlpha = 0.55;
  кт.fillStyle = '#eef3ff';
  кт.beginPath();
  кт.arc(джойстик.базаX + Math.cos(у) * д, джойстик.базаY + Math.sin(у) * д, 30, 0, ДВА_ПИ);
  кт.fill();
  кт.restore();
}

function нажатие(код) {
  разбудитьЗвук();
  // Ускорение x4: без него проверка поздних волн съедает по десять минут за прогон.
  if (код === 'KeyF') { ИГРА.показыватьFPS = !ИГРА.показыватьFPS; return; }
  if (код === 'KeyT') {
    ИГРА.множительВремени = ИГРА.множительВремени === 1 ? 4 : 1;
    return;
  }
  if (ИГРА.экран === 'изменения') {
    if (код === 'Escape' || код === 'Enter' || код === 'Space') закрытьИзменения();
    return;
  }
  if (ИГРА.экран === 'старт' && (код === 'Enter' || код === 'Space')) начатьЗабег();
  else if (ИГРА.экран === 'итоги' && (код === 'Enter' || код === 'KeyR')) начатьЗабег();
  else if (ИГРА.экран === 'левелап') {
    if (код === 'Digit1' || код === 'Numpad1') взятьКарточку(0);
    if (код === 'Digit2' || код === 'Numpad2') взятьКарточку(1);
    if (код === 'Digit3' || код === 'Numpad3') взятьКарточку(2);
  }
  else if (ИГРА.экран === 'замена') {
    if (код === 'Digit1' || код === 'Numpad1') заменитьСоюзника(0);
    if (код === 'Digit2' || код === 'Numpad2') заменитьСоюзника(1);
    if (код === 'Digit3' || код === 'Numpad3') заменитьСоюзника(2);
    if (код === 'Escape') заменитьСоюзника(-1);
  }
}

/* Подпись версии в левом нижнем углу. Полупрозрачная, чтобы не лезть в глаза,
   и кликабельная: по нажатию открывается список изменений. Рисуется поверх
   всех экранов, кроме боя — в бою угол занят иконками билда, да и читать
   ченджлог посреди забега некому. */
function нарисоватьВерсию() {
  /* Подпись должна быть НЕЗАМЕТНОЙ, но РАЗЛИЧИМОЙ — это разные вещи.
     Первая версия была на 35% прозрачности серым по тёмному: замер пикселей
     дал разницу с фоном в 8 единиц из 255, то есть её буквально не было
     видно. Теперь плашка почти непрозрачная, текст светлый, и рядом стоит
     подпись «ЧТО НОВОГО» — иначе непонятно, что по цифре можно нажать. */
  const цифра = 'v' + ВЕРСИЯ;
  const подпись = 'ЧТО НОВОГО';
  const рЦ = 15, рП = 12;
  const ш = ширинаТекста(цифра, рЦ) + ширинаТекста(подпись, рП) + 28;
  const в = 28;
  const x = 12, y = ЭКР.в - в - 12;
  const наведена = мышь.x >= x && мышь.x <= x + ш && мышь.y >= y && мышь.y <= y + в;

  кт.save();
  кт.globalAlpha = наведена ? 1 : 0.8;
  кт.fillStyle = наведена ? '#2c2a3c' : '#1d1a26';
  скруглённыйПрямоугольник(x, y, ш, в, 7); кт.fill();
  кт.strokeStyle = наведена ? '#8fb6ff' : '#565269';
  кт.lineWidth = 1.5;
  скруглённыйПрямоугольник(x, y, ш, в, 7); кт.stroke();
  кт.restore();

  текст(цифра, x + 10, y + в / 2, {
    размер: рЦ, базовая: 'middle',
    цвет: наведена ? '#ffffff' : '#c9c3da', обводка: false
  });
  текст(подпись, x + 10 + ширинаТекста(цифра, рЦ) + 8, y + в / 2 + 1, {
    размер: рП, базовая: 'middle',
    цвет: наведена ? '#8fb6ff' : '#7d788e', обводка: false
  });

  кнопки.push({ x, y, ш, в, действие: открытьИзменения });
}

function открытьИзменения() {
  ИГРА.экранДоИзменений = ИГРА.экран;
  ИГРА.прокруткаИзменений = 0;
  ИГРА.экран = 'изменения';
}

function закрытьИзменения() {
  ИГРА.экран = ИГРА.экранДоИзменений || 'старт';
}

/* Экран списка изменений. Прокрутка колесом и пальцем: записей со временем
   станет больше, чем влезает на телефон. */
function экранИзменений() {
  кнопки = [];
  кт.fillStyle = ЦВЕТ.пол;
  кт.fillRect(0, 0, ЭКР.ш, ЭКР.в);
  нарисоватьПол(60, 40);
  затемнение(0.8);

  const у = ЭКР.uiМасштаб;
  const поля = Math.max(20, ЭКР.ш * 0.06);
  const ш = Math.min(720, ЭКР.ш - поля * 2);
  const x = (ЭКР.ш - ш) / 2;

  const шапка = 74 * у;
  текст('ЧТО НОВОГО', x, 26 * у, { размер: 30 * у, цвет: ЦВЕТ.текст });
  текст('версия ' + ВЕРСИЯ, x, 26 * у + 34 * у, { размер: 16 * у, цвет: ЦВЕТ.золото });

  // всё ниже шапки режем по области, иначе прокрутка залезет на заголовок
  кт.save();
  кт.beginPath();
  кт.rect(0, шапка, ЭКР.ш, ЭКР.в - шапка - 78);
  кт.clip();

  let y = шапка + 10 - ИГРА.прокруткаИзменений;
  for (const и of ИЗМЕНЕНИЯ) {
    const свежая = и.версия === ВЕРСИЯ;
    текст('v' + и.версия, x, y, {
      размер: 20 * у, цвет: свежая ? ЦВЕТ.зелёный : ЦВЕТ.текст
    });
    текст(и.дата, x + ш, y, {
      размер: 15 * у, выравн: 'right', цвет: ЦВЕТ.текстТускл
    });
    текст(и.заголовок, x + ширинаТекста('v' + и.версия, 20 * у) + 12 * у, y + 3 * у, {
      размер: 16 * у, цвет: ЦВЕТ.текстТускл
    });
    y += 30 * у;

    for (const п of и.пункты) {
      // длинные строки переносим по словам, иначе на телефоне уезжают за край
      const рП = 16 * у;
      const доступно = ш - 20 * у;
      const слова = п.split(' ');
      let строка = '';
      const вывести = (с) => {
        текст('·', x + 4 * у, y, { размер: рП, цвет: '#6a6578' });
        текст(с, x + 18 * у, y, { размер: рП, цвет: '#c8c3d6' });
        y += 23 * у;
      };
      for (const сл of слова) {
        const проба = строка ? строка + ' ' + сл : сл;
        if (ширинаТекста(проба, рП) > доступно && строка) { вывести(строка); строка = сл; }
        else строка = проба;
      }
      if (строка) вывести(строка);
    }
    y += 16 * у;
  }
  ИГРА.высотаИзменений = y + ИГРА.прокруткаИзменений - шапка;
  кт.restore();

  const шК = 220 * у, вК = Math.max(50, 54 * у);
  кнопка('НАЗАД', ЭКР.ш / 2 - шК / 2, ЭКР.в - вК - 14, шК, вК, закрытьИзменения);
}

