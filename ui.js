/* Горячий путь: враг рисуется без единого выделения памяти, без строковых
   ключей и без save/restore. Поза достаётся прямым индексом из таблицы,
   тень уже внутри канваса — то есть один drawImage на врага. */
/* Уникальные враги (боссы) мимо предрендера: у ТОЛПЫ масштаб плавно едет
   по мере потери кусков, под это одна запечённая копия не годится.
   Их на экране один-два, так что обычный drawImage с масштабированием
   ничего не стоит. */
function нарисоватьУникального(в, кx, кy) {
  const с = СПРАЙТ[в.шаблон.спрайт];
  const г = габариты(в.шаблон.спрайт, в.масштаб, в.шаблон.ширинаX);
  const x = в.x - кx, y = в.y - кy;
  const подпрыг = Math.abs(Math.sin(в.фаза)) * 4;
  const колыхание = Math.sin(в.фаза * 0.7) * 0.02;   // туша слегка колышется

  кт.save();
  кт.globalAlpha = 0.34;
  кт.fillStyle = '#000000';
  кт.beginPath();
  кт.ellipse(x, y, г.ш * 0.34, г.ш * 0.12, 0, 0, ДВА_ПИ);
  кт.fill();
  кт.restore();

  if (!с || !с.готов) return;
  кт.save();
  кт.translate(x, y - подпрыг);
  кт.rotate(колыхание);
  кт.scale(в.сторона === -1 ? -1 : 1, 1);
  кт.drawImage(с.картинка, -г.ш / 2, -г.в, г.ш, г.в);
  /* Подкраска уникального врага. Осталась как механизм, но в конфиге сейчас
     не используется никем: ДВОЙНИКУ она была нужна, пока он рисовался
     спрайтом самого игрока, а теперь у него свой. Если появится босс-вариант
     существующего спрайта — поле «оттенок» снова его отличит. */
  if (в.шаблон.оттенок) {
    кт.save();
    кт.globalAlpha = 0.55;
    кт.globalCompositeOperation = 'source-atop';
    кт.fillStyle = в.шаблон.оттенок;
    кт.fillRect(-г.ш / 2, -г.в, г.ш, г.в);
    кт.restore();
  }
  if (в.вспышка > 0) {
    кт.globalAlpha = зажать(в.вспышка * 8, 0, 0.8);
    кт.globalCompositeOperation = 'source-atop';
    кт.fillStyle = '#ffffff';
    кт.fillRect(-г.ш / 2, -г.в, г.ш, г.в);
  }
  кт.restore();
}

function нарисоватьВрага(в, кx, кy) {
  const ш = в.шаблон;
  if (ш.уникальный) { нарисоватьУникального(в, кx, кy); return; }
  const норм = ((в.фаза % ДВА_ПИ) + ДВА_ПИ) % ДВА_ПИ;
  const индекс = (норм / ДВА_ПИ * ПОЗ) | 0;
  const влево = в.сторона === -1;

  const поза = (влево ? ш._база.лев : ш._база.прав)[индекс];
  if (!поза) return;
  const пx = (в.x - кx - поза.якорьX) | 0;
  const пy = (в.y - кy - поза.якорьY) | 0;

  const альфа = в.гаснет > 0 ? в.гаснет / ЗАТУХАНИЕ : 1;
  if (альфа !== 1) кт.globalAlpha = альфа;
  кт.drawImage(поза.холст, пx, пy);

  if (в.вспышка > 0) {
    const с = (влево ? ш._белые.лев : ш._белые.прав)[индекс];
    кт.globalAlpha = зажать(в.вспышка * 8, 0, 0.85) * альфа;
    кт.drawImage(с.холст, пx, пy);
    кт.globalAlpha = 1;
  } else if (ш._оттенок) {
    // трещина делителя и табличка маски уже в спрайтах,
    // кодом осталась только пульсация каминг-аута. На замахе она
    // разгоняется до предела — это и есть предупреждение о взрыве.
    const с = (влево ? ш._оттенок.лев : ш._оттенок.прав)[индекс];
    let сила;
    if (в.замах > 0) {
      const близко = 1 - в.замах / КАМИНГ.замах;              // 0 в начале, 1 перед взрывом
      const частота = 10 + близко * 40;                        // мигает всё чаще
      сила = 0.25 + близко * 0.5 + Math.abs(Math.sin(в.замах * частота)) * 0.35;
    } else {
      сила = 0.05 + Math.abs(Math.sin(в.фаза * 2)) * 0.18;
    }
    кт.globalAlpha = зажать(сила, 0, 1) * альфа;
    кт.drawImage(с.холст, пx, пy);
    кт.globalAlpha = 1;
  } else if (альфа !== 1) {
    кт.globalAlpha = 1;
  }

  // дрищ на замахе: линия будущего рывка. Без неё он просто телепортируется
  if (в.шаблон.поведение === 'рывок' && в.замах > 0) {
    const и2 = ИГРА.игрок;
    const у = Math.atan2(и2.y - в.y, и2.x - в.x);
    кт.save();
    кт.globalAlpha = 0.25 + (1 - в.замах / ДРИЩ.замах) * 0.5;
    кт.strokeStyle = '#ff9a5a'; кт.lineWidth = 3;
    кт.setLineDash([12, 8]);
    кт.beginPath();
    кт.moveTo(в.x - кx, в.y - кy);
    кт.lineTo(в.x - кx + Math.cos(у) * ДРИЩ.дальностьРывка,
              в.y - кy + Math.sin(у) * ДРИЩ.дальностьРывка);
    кт.stroke();
    кт.restore();
  }
  // отдышка: видно, что сейчас его можно бить
  if (в.отдышка > 0) {
    кт.save();
    кт.globalAlpha = 0.4;
    кт.strokeStyle = '#8fd6ff'; кт.lineWidth = 2;
    кт.beginPath();
    кт.ellipse(в.x - кx, в.y - кy, 22, 9, 0, 0, ДВА_ПИ);
    кт.stroke();
    кт.restore();
  }

  // кольцо радиуса подрыва: видно, куда именно прилетит
  if (в.шаблон.поведение === 'взрывается' && в.замах > 0) {
    const близко = 1 - в.замах / КАМИНГ.замах;
    кт.save();
    кт.globalAlpha = 0.25 + близко * 0.45;
    кт.strokeStyle = '#ff7a45';
    кт.lineWidth = 2 + близко * 2;
    кт.beginPath();
    кт.ellipse(в.x - кx, в.y - кy, КАМИНГ.радиус * (0.35 + близко * 0.65),
               КАМИНГ.радиус * (0.35 + близко * 0.65) * 0.42, 0, 0, ДВА_ПИ);
    кт.stroke();
    кт.restore();
  }

  /* Щит маски. Пока цел — дуга со стороны взгляда и точки оставшейся
     прочности: игрок должен видеть, что щит конечен, иначе он читает
     нули как «враг неуязвим» и идёт писать в чат, что игра сломана. */
  if (в.шаблон.поведение === 'щит' && в.щитЦел !== false) {
    const осталось = Math.max(0, МАСКА.прочность - (в.блоков || 0));
    const цx = в.x - кx, цy = в.y - кy - в.высотаСпрайта * 0.5;
    const у = Math.atan2(в.лицоY, в.лицоX);
    кт.save();
    кт.globalAlpha = 0.35 + осталось / МАСКА.прочность * 0.4;
    кт.strokeStyle = '#9fc6ff';
    кт.lineWidth = 3;
    кт.beginPath();
    кт.arc(цx, цy, в.ш * 0.75, у - 0.7, у + 0.7);
    кт.stroke();
    кт.restore();
    // точки прочности над головой
    for (let i = 0; i < МАСКА.прочность; i++) {
      const тx = цx - (МАСКА.прочность - 1) * 4 + i * 8;
      кт.fillStyle = i < осталось ? '#9fc6ff' : 'rgba(120,120,140,0.45)';
      кт.beginPath();
      кт.arc(тx, цy - в.высотаСпрайта * 0.42, 2.6, 0, ДВА_ПИ);
      кт.fill();
    }
  }

  // кусок ТОЛПЫ ещё встаёт: пыль под ногами, чтобы читалось «поднимается»
  if (в.встаёт > 0) {
    кт.save();
    кт.globalAlpha = зажать(в.встаёт / КУСОК.вставание, 0, 1) * 0.5;
    кт.fillStyle = '#b6b1c4';
    кт.beginPath();
    кт.ellipse(в.x - кx, в.y - кy, 26 * (1.2 - в.встаёт / КУСОК.вставание), 8, 0, 0, ДВА_ПИ);
    кт.fill();
    кт.restore();
  }

  // полоска hp только у раненых — иначе экран превращается в кашу
  if (в.hp < в.максHp && в.гаснет <= 0) {
    const шп = в.ширинаСпрайта > 37 ? в.ширинаСпрайта * 0.7 : 26;
    const y = в.y - кy - в.высотаСпрайта - 10;
    const x = в.x - кx - шп / 2;
    кт.fillStyle = 'rgba(0,0,0,0.6)';
    кт.fillRect(x, y, шп, 5);
    кт.fillStyle = ЦВЕТ.хп;
    кт.fillRect(x, y, шп * (в.hp > 0 ? в.hp / в.максHp : 0), 5);
  }
}

function нарисоватьИгрока(кx, кy) {
  const и = ИГРА.игрок;
  const мигает = и.неуязвим > 0 && Math.floor(и.неуязвим * 18) % 2 === 0;

  /* Постоянное тонкое кольцо под Ильёй. Со свитой из союзников, тараканов
     и щенков игрок теряется в толпе — взгляд должен находить себя мгновенно. */
  кт.save();
  кт.beginPath();
  кт.ellipse(и.x - кx, и.y - кy, 34, 14, 0, 0, ДВА_ПИ);
  кт.globalAlpha = 0.18;
  кт.fillStyle = '#eef3ff';
  кт.fill();
  кт.globalAlpha = 0.28;                       // мягкая внешняя подложка
  кт.strokeStyle = '#eef3ff';
  кт.lineWidth = 6;
  кт.stroke();
  кт.globalAlpha = 0.85;                       // чёткий тонкий контур
  кт.lineWidth = 2;
  кт.stroke();
  кт.restore();

  // аура ПРАЙМА под ногами
  if (и.праймОсталось > 0) {
    кт.save();
    кт.globalAlpha = 0.25 + Math.sin(ИГРА.времяВсего * 8) * 0.1;
    кт.fillStyle = ЦВЕТ.золото;
    кт.beginPath();
    кт.ellipse(и.x - кx, и.y - кy, 54, 20, 0, 0, Math.PI * 2);
    кт.fill();
    кт.restore();
  }
  // щит БЕЗ ТРЕША
  if (и.щитЗаряжен) {
    кт.save();
    кт.globalAlpha = 0.5;
    кт.strokeStyle = ЦВЕТ.крик; кт.lineWidth = 2.5;
    кт.beginPath();
    кт.ellipse(и.x - кx, и.y - кy - и.в * 0.45, 42, 62, 0, 0, Math.PI * 2);
    кт.stroke();
    кт.restore();
  }

  drawSprite(и.шварц > 0 ? 'shvarts' : 'ilya_idle', и.x - кx, и.y - кy, {
    фаза: и.фаза, идёт: и.идёт, сторона: и.сторона,
    вспышка: и.вспышка, альфа: мигает ? 0.35 : 1
  });

  // Пока нет спрайтов-слоёв прокачки, ОЧКИ отражаем свечением.
  const ур = и.апгрейды.ochki || 0;
  if (ур >= 3) {
    const г = габариты('ilya_idle');
    кт.save();
    кт.globalAlpha = 0.55;
    кт.fillStyle = ур >= 4 ? '#5cff9a' : '#bfe9ff';
    кт.beginPath();
    кт.ellipse(и.x - кx + (и.сторона * 2), и.y - кy - г.в * 0.86, 9, 3.5, 0, 0, Math.PI * 2);
    кт.fill();
    кт.restore();
  }
}

function нарисоватьПузыри(кx, кy) {
  for (const п of ИГРА.пузыри) {
    const ц = п.цель;
    if (!ц) continue;
    let x, y;
    if (п.цельТип === 'игрок') {
      x = ц.x - кx; y = ц.y - кy - габариты('ilya_idle').в - 22;
    } else {
      x = ц.x - кx; y = ц.y - кy - ц.высотаСпрайта - 16;
    }
    if (x < -200 || x > ЭКР.ш + 200 || y < -100 || y > ЭКР.в + 100) continue;

    const появление = зажать((п.всего - п.жизнь) * 6, 0, 1);
    const исчезание = зажать(п.жизнь * 3, 0, 1);
    кт.save();
    кт.globalAlpha = появление * исчезание;

    const размер = 17;
    const ш = ширинаТекста(п.строка, размер, '700') + 22;
    const в = размер + 16;
    кт.fillStyle = 'rgba(18,16,24,0.9)';
    кт.strokeStyle = 'rgba(210,205,225,0.35)';
    кт.lineWidth = 1.5;
    скруглённыйПрямоугольник(x - ш / 2, y - в, ш, в, 9);
    кт.fill(); кт.stroke();
    // хвостик пузыря
    кт.beginPath();
    кт.moveTo(x - 6, y); кт.lineTo(x + 6, y); кт.lineTo(x, y + 8);
    кт.closePath(); кт.fill();

    текст(п.строка, x, y - в / 2, {
      размер, вес: '700', выравн: 'center', базовая: 'middle',
      цвет: '#e8e4f2', обводка: false
    });
    кт.restore();
  }
}

