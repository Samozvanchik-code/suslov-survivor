function нарисоватьИконку(ключ, x, y, размер) {
  if (СПРАЙТ[ключ] && СПРАЙТ[ключ].готов) {
    const с = СПРАЙТ[ключ];
    const к = размер / Math.max(с.ш, с.в);
    кт.drawImage(с.картинка, x - с.ш * к / 2, y - с.в * к / 2, с.ш * к, с.в * к);
    return;
  }
  const цвет = ЦВЕТА_ИКОНОК[ключ] || '#7a7a90';
  кт.fillStyle = цвет;
  кт.beginPath(); кт.arc(x, y, размер * 0.42, 0, Math.PI * 2); кт.fill();
  кт.strokeStyle = 'rgba(0,0,0,0.4)'; кт.lineWidth = 2; кт.stroke();
  const б = (ключ || '?').charAt(0).toUpperCase();
  текст(б, x, y, {
    размер: размер * 0.5, выравн: 'center', базовая: 'middle',
    цвет: '#fff', толщинаОбводки: 3
  });
}

/* Указатель на объект за краем экрана. Общий для стрелки к клетке и для
   лута: механика одна, различаются только цвет, размер и подпись.
   Возвращает точку у края, чтобы вызывающий мог подписать её. */
function указательЗаКрай(мирX, мирY, цвет, размер, альфа, поля) {
  const цx = ЭКР.ш / 2, цy = ЭКР.в / 2;
  const эx = мирВЭкранX(мирX), эy = мирВЭкранY(мирY);
  const запас = поля !== undefined ? поля : 60;
  if (эx > запас && эx < ЭКР.ш - запас && эy > запас && эy < ЭКР.в - запас) return null;

  const угол = Math.atan2(эy - цy, эx - цx);
  const радX = ЭКР.ш / 2 - (запас + 36), радY = ЭКР.в / 2 - (запас + 36);
  const сx = цx + Math.cos(угол) * радX, сy = цy + Math.sin(угол) * радY;

  const к = размер / 26;
  кт.save();
  кт.globalAlpha = альфа;
  кт.translate(сx, сy);
  кт.rotate(угол);
  кт.fillStyle = цвет;
  кт.beginPath();
  кт.moveTo(26 * к, 0); кт.lineTo(-14 * к, -17 * к);
  кт.lineTo(-6 * к, 0);  кт.lineTo(-14 * к, 17 * к);
  кт.closePath(); кт.fill();
  кт.restore();
  return { x: сx, y: сy, угол };
}

/* Сердце рисуем вектором: спрайта под него нет, а половинка нужна
   произвольная. доля: 1 — целое, 0.5 — половина, 0 — пустое. */
function сердце(x, y, р, доля) {
  const путь = () => {
    кт.beginPath();
    кт.moveTo(x, y + р * 0.75);
    кт.bezierCurveTo(x - р * 1.35, y - р * 0.15, x - р * 0.55, y - р * 1.15, x, y - р * 0.35);
    кт.bezierCurveTo(x + р * 0.55, y - р * 1.15, x + р * 1.35, y - р * 0.15, x, y + р * 0.75);
    кт.closePath();
  };
  кт.save();
  путь();
  кт.fillStyle = ЦВЕТ.хпФон; кт.fill();
  if (доля > 0) {
    кт.save();
    путь();
    кт.clip();
    // половинку режем прямоугольником по левой стороне
    кт.fillStyle = ЦВЕТ.хп;
    кт.fillRect(x - р * 1.5, y - р * 1.5, р * 3 * доля, р * 3);
    кт.restore();
  }
  путь();
  кт.strokeStyle = 'rgba(10,8,14,0.85)'; кт.lineWidth = Math.max(2, р * 0.16);
  кт.stroke();
  кт.restore();
}

/* Ряд сердец. Округление ВНИЗ до половины: 2.9 показывает два с половиной,
   а не три — игрок не должен думать, что у него есть сердце, которого нет. */
function нарисоватьСердца(x, y, у) {
  const и = ИГРА.игрок;
  const всего = Math.max(1, Math.round(и.максHp));
  const р = 11 * у, шаг = 26 * у;

  // с большим максимумом ряд не влезает — сворачиваем в «сердце x N»
  if (всего > 10) {
    сердце(x + р, y + р, р, зажать(и.hp / и.максHp, 0, 1));
    текст('x ' + (Math.floor(и.hp * 2) / 2).toFixed(1) + ' / ' + всего,
          x + р * 2 + 10 * у, y + р, {
      размер: 16 * у, базовая: 'middle', цвет: ЦВЕТ.текст
    });
    return 26 * у;
  }

  for (let i = 0; i < всего; i++) {
    const остаток = и.hp - i;
    const доля = остаток >= 1 ? 1 : (остаток >= 0.5 ? 0.5 : 0);
    сердце(x + р + i * шаг, y + р, р, доля);
  }
  return 26 * у;
}

function нарисоватьИнтерфейс() {
  const и = ИГРА.игрок;
  const у = ЭКР.uiМасштаб;               // на узком экране всё крупнее
  const поля = 16 * у;
  const шп = Math.min(300 * у, ЭКР.ш * 0.42);

  // hp: сердца половинками вместо полоски
  нарисоватьСердца(поля, поля, у);

  // опыт
  const порог = БАЛАНС.порогУровня(ИГРА.уровень);
  полоска(поля, поля + 26 * у, шп, 11 * у, ИГРА.опыт / порог, ЦВЕТ.опыт, ЦВЕТ.опытФон, 4);
  if (ЭКР.ш < 620) {
    // на телефоне справа от полоски уже стоит счётчик анонов — уводим вниз
    текст('УР ' + ИГРА.уровень, поля, поля + 40 * у, { размер: 15 * у, цвет: ЦВЕТ.опыт });
  } else {
    текст('УР ' + ИГРА.уровень, поля + шп + 10, поля + 24 * у, { размер: 16 * у, цвет: ЦВЕТ.опыт });
  }

  /* На узком экране таймер по центру налезает на полоски, поэтому там
     он уходит вправо и уменьшается, а счётчик убитых встаёт под него. */
  const узкийHUD = ЭКР.ш < 620;
  /* Дополнительное время. Часы забега встали на 10:00, и без отдельной
     строки это выглядит как замерший таймер, то есть как баг. Подпись
     объясняет: время больше не идёт, идёт бой с двойником. */
  const доп = ИГРА.дополнительное > 0
    ? ФИНАЛ.подпись + ' +' + форматВремени(ИГРА.дополнительное) : '';
  if (узкийHUD) {
    текст(форматВремени(ИГРА.время), ЭКР.ш - поля, поля - 2, {
      размер: 26 * у, выравн: 'right', цвет: доп ? ЦВЕТ.золото : ЦВЕТ.текст
    });
    if (доп) текст(доп, ЭКР.ш - поля, поля + 46 * у, {
      размер: 12 * у, выравн: 'right', цвет: ЦВЕТ.золото
    });
    текст('АНОНОВ: ' + ИГРА.убито, ЭКР.ш - поля, поля + 30 * у, {
      размер: 14 * у, выравн: 'right', цвет: ЦВЕТ.текстТускл
    });
  } else {
    текст(форматВремени(ИГРА.время), ЭКР.ш / 2, поля, {
      размер: 36 * у, выравн: 'center', цвет: доп ? ЦВЕТ.золото : ЦВЕТ.текст
    });
    if (доп) текст(доп, ЭКР.ш / 2, поля + 42 * у, {
      размер: 14 * у, выравн: 'center', цвет: ЦВЕТ.золото
    });
    текст('АНОНОВ: ' + ИГРА.убито, ЭКР.ш - поля, поля, {
      размер: 16 * у, выравн: 'right', цвет: ЦВЕТ.текстТускл
    });
  }

  /* Строка активных эффектов по центру. Раньше ПРАЙМ печатался в фиксированную
     точку и на боссе налезал прямо на его имя — два текста в одном месте.
     Теперь под баннером босса, и эффекты идут друг под другом. */
  const боссЖив = ИГРА.босс && !ИГРА.босс.мёртв && ИГРА.враги.indexOf(ИГРА.босс) >= 0;
  let yЭффекта = поля + (боссЖив ? 108 * у : 48);
  const эффект = (строка, цвет) => {
    текст(строка, ЭКР.ш / 2, yЭффекта, { размер: 22, выравн: 'center', цвет });
    yЭффекта += 26;
  };
  if (и.праймОсталось > 0) эффект('ПРАЙМ ' + и.праймОсталось.toFixed(1), ЦВЕТ.золото);
  if (и.шварц > 0)         эффект('ШВАРЦ ' + и.шварц.toFixed(1), '#6cff9a');
  if (и.баффБелуги > 0)    эффект('БЕЛУГА ' + и.баффБелуги.toFixed(1), '#8fd8ff');

  // собранный билд слева внизу
  const ключи = Object.keys(и.апгрейды);
  const размерИконки = 44, шаг = 52;
  let x = поля + размерИконки / 2;
  const y = ЭКР.в - поля - размерИконки / 2;
  for (const ид of ключи) {
    const а = АПГРЕЙДЫ.find(u => u.ид === ид);
    if (!а) continue;
    кт.save();
    кт.fillStyle = 'rgba(16,14,22,0.75)';
    скруглённыйПрямоугольник(x - размерИконки / 2, y - размерИконки / 2, размерИконки, размерИконки, 8);
    кт.fill();
    кт.strokeStyle = 'rgba(220,215,235,0.25)'; кт.lineWidth = 1.5; кт.stroke();
    кт.restore();
    нарисоватьИконку(а.иконка, x, y, размерИконки - 12);
    текст('' + и.апгрейды[ид], x + размерИконки / 2 - 4, y + размерИконки / 2 - 4, {
      размер: 15, выравн: 'right', базовая: 'bottom', цвет: ЦВЕТ.золото
    });
    x += шаг;
  }

  // полоска здоровья босса во всю верхнюю часть экрана
  const босс = ИГРА.босс;
  if (босс && босс.мёртв) ИГРА.босс = null;
  if (босс && !босс.мёртв && ИГРА.враги.indexOf(босс) >= 0) {
    const шп = Math.min(760, ЭКР.ш - 40);
    const x = ЭКР.ш / 2 - шп / 2, y = поля + 68 * у;
    полоска(x, y, шп, 18 * у, босс.hp / босс.максHp, ЦВЕТ.хп, ЦВЕТ.хпФон, 6);

    /* Засечка на половине: у босса там меняется поведение. Игрок должен
       видеть, что фаза приближается, а не удивляться ей. У босса без второй
       фазы засечки нет — врать разметкой нельзя. */
    if (босс.шаблон.фаза2) {
      кт.save();
      кт.strokeStyle = босс.фаза2 ? 'rgba(255,204,68,0.9)' : 'rgba(255,255,255,0.75)';
      кт.lineWidth = 2;
      кт.beginPath();
      кт.moveTo(x + шп / 2, y - 3 * у);
      кт.lineTo(x + шп / 2, y + 18 * у + 3 * у);
      кт.stroke();
      кт.restore();
    }

    текст(босс.шаблон.имя + (босс.фаза2 ? '  ·  ФАЗА 2' : ''), ЭКР.ш / 2, y - 22 * у, {
      размер: 21 * у, выравн: 'center', цвет: босс.фаза2 ? ЦВЕТ.золото : ЦВЕТ.хп
    });
    текст(Math.max(0, Math.ceil(босс.hp)) + ' / ' + Math.round(босс.максHp),
          ЭКР.ш / 2, y + 9 * у, { размер: 13 * у, выравн: 'center', базовая: 'middle' });
  }

  // ускорение времени включено
  if (ИГРА.множительВремени !== 1 && !МОБИЛЬНЫЙ) {
    текст('x' + ИГРА.множительВремени + ' УСКОРЕНИЕ (T)', ЭКР.ш - поля, поля + 30 * у, {
      размер: 16, выравн: 'right', цвет: ЦВЕТ.золото
    });
  }

  // Счётчик кадров: включается по F. Нужен, чтобы снять реальные цифры
  // на телефоне — в эмуляторе они ничего не значат.
  if (ИГРА.показыватьFPS) {
    текст(ИГРА.fps + ' fps   врагов ' + ИГРА.враги.length, поля, ЭКР.в - 26 * у, {
      размер: 15 * у, цвет: ЦВЕТ.зелёный
    });
  }

  /* --- указатели на лут за краем экрана ---
     Предмет, которого не видно, для игрока не существует: без стрелки вся
     выкладка лута работала бы только когда повезло смотреть в ту сторону. */
  for (const п of ИГРА.предметы) {
    const свой = п.вид === 'cherep' ? '#6cff9a' : '#8fd8ff';
    const мигает = п.жизнь < ЛУТ.мигание;
    const альфа = мигает ? 0.4 + Math.abs(Math.sin(ИГРА.времяВсего * 9)) * 0.6 : 0.85;
    const т = указательЗаКрай(п.x, п.y, свой, 17, альфа, 70);
    if (!т) continue;
    // иконка предмета сидит верхом на стрелке — видно, за чем бежать
    const ключ = п.вид === 'cherep' ? 'item_cherep' : 'item_beluga';
    кт.save();
    кт.globalAlpha = альфа;
    нарисоватьИконку(ключ, т.x - Math.cos(т.угол) * 26, т.y - Math.sin(т.угол) * 26, 26 * у);
    кт.restore();
  }

  // --- стрелка к клетке: ник, метры и обратный отсчёт ---
  const кл = ИГРА.клетка;
  if (кл && кл.тает <= 0 && !кл.открыта) {
    const цx = ЭКР.ш / 2, цy = ЭКР.в / 2;
    const эx = мирВЭкранX(кл.x), эy = мирВЭкранY(кл.y);
    const вКадре = эx > 60 && эx < ЭКР.ш - 60 && эy > 60 && эy < ЭКР.в - 60;
    if (!вКадре) {
      const угол = Math.atan2(эy - цy, эx - цx);
      const радX = ЭКР.ш / 2 - 96, радY = ЭКР.в / 2 - 96;
      const сx = цx + Math.cos(угол) * радX, сy = цy + Math.sin(угол) * радY;

      const доля = зажать(кл.осталось / ИВЕНТ.времяНаСпасение, 0, 1);
      // чем меньше остаётся, тем краснее и быстрее пульсация
      const частота = 3 + (1 - доля) * 12;
      const пульс = 0.55 + Math.abs(Math.sin(ИГРА.времяВсего * частота)) * 0.45;
      const цвет = доля > 0.5 ? '#8fd6ff' : (доля > 0.25 ? '#ffcc44' : '#ff5a5a');
      const метры = Math.round(дистанция(кл.x, кл.y, ИГРА.игрок.x, ИГРА.игрок.y) / 32);

      кт.save();
      кт.globalAlpha = пульс;
      кт.translate(сx, сy);
      кт.rotate(угол);
      кт.fillStyle = цвет;
      кт.beginPath();
      кт.moveTo(26, 0); кт.lineTo(-14, -17); кт.lineTo(-6, 0); кт.lineTo(-14, 17);
      кт.closePath(); кт.fill();
      кт.restore();

      // табличка с цифрами: игрок решает бежать или нет именно по ним
      const ник = кл.донатер.ник;
      const строка2 = метры + ' м   ' + Math.ceil(кл.осталось) + ' сек';
      const рН = 17 * у, рС = 16 * у;
      const шп = Math.max(ширинаТекста(ник, рН), ширинаТекста(строка2, рС, '700')) + 22;
      const пx = зажать(сx, шп / 2 + 8, ЭКР.ш - шп / 2 - 8);
      const пy = зажать(сy + (Math.sin(угол) > 0 ? -60 : 40), 40, ЭКР.в - 70);
      кт.save();
      кт.globalAlpha = 0.9;
      кт.fillStyle = 'rgba(16,14,22,0.85)';
      const вп = 30 * у + рС;
      скруглённыйПрямоугольник(пx - шп / 2, пy - 6, шп, вп, 8); кт.fill();
      кт.strokeStyle = цвет; кт.lineWidth = 2;
      скруглённыйПрямоугольник(пx - шп / 2, пy - 6, шп, вп, 8); кт.stroke();
      кт.restore();
      текст(ник, пx, пy, { размер: рН, выравн: 'center', цвет: '#f2f0f6' });
      текст(строка2, пx, пy + рН + 6, { размер: рС, вес: '700', выравн: 'center', цвет: цвет });
    }
  }

  // --- список спасённых с иконками бонусов ---
  if (ИГРА.спасённые.length) {
    // если сверху висит полоска босса, список уходит под неё
    const боссНаЭкране = босс && !босс.мёртв && ИГРА.враги.indexOf(босс) >= 0;
    let y = поля + (узкийHUD ? 56 * у : 58) + (боссНаЭкране ? 56 * у : 0);
    const рн = 15 * у;
    текст('СПАСЕНЫ', ЭКР.ш - поля, y, { размер: 13 * у, выравн: 'right', цвет: ЦВЕТ.текстТускл });
    y += 22 * у;
    for (const с of ИГРА.спасённые) {
      const шн = ширинаТекста(с.ник, рн);
      нарисоватьИконку(с.иконка, ЭКР.ш - поля - шн - 20 * у, y + 7 * у, 24 * у);
      текст(с.ник, ЭКР.ш - поля, y, { размер: рн, выравн: 'right', цвет: ЦВЕТ.зелёный });
      y += 27 * у;
    }
  }

  // призрачный режим
  if (ИГРА.игрок.призрак > 0) {
    текст('ПРИЗРАК ' + ИГРА.игрок.призрак.toFixed(1), поля, поля + 52, {
      размер: 20, цвет: '#b98ce0'
    });
  }

  // подсказка на первых секундах
  if (ИГРА.время < 7) {
    кт.globalAlpha = зажать((7 - ИГРА.время) / 2.5, 0, 1);
    const подсказка = МОБИЛЬНЫЙ
      ? 'ВЕДИ ПАЛЬЦЕМ. ГАНТЕЛЯ САМА.'
      : 'WASD ИЛИ СТРЕЛКИ. ГАНТЕЛЯ ЛЕТИТ САМА.';
    let рП = 22 * (МОБИЛЬНЫЙ ? у : 1);
    while (ширинаТекста(подсказка, рП) > ЭКР.ш - 40 && рП > 11) рП -= 1;
    текст(подсказка, ЭКР.ш / 2, ЭКР.в - 70, {
      размер: рП, выравн: 'center', цвет: ЦВЕТ.текстТускл
    });
    кт.globalAlpha = 1;
  }
}


