"use strict";
/* ==========================================================================
   ОНЛАЙН: СВЯЗЬ С СЕРВЕРОМ КОМНАТ (этап 1c, слой связи и лобби)

   Отдельный файл, и это не про порядок в папке. Сингл — то, чем игра живёт
   каждый день, и он обязан работать при мёртвом сервере, закрытом порту,
   блокировщике и отсутствии вебсокетов вообще. Поэтому вся сеть заперта
   здесь, а engine.js и ui.js обращаются к ней только через объект ОНЛАЙН.
   Ни одна строка ниже не выполняется, пока игрок сам не нажал ОНЛАЙН.

   Сервер авторитетный: мир считает он, клиент шлёт ввод и рисует присланное.
   Формат — общий protocol.js, тот же файл, что лежит на сервере.

   ЧТО ЗДЕСЬ ЕСТЬ: соединение, лобби (создать, войти по коду, быстрая игра),
   состав комнаты, старт, экран выбора карточки, конец забега, разрыв и
   возврат по коду, замер задержки, кнопка «сломалось», отрисовка боя из
   снапшотов с интерполяцией чужих, предсказание своего персонажа с поправкой
   по подтверждённому вводу и счётчик расхождений.

   ЧЕГО ЕЩЁ НЕТ: свита, снаряды и телеграфы в снапшот не входят — на клиенте
   они пустые. Это видно в бою и это следующая работа, а не забытая мелочь.
   ========================================================================== */

/* Адрес игрового сервера. Страница отдаётся по https, значит соединение
   обязано быть wss — браузер иначе заблокирует его как смешанное. */
const АДРЕС_ИГРОВОГО = 'wss://game.syslov171.com/ws';

/* Кнопка ОНЛАЙН в меню появляется только по ?online=1, пока не пройден
   закрытый прогон на четверых. Показывать сырой режим всему стриму — это
   раздать людям кнопку, которая половине не заработает, и потом месяц
   объяснять в чате, что «онлайн вообще-то ещё не онлайн». */
const ОНЛАЙН_ОТКРЫТ = /[?&]online=1/.test(location.search);

const ОНЛАЙН = {
  доступен: typeof WebSocket === 'function',
  открыт: ОНЛАЙН_ОТКРЫТ,
  сокет: null,
  /* выкл | подключение | лобби | бой | конец */
  состояние: 'выкл',
  код: '',                  // код комнаты, его диктуют голосом
  слот: -1,
  хост: -1,
  состав: [],               // [{ слот, ник, наСвязи }]
  ошибка: '',               // последний отказ сервера, словами
  сообщение: '',            // что сейчас происходит, для экрана
  сид: 0,
  типыВрагов: [],           // код врага в снапшоте -> имя типа
  выбор: null,              // открытый экран выбора: { вид, варианты, твой, секунд }
  итог: null,
  задержка: 0,              // мс, замер пингом
  расхождения: 0,
  снапшот: null,            // последний разобранный
  снапшотов: 0,
  событий: 0,
  номерВвода: 0,
  подтверждённыйВвод: 0,
  журнал: []                // последние события клиента, уезжают с жалобой
};

/* Свежие события клиента. Уходят вместе с кнопкой «сломалось»: жалоба без
   них — это «у меня не работает», по которой чинить нечего. */
function онлайнЗапись(текст) {
  ОНЛАЙН.журнал.push({ т: Math.round(performance.now()), текст: String(текст).slice(0, 120) });
  if (ОНЛАЙН.журнал.length > 60) ОНЛАЙН.журнал.shift();
}

function онлайнСброс() {
  ОНЛАЙН.код = '';
  ОНЛАЙН.слот = -1;
  ОНЛАЙН.хост = -1;
  ОНЛАЙН.состав = [];
  ОНЛАЙН.выбор = null;
  ОНЛАЙН.итог = null;
  ОНЛАЙН.снапшот = null;
  ОНЛАЙН.снапшотов = 0;
  ОНЛАЙН.событий = 0;
  ОНЛАЙН.номерВвода = 0;
  ОНЛАЙН.подтверждённыйВвод = 0;
  ОНЛАЙН.расхождения = 0;
}

function онлайнОтключиться(причина) {
  if (ОНЛАЙН.сокет) {
    try { ОНЛАЙН.сокет.close(); } catch (e) { /* уже закрыт */ }
  }
  ОНЛАЙН.сокет = null;
  ОНЛАЙН.состояние = 'выкл';
  ОНЛАЙН.сообщение = причина || '';
  онлайнСброс();
}

function онлайнПослать(объект) {
  const с = ОНЛАЙН.сокет;
  if (!с || с.readyState !== 1) return false;
  try { с.send(JSON.stringify(объект)); return true; } catch (e) { return false; }
}

/* Вход в игру. действие: создать | войти | быстрая.
   Ошибку показываем словами на экране — молчащая кнопка здесь означает
   человека, который жмёт ВОЙТИ и уходит с мыслью, что онлайна нет. */
function онлайнВойти(действие, код) {
  if (!ОНЛАЙН.доступен) { ОНЛАЙН.ошибка = 'Браузер не умеет вебсокеты'; return; }
  if (ОНЛАЙН.сокет) онлайнОтключиться('');

  ОНЛАЙН.ошибка = '';
  ОНЛАЙН.состояние = 'подключение';
  ОНЛАЙН.сообщение = 'соединяюсь с сервером...';
  онлайнЗапись('вход: ' + действие + (код ? ' ' + код : ''));

  let с;
  try { с = new WebSocket(АДРЕС_ИГРОВОГО); } catch (e) {
    ОНЛАЙН.состояние = 'выкл';
    ОНЛАЙН.ошибка = 'Не удалось открыть соединение';
    return;
  }
  ОНЛАЙН.сокет = с;
  с.binaryType = 'arraybuffer';

  с.onopen = () => {
    ОНЛАЙН.сообщение = 'сервер ответил';
    const ник = (typeof прочитатьНик === 'function' ? прочитатьНик() : '') || 'аноним';
    if (действие === 'войти') онлайнПослать({ т: 'войти', код: String(код || '').toUpperCase().trim(), ник });
    else if (действие === 'быстрая') онлайнПослать({ т: 'быстрая', ник });
    else онлайнПослать({ т: 'создать', ник });
    онлайнПинг();
  };

  с.onmessage = (е) => {
    if (typeof е.data !== 'string') { онлайнДвоичное(е.data); return; }
    let сооб;
    try { сооб = JSON.parse(е.data); } catch (ошибка) { return; }
    онлайнСообщение(сооб);
  };

  /* Обрыв и отказ — разные беды, и лечатся по-разному: при отказе виноват
     запрос, при обрыве связь. Слить их в одно «что-то пошло не так» значит
     отправить игрока чинить не то. */
  с.onerror = () => { онлайнЗапись('ошибка сокета'); };
  с.onclose = () => {
    онлайнЗапись('соединение закрыто');
    if (ОНЛАЙН.состояние === 'бой') {
      ОНЛАЙН.сообщение = 'связь потеряна, можно вернуться по коду ' + ОНЛАЙН.код;
      /* Молча оставить человека в замершем бою — худшее из возможного:
         он будет водить пальцем по мёртвой картинке. */
      try { ИГРА.экран = 'онлайн'; } catch (e) {}
    } else if (!ОНЛАЙН.ошибка) {
      ОНЛАЙН.сообщение = 'соединение закрыто';
    }
    ОНЛАЙН.сокет = null;
    if (ОНЛАЙН.состояние !== 'конец') ОНЛАЙН.состояние = 'выкл';
  };
}

function онлайнСообщение(с) {
  const т = с && с.т;
  if (т === 'комната') {
    ОНЛАЙН.состояние = 'лобби';
    ОНЛАЙН.код = с.код || ОНЛАЙН.код;
    ОНЛАЙН.слот = typeof с.слот === 'number' ? с.слот : ОНЛАЙН.слот;
    ОНЛАЙН.хост = typeof с.хост === 'number' ? с.хост : -1;
    ОНЛАЙН.состав = Array.isArray(с.игроки) ? с.игроки : [];
    ОНЛАЙН.сообщение = '';
    онлайнЗапись('комната ' + ОНЛАЙН.код + ', слот ' + ОНЛАЙН.слот);
    return;
  }
  if (т === 'старт') {
    ОНЛАЙН.состояние = 'бой';
    ОНЛАЙН.сид = с.сид;
    ОНЛАЙН.слот = typeof с.слот === 'number' ? с.слот : ОНЛАЙН.слот;
    ОНЛАЙН.типыВрагов = Array.isArray(с.типы) ? с.типы : [];
    ОНЛАЙН.выбор = null;
    ОНЛАЙН.сообщение = с.возврат ? 'вернулся в забег' : '';
    /* Забег начался — показываем бой, а не лобби. Состояние мира приедет
       снапшотами; до первого кадра рисуется прошлый экран, это доли секунды. */
    онлайнНачатьБой();
    онлайнЗапись('старт, слотов ' + с.слотов + (с.возврат ? ', возврат' : ''));
    return;
  }
  /* Мир встал и ждёт выбора карточки. Ждёт он не вечно: не ответил за
     отведённые секунды — сервер выберет сам, и это правильно, иначе один
     отошедший хост морозит забег троим. */
  if (т === 'выбор') {
    ОНЛАЙН.выбор = {
      вид: с.вид, варианты: с.варианты || [], твой: !!с.твой,
      секунд: с.секунд || 15, открыт: performance.now()
    };
    онлайнЗапись('выбор: ' + с.вид + (с.твой ? ' (мой)' : ''));
    return;
  }
  if (т === 'выборСделан') { ОНЛАЙН.выбор = null; return; }
  if (т === 'конец') {
    ОНЛАЙН.состояние = 'конец';
    ОНЛАЙН.итог = с.итог || null;
    ОНЛАЙН.выбор = null;
    /* Забег кончился — возвращаем экран онлайна: на нём есть итог, кнопка
       «сломалось» и выход. Бросить игрока в застывшем бою нельзя. */
    try { ИГРА.экран = 'онлайн'; } catch (e) { /* игра ещё не поднялась */ }
    онлайнЗапись('конец забега');
    return;
  }
  if (т === 'ошибка') {
    ОНЛАЙН.ошибка = String(с.причина || 'сервер отказал').slice(0, 160);
    онлайнЗапись('отказ: ' + ОНЛАЙН.ошибка);
    if (ОНЛАЙН.состояние === 'подключение') ОНЛАЙН.состояние = 'выкл';
    return;
  }
  if (т === 'понг') {
    ОНЛАЙН.задержка = Math.round(performance.now() - (с.время || performance.now()));
    return;
  }
  if (т === 'жалобаПринята') { ОНЛАЙН.сообщение = 'жалоба ушла, спасибо'; return; }
}

/* Снапшот и события. Тело разбирает общий protocol.js — тот же файл, что
   пакует их на сервере. */
function онлайнДвоичное(буфер) {
  const П = typeof SurvivorProtocol === 'object' ? SurvivorProtocol : null;
  if (!П) return;
  let вид;
  try { вид = new DataView(буфер).getUint8(0); } catch (e) { return; }
  if (вид === П.ТИП.СНАПШОТ) {
    let с;
    try { с = П.разобратьСнапшот(буфер); } catch (e) { онлайнЗапись('битый снапшот'); return; }
    ОНЛАЙН.снапшот = с;
    ОНЛАЙН.снапшотов++;
    ОНЛАЙН.подтверждённыйВвод = с.подтверждённыйВвод;
    if (typeof онлайнПринятьСнапшот === 'function') онлайнПринятьСнапшот(с);
    return;
  }
  if (вид === П.ТИП.СОБЫТИЯ) {
    ОНЛАЙН.событий++;
    if (!ОНЛАЙН.снапшот) return;
    let список;
    try { список = П.разобратьСобытия(буфер, ОНЛАЙН.снапшот.центр); } catch (e) { return; }
    if (typeof онлайнПринятьСобытия === 'function') онлайнПринятьСобытия(список);
  }
}

/* Ввод уходит 20 раз в секунду восемью байтами. Чаще незачем: сервер считает
   мир на тех же двадцати герцах и лишние пакеты просто выбросит. */
let онлайнПоследнийВвод = 0;
function онлайнОтправитьВвод(сейчас, ввод) {
  if (ОНЛАЙН.состояние !== 'бой') return;
  const с = ОНЛАЙН.сокет;
  if (!с || с.readyState !== 1) return;
  const интервал = онлайнПоследнийВвод ? сейчас - онлайнПоследнийВвод : 50;
  if (интервал < 50) return;
  онлайнПоследнийВвод = сейчас;
  const П = typeof SurvivorProtocol === 'object' ? SurvivorProtocol : null;
  if (!П) return;
  ОНЛАЙН.номерВвода++;
  try {
    с.send(П.собратьВвод({
      номер: ОНЛАЙН.номерВвода,
      x: ввод.x, y: ввод.y, dash: !!ввод.dash
    }));
  } catch (e) { /* закрылось между проверкой и отправкой */ }
  /* Тот же шаг кладём в историю: когда придёт подтверждение, именно эти
     непроигранные вводы переигрываются поверх авторитетной позиции. Шаг
     берётся фактический, а не кадровый — сервер учтёт ровно этот пакет. */
  if (typeof онлайнЗапомнитьВвод === 'function') {
    онлайнЗапомнитьВвод(ОНЛАЙН.номерВвода, ввод, Math.min(0.2, интервал / 1000));
  }
  return ОНЛАЙН.номерВвода;
}

/* Задержка мерится своим пингом, а не сетевым: игроку важно время до мира,
   а не до сетевой карты. Раз в две секунды — этого хватает, чтобы заметить
   деградацию, и не хватает, чтобы самому её создать. */
function онлайнПинг() {
  if (!ОНЛАЙН.сокет || ОНЛАЙН.сокет.readyState !== 1) return;
  онлайнПослать({ т: 'пинг', время: performance.now() });
  setTimeout(онлайнПинг, 2000);
}

function онлайнСтарт() {
  if (ОНЛАЙН.состояние !== 'лобби') return;
  if (ОНЛАЙН.слот !== ОНЛАЙН.хост) { ОНЛАЙН.ошибка = 'Забег запускает хост комнаты'; return; }
  онлайнПослать({ т: 'старт' });
}

function онлайнВыбрать(индекс) {
  if (!ОНЛАЙН.выбор) return;
  онлайнПослать({ т: 'выбор', индекс });
}

function онлайнВыйти() {
  онлайнПослать({ т: 'выход' });
  онлайнОтключиться('');
}

/* Кнопка «сломалось». Одна кнопка превращает жалобу в отчёт: комната, тик,
   задержка, сборка и последние события клиента. Без неё разбор бага в
   реальном времени выглядит как переписка «а что именно?» — «ну лагает». */
function онлайнЖалоба(текст) {
  онлайнПослать({
    т: 'жалоба',
    ник: (typeof прочитатьНик === 'function' ? прочитатьНик() : '') || 'аноним',
    текст: String(текст || 'сломалось'),
    задержка: ОНЛАЙН.задержка,
    сборка: (typeof ВЕРСИЯ === 'string' ? ВЕРСИЯ : '') + (ОНЛАЙН.снапшот ? ' тик ' + ОНЛАЙН.снапшот.тик : ''),
    события: ОНЛАЙН.журнал.slice(-40).map(з => з.т + ' ' + з.текст)
  });
  ОНЛАЙН.сообщение = 'жалоба ушла';
}

/* Расхождение предсказания с авторитетной позицией. Копится молча и уходит
   пачкой: сообщать о каждом кадре — это самому себе устроить нагрузку.
   Заполняется на шаге 5, здесь только точка входа. */
let онлайнПодрядРасхождений = 0;
function онлайнРасхождение(пиксели) {
  ОНЛАЙН.расхождения++;
  онлайнПодрядРасхождений++;
  if (онлайнПодрядРасхождений % 30 !== 0) return;
  онлайнПослать({ т: 'расхождение', пиксели: Math.round(пиксели), подряд: онлайнПодрядРасхождений });
}
function онлайнСошлось() { онлайнПодрядРасхождений = 0; }

/* ==========================================================================
   БОЙ ПО СНАПШОТАМ (этап 1c, шаги 4-5)

   Мир считает сервер, поэтому локальная симуляция в онлайне не шагает вообще
   (см. кадр() в engine.js). Задача этого слоя — превратить поток снапшотов в
   те же самые поля ИГРА, из которых рисует ui.js. Так у онлайна и сингла
   ОДИН рендер: второй набор отрисовки разъехался бы с первым на первой же
   правке, и половина багов жила бы только в онлайне.

   Две разные вещи делаются двумя разными способами:

   ЧУЖИЕ И МИР — интерполяция с задержкой. Показываем не последний снапшот, а
   состояние на СТО МИЛЛИСЕКУНД в прошлом, между двумя уже полученными
   кадрами. Задержка платится один раз и покупает плавность: без неё каждый
   потерянный или опоздавший кадр виден как рывок у всех врагов сразу.

   СВОЙ ПЕРСОНАЖ — предсказание. Ждать подтверждения сервера для СВОЕГО шага
   значит играть с задержкой канала в управлении, а это чувствуется сразу
   даже на двухстах миллисекундах. Поэтому свой персонаж двигается локально,
   а приходящий снапшот используется как поправка: берём авторитетную
   позицию, переигрываем поверх неё ввод, который сервер ещё не подтвердил, и
   сравниваем с тем, что нарисовали. Разошлось на волос — подтягиваем мягко,
   разошлось грубо — признаём поражение и телепортируемся, потому что честный
   рывок лучше, чем персонаж, живущий в своей вселенной.
   ========================================================================== */

const ЗАДЕРЖКА_ПОКАЗА = 100;      // мс, буфер интерполяции чужих
/* Двенадцать пикселей, а не три. Клиент предсказывает движение базовой
   скоростью, а сервер считает полную физику: инерцию, рывок, вытеснение из
   врагов и множители прокачки, которых у клиента нет. Совпадать до пикселя
   тут нечему, и порог в три пикселя означал бы «расхождение» на каждом кадре
   ровной пробежки — то есть счётчик, который всегда горит и потому ничего не
   значит. Двенадцать при росте героя в шестьдесят четыре глазом не видно, а
   настоящий разъезд начинается заметно выше. */
const ПОРОГ_ПОДТЯЖКИ = 12;        // px, ниже — считаем, что сошлось
const ПОРОГ_ТЕЛЕПОРТА = 220;      // px, выше — предсказание проиграло

ОНЛАЙН.буфер = [];                // [{ с, время }] последние снапшоты
ОНЛАЙН.историяВвода = [];         // [{ номер, x, y, dash, дт }] неподтверждённое
ОНЛАЙН.мой = { x: 0, y: 0, есть: false };
ОНЛАЙН.врагиПоИд = new Map();     // ид -> болванка для рендера, чтобы копилась фаза

function онлайнПринятьСнапшот(с) {
  ОНЛАЙН.буфер.push({ с, время: performance.now() });
  while (ОНЛАЙН.буфер.length > 12) ОНЛАЙН.буфер.shift();
  /* Подтверждённый ввод пришёл — всё, что сервер уже учёл, из истории
     выбрасываем: переигрывать его поверх авторитетной позиции значит
     применить один и тот же шаг дважды. */
  const до = с.подтверждённыйВвод;
  while (ОНЛАЙН.историяВвода.length > 0 && ОНЛАЙН.историяВвода[0].номер <= до) {
    ОНЛАЙН.историяВвода.shift();
  }
}

function онлайнПринятьСобытия(список) {
  for (const с of список || []) {
    if (typeof звук === 'function' && с.имя) {
      try { звук(с.имя, с.громкость); } catch (e) { /* нет такого звука — не беда */ }
    }
  }
}

/* Пара снапшотов вокруг показываемого момента и доля между ними. */
function онлайнПара(сейчас) {
  const цель = сейчас - ЗАДЕРЖКА_ПОКАЗА;
  const б = ОНЛАЙН.буфер;
  if (б.length === 0) return null;
  if (б.length === 1) return { а: б[0].с, б: б[0].с, доля: 0 };
  for (let i = б.length - 1; i > 0; i--) {
    if (б[i - 1].время <= цель && б[i].время >= цель) {
      const шаг = б[i].время - б[i - 1].время;
      return { а: б[i - 1].с, б: б[i].с, доля: шаг > 0 ? (цель - б[i - 1].время) / шаг : 0 };
    }
  }
  /* Цель левее буфера — показываем самый старый; правее — самый свежий.
     Второе бывает при просадке сети, и лучше замереть на последнем кадре,
     чем прыгать вперёд по выдуманным позициям. */
  return цель < б[0].время
    ? { а: б[0].с, б: б[0].с, доля: 0 }
    : { а: б[б.length - 1].с, б: б[б.length - 1].с, доля: 0 };
}

const между = (а, б, д) => а + (б - а) * д;

/* Скорость своего персонажа. Апгрейды живут на сервере, клиент их не знает,
   поэтому берём базовую: расхождение от разницы в множителе съест поправка,
   а угадывать чужую прокачку — это второй источник правды. */
function онлайнСкорость() {
  try { return (ГЕРОЙ && ГЕРОЙ.скорость) || 240; } catch (e) { return 240; }
}

function онлайнШагПредсказания(поз, ввод, дт) {
  let x = ввод.x, y = ввод.y;
  const длина = Math.hypot(x, y);
  if (длина > 1) { x /= длина; y /= длина; }
  const ск = онлайнСкорость() * дт;
  поз.x += x * ск;
  поз.y += y * ск;
}

/* Болванка врага. Переиспользуется по ид, чтобы фаза шага копилась между
   кадрами: пересоздавать объект каждый кадр значит анимацию, стоящую на
   месте, и мусор для сборщика тридцать раз в секунду. */
function онлайнВраг(сырой, типы) {
  let в = ОНЛАЙН.врагиПоИд.get(сырой.ид);
  if (!в) {
    const имя = типы[сырой.код - 1];
    let шаблон = null;
    try { шаблон = ВРАГИ[имя] || null; } catch (e) { шаблон = null; }
    if (!шаблон) return null;
    в = {
      ид: сырой.ид, шаблон, тип: имя, x: сырой.x, y: сырой.y,
      фаза: Math.random() * 6.283, масштаб: шаблон.масштаб || 1,
      сторона: 1, гаснет: 0, вспышка: 0, замах: 0, щит: 0, встаёт: 0,
      мёртв: false, hp: 1, максHp: 1
    };
    ОНЛАЙН.врагиПоИд.set(сырой.ид, в);
  }
  return в;
}

/* Один кадр онлайна: собрать мир из снапшотов и подвинуть своего. */
function онлайнКадр(сейчас, дельта, ввод) {
  if (ОНЛАЙН.состояние !== 'бой' && ОНЛАЙН.состояние !== 'конец') return false;
  const пара = онлайнПара(сейчас);
  if (!пара) return false;
  const а = пара.а, б = пара.б, д = пара.доля;

  /* ЧУЖИЕ И МИР */
  const типы = ОНЛАЙН.типыВрагов;
  const живые = new Set();
  const враги = ИГРА.враги;
  враги.length = 0;
  const поИд = new Map();
  for (const с of б.враги) поИд.set(с.ид, с);
  for (const стар of а.враги) {
    const нов = поИд.get(стар.ид);
    const в = онлайнВраг(нов || стар, типы);
    if (!в) continue;
    живые.add(в.ид);
    в.x = нов ? между(стар.x, нов.x, д) : стар.x;
    в.y = нов ? между(стар.y, нов.y, д) : стар.y;
    const и = нов || стар;
    в.сторона = и.сторона;
    в.гаснет = и.гаснет ? 0.25 : 0;
    в.вспышка = и.вспышка ? 0.08 : 0;
    в.щит = и.щит ? 1 : 0;
    в.встаёт = и.встаёт ? 1 : 0;
    в.фаза += дельта * 6;
    враги.push(в);
  }
  for (const ид of Array.from(ОНЛАЙН.врагиПоИд.keys())) {
    if (!живые.has(ид)) ОНЛАЙН.врагиПоИд.delete(ид);
  }

  ИГРА.гантели.length = 0;
  for (const г of б.гантели) ИГРА.гантели.push({ x: г.x, y: г.y, поворот: г.поворот });
  ИГРА.кристаллы.length = 0;
  for (const к of б.кристаллы) ИГРА.кристаллы.push({ x: к.x, y: к.y, фаза: (к.x + к.y) * 0.01 + сейчас * 0.004 });
  ИГРА.предметы.length = 0;
  for (const п of б.предметы) ИГРА.предметы.push({ x: п.x, y: п.y, вид: п.вид, фаза: сейчас * 0.004 });

  /* Свита, снаряды и телеграфы в снапшот пока не входят — рисовать пустые
     массивы честнее, чем показывать чужие объекты из прошлого забега. */
  ИГРА.тараканы.length = 0;
  ИГРА.щенки.length = 0;
  ИГРА.союзники.length = 0;

  ИГРА.убито = б.убито;
  ИГРА.уровень = б.уровень;
  ИГРА.время = б.время;

  /* ОТРЯД. Свой персонаж рисуется предсказанным, чужие — интерполированными. */
  const мойСлот = ОНЛАЙН.слот;
  const образец = ИГРА.игрок;
  ОНЛАЙН.отряд = ОНЛАЙН.отряд || [];
  ОНЛАЙН.отряд.length = 0;
  const староеПоИндексу = new Map();
  for (const и of а.игроки) староеПоИндексу.set(и.индекс, и);

  for (const свежий of б.игроки) {
    const стар = староеПоИндексу.get(свежий.индекс) || свежий;
    const мой = свежий.индекс === мойСлот;
    const цель = {
      x: между(стар.x, свежий.x, д), y: между(стар.y, свежий.y, д)
    };
    if (мой) {
      онлайнПоправить(свежий, дельта, ввод);
      образец.x = ОНЛАЙН.мой.x;
      образец.y = ОНЛАЙН.мой.y;
      образец.жив = свежий.жив;
      образец.hp = свежий.hp;
      образец.сторона = свежий.сторона;
      образец.идёт = свежий.идёт;
      образец.неуязвим = свежий.неуязвим ? 0.2 : 0;
      образец.шварц = свежий.шварц ? 1 : 0;
      образец.фаза += дельта * (свежий.идёт ? 9 : 3);
      continue;
    }
    ОНЛАЙН.отряд.push({
      индекс: свежий.индекс, x: цель.x, y: цель.y, hp: свежий.hp,
      жив: свежий.жив, идёт: свежий.идёт, сторона: свежий.сторона,
      неуязвим: свежий.неуязвим ? 0.2 : 0, шварц: свежий.шварц ? 1 : 0,
      праймОсталось: свежий.прайм ? 1 : 0, щитЗаряжен: false,
      в: образец.в, ш: образец.ш, апгрейды: {},
      фаза: (образец.фаза || 0) + свежий.индекс * 1.7,
      вспышка: 0, максHp: Math.max(свежий.hp, 1)
    });
  }

  /* Камера. В сингле её двигает шаг логики, которого здесь нет: считаем сами,
     по тому же правилу и по центру ОТРЯДА, иначе камера дёргалась бы за
     своим персонажем и напарники уезжали бы за край. */
  const центр = б.центр;
  const целx = центр.x - ЭКР.ш / 2;
  const целy = (центр.y - образец.в * 0.4) - ЭКР.в / 2;
  const к = 1 - Math.pow(0.0005, дельта);
  ИГРА.камера.x += (целx - ИГРА.камера.x) * к;
  ИГРА.камера.y += (целy - ИГРА.камера.y) * к;
  return true;
}

/* Поправка предсказания по авторитетной позиции. */
function онлайнПоправить(свой, дельта, ввод) {
  const м = ОНЛАЙН.мой;
  if (!м.есть) { м.x = свой.x; м.y = свой.y; м.есть = true; return; }

  /* Лёгший никуда не бежит. Предсказывать движение мёртвого — верный способ
     получить труп, уползающий с поля, и счётчик расхождений, который растёт
     до конца забега без единой настоящей причины. */
  if (!свой.жив) { м.x = свой.x; м.y = свой.y; ОНЛАЙН.историяВвода.length = 0; онлайнСошлось(); return; }

  // свой шаг за этот кадр
  if (ввод) онлайнШагПредсказания(м, ввод, дельта);

  /* Авторитетная позиция плюс всё, что сервер ещё не подтвердил. */
  const правильно = { x: свой.x, y: свой.y };
  for (const шаг of ОНЛАЙН.историяВвода) онлайнШагПредсказания(правильно, шаг, шаг.дт);

  const разница = Math.hypot(правильно.x - м.x, правильно.y - м.y);
  if (разница > ПОРОГ_ТЕЛЕПОРТА) {
    м.x = правильно.x; м.y = правильно.y;
    онлайнРасхождение(разница);
    return;
  }
  if (разница > ПОРОГ_ПОДТЯЖКИ) {
    /* Подтягиваем долей за кадр, а не рывком: мгновенная правка на каждом
       кадре выглядит как дрожь персонажа на месте. */
    const к = 1 - Math.pow(0.001, дельта);
    м.x += (правильно.x - м.x) * к;
    м.y += (правильно.y - м.y) * к;
    онлайнРасхождение(разница);
  } else {
    онлайнСошлось();
  }
}

/* Запомнить свой ввод: он понадобится, чтобы переиграть его поверх
   авторитетной позиции, когда придёт подтверждение. */
function онлайнЗапомнитьВвод(номер, ввод, дт) {
  if (!номер) return;
  ОНЛАЙН.историяВвода.push({ номер, x: ввод.x, y: ввод.y, dash: !!ввод.dash, дт });
  if (ОНЛАЙН.историяВвода.length > 120) ОНЛАЙН.историяВвода.shift();
}

/* Начало боя: чистим всё, что осталось от прошлого забега, и переводим
   экран в бой. Старый буфер снапшотов на новом забеге означал бы один кадр
   чужого мира поверх нового — редко, но именно такие вещи и ловят в эфире. */
function онлайнНачатьБой() {
  ОНЛАЙН.буфер.length = 0;
  ОНЛАЙН.историяВвода.length = 0;
  ОНЛАЙН.врагиПоИд.clear();
  ОНЛАЙН.мой.есть = false;
  ОНЛАЙН.отряд = [];
  онлайнПоследнийВвод = 0;
  try {
    /* Локальный забег всё-таки запускается — но не ради логики, а ради
       ОБЪЕКТА игрока: у него готовые спрайты, размеры, апгрейды и всё, из
       чего рисует ui.js. Шагать эту симуляцию в онлайне нельзя и не будем
       (см. кадр() в engine.js), позиции переписываются из снапшотов. Иначе
       пришлось бы собирать болванку героя вручную и держать её в согласии
       с ядром — вторая правда о том, как выглядит Илья. */
    if (typeof начатьЗабег === 'function') начатьЗабег();
    ИГРА.частицы.length = ИГРА.всплывашки.length = ИГРА.пузыри.length = 0;
    ИГРА.экран = 'бой';
  } catch (e) { /* игра ещё не поднялась */ }
}
