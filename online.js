"use strict";
/* ==========================================================================
   ОНЛАЙН: СВЯЗЬ С СЕРВЕРОМ КОМНАТ (этап 1c, слой связи и лобби)

   Отдельный файл, и это не про порядок в папке. Сингл — то, чем игра живёт
   каждый день, и он обязан работать при мёртвом сервере, закрытом порту,
   блокировщике и отсутствии вебсокетов вообще. Поэтому вся сеть заперта
   здесь, а engine.js и ui.js обращаются к ней только через объект ОНЛАЙН.
   Ни одна строка ниже не выполняется, пока игрок сам не нажал ОНЛАЙН.

   Сервер авторитетный: мир считает он, клиент шлёт ввод и рисует присланное.
   Формат — общий protocol.js, тот же файл, что лежит на сервере.

   ЧТО ЗДЕСЬ ЕСТЬ УЖЕ: соединение, лобби (создать, войти по коду, быстрая
   игра), состав комнаты, старт, экран выбора карточки, конец забега, разрыв
   и возврат, замер задержки, кнопка «сломалось», приём снапшотов в буфер.
   ЧТО БУДЕТ ДАЛЬШЕ (шаги 4-6): отрисовка боя из снапшотов, предсказание
   своего персонажа и счётчик расхождений.
   ========================================================================== */

/* Адрес игрового сервера. Страница отдаётся по https, значит соединение
   обязано быть wss — браузер иначе заблокирует его как смешанное. */
const АДРЕС_ИГРОВОГО = 'wss://game.syslov171.com/ws';

/* Кнопка ОНЛАЙН в меню появляется только по ?online=1, пока не пройден
   закрытый прогон на четверых. Показывать сырой режим всему стриму — это
   раздать людям кнопку, которая половине не заработает, и потом месяц
   объяснять в чате, что «онлайн вообще-то ещё не онлайн». */
const ОНЛАЙН_ОТКРЫТ = /[?&]online=1/.test(location.search);

const ОНЛАЙН = {
  доступен: typeof WebSocket === 'function',
  открыт: ОНЛАЙН_ОТКРЫТ,
  сокет: null,
  /* выкл | подключение | лобби | бой | конец */
  состояние: 'выкл',
  код: '',                  // код комнаты, его диктуют голосом
  слот: -1,
  хост: -1,
  состав: [],               // [{ слот, ник, наСвязи }]
  ошибка: '',               // последний отказ сервера, словами
  сообщение: '',            // что сейчас происходит, для экрана
  сид: 0,
  типыВрагов: [],           // код врага в снапшоте -> имя типа
  выбор: null,              // открытый экран выбора: { вид, варианты, твой, секунд }
  итог: null,
  задержка: 0,              // мс, замер пингом
  расхождения: 0,
  снапшот: null,            // последний разобранный
  снапшотов: 0,
  событий: 0,
  номерВвода: 0,
  подтверждённыйВвод: 0,
  журнал: []                // последние события клиента, уезжают с жалобой
};

/* Свежие события клиента. Уходят вместе с кнопкой «сломалось»: жалоба без
   них — это «у меня не работает», по которой чинить нечего. */
function онлайнЗапись(текст) {
  ОНЛАЙН.журнал.push({ т: Math.round(performance.now()), текст: String(текст).slice(0, 120) });
  if (ОНЛАЙН.журнал.length > 60) ОНЛАЙН.журнал.shift();
}

function онлайнСброс() {
  ОНЛАЙН.код = '';
  ОНЛАЙН.слот = -1;
  ОНЛАЙН.хост = -1;
  ОНЛАЙН.состав = [];
  ОНЛАЙН.выбор = null;
  ОНЛАЙН.итог = null;
  ОНЛАЙН.снапшот = null;
  ОНЛАЙН.снапшотов = 0;
  ОНЛАЙН.событий = 0;
  ОНЛАЙН.номерВвода = 0;
  ОНЛАЙН.подтверждённыйВвод = 0;
  ОНЛАЙН.расхождения = 0;
}

function онлайнОтключиться(причина) {
  if (ОНЛАЙН.сокет) {
    try { ОНЛАЙН.сокет.close(); } catch (e) { /* уже закрыт */ }
  }
  ОНЛАЙН.сокет = null;
  ОНЛАЙН.состояние = 'выкл';
  ОНЛАЙН.сообщение = причина || '';
  онлайнСброс();
}

function онлайнПослать(объект) {
  const с = ОНЛАЙН.сокет;
  if (!с || с.readyState !== 1) return false;
  try { с.send(JSON.stringify(объект)); return true; } catch (e) { return false; }
}

/* Вход в игру. действие: создать | войти | быстрая.
   Ошибку показываем словами на экране — молчащая кнопка здесь означает
   человека, который жмёт ВОЙТИ и уходит с мыслью, что онлайна нет. */
function онлайнВойти(действие, код) {
  if (!ОНЛАЙН.доступен) { ОНЛАЙН.ошибка = 'Браузер не умеет вебсокеты'; return; }
  if (ОНЛАЙН.сокет) онлайнОтключиться('');

  ОНЛАЙН.ошибка = '';
  ОНЛАЙН.состояние = 'подключение';
  ОНЛАЙН.сообщение = 'соединяюсь с сервером...';
  онлайнЗапись('вход: ' + действие + (код ? ' ' + код : ''));

  let с;
  try { с = new WebSocket(АДРЕС_ИГРОВОГО); } catch (e) {
    ОНЛАЙН.состояние = 'выкл';
    ОНЛАЙН.ошибка = 'Не удалось открыть соединение';
    return;
  }
  ОНЛАЙН.сокет = с;
  с.binaryType = 'arraybuffer';

  с.onopen = () => {
    ОНЛАЙН.сообщение = 'сервер ответил';
    const ник = (typeof прочитатьНик === 'function' ? прочитатьНик() : '') || 'аноним';
    if (действие === 'войти') онлайнПослать({ т: 'войти', код: String(код || '').toUpperCase().trim(), ник });
    else if (действие === 'быстрая') онлайнПослать({ т: 'быстрая', ник });
    else онлайнПослать({ т: 'создать', ник });
    онлайнПинг();
  };

  с.onmessage = (е) => {
    if (typeof е.data !== 'string') { онлайнДвоичное(е.data); return; }
    let сооб;
    try { сооб = JSON.parse(е.data); } catch (ошибка) { return; }
    онлайнСообщение(сооб);
  };

  /* Обрыв и отказ — разные беды, и лечатся по-разному: при отказе виноват
     запрос, при обрыве связь. Слить их в одно «что-то пошло не так» значит
     отправить игрока чинить не то. */
  с.onerror = () => { онлайнЗапись('ошибка сокета'); };
  с.onclose = () => {
    онлайнЗапись('соединение закрыто');
    if (ОНЛАЙН.состояние === 'бой') {
      ОНЛАЙН.сообщение = 'связь потеряна, можно вернуться по коду ' + ОНЛАЙН.код;
    } else if (!ОНЛАЙН.ошибка) {
      ОНЛАЙН.сообщение = 'соединение закрыто';
    }
    ОНЛАЙН.сокет = null;
    if (ОНЛАЙН.состояние !== 'конец') ОНЛАЙН.состояние = 'выкл';
  };
}

function онлайнСообщение(с) {
  const т = с && с.т;
  if (т === 'комната') {
    ОНЛАЙН.состояние = 'лобби';
    ОНЛАЙН.код = с.код || ОНЛАЙН.код;
    ОНЛАЙН.слот = typeof с.слот === 'number' ? с.слот : ОНЛАЙН.слот;
    ОНЛАЙН.хост = typeof с.хост === 'number' ? с.хост : -1;
    ОНЛАЙН.состав = Array.isArray(с.игроки) ? с.игроки : [];
    ОНЛАЙН.сообщение = '';
    онлайнЗапись('комната ' + ОНЛАЙН.код + ', слот ' + ОНЛАЙН.слот);
    return;
  }
  if (т === 'старт') {
    ОНЛАЙН.состояние = 'бой';
    ОНЛАЙН.сид = с.сид;
    ОНЛАЙН.слот = typeof с.слот === 'number' ? с.слот : ОНЛАЙН.слот;
    ОНЛАЙН.типыВрагов = Array.isArray(с.типы) ? с.типы : [];
    ОНЛАЙН.выбор = null;
    ОНЛАЙН.сообщение = с.возврат ? 'вернулся в забег' : '';
    онлайнЗапись('старт, слотов ' + с.слотов + (с.возврат ? ', возврат' : ''));
    return;
  }
  /* Мир встал и ждёт выбора карточки. Ждёт он не вечно: не ответил за
     отведённые секунды — сервер выберет сам, и это правильно, иначе один
     отошедший хост морозит забег троим. */
  if (т === 'выбор') {
    ОНЛАЙН.выбор = {
      вид: с.вид, варианты: с.варианты || [], твой: !!с.твой,
      секунд: с.секунд || 15, открыт: performance.now()
    };
    онлайнЗапись('выбор: ' + с.вид + (с.твой ? ' (мой)' : ''));
    return;
  }
  if (т === 'выборСделан') { ОНЛАЙН.выбор = null; return; }
  if (т === 'конец') {
    ОНЛАЙН.состояние = 'конец';
    ОНЛАЙН.итог = с.итог || null;
    ОНЛАЙН.выбор = null;
    онлайнЗапись('конец забега');
    return;
  }
  if (т === 'ошибка') {
    ОНЛАЙН.ошибка = String(с.причина || 'сервер отказал').slice(0, 160);
    онлайнЗапись('отказ: ' + ОНЛАЙН.ошибка);
    if (ОНЛАЙН.состояние === 'подключение') ОНЛАЙН.состояние = 'выкл';
    return;
  }
  if (т === 'понг') {
    ОНЛАЙН.задержка = Math.round(performance.now() - (с.время || performance.now()));
    return;
  }
  if (т === 'жалобаПринята') { ОНЛАЙН.сообщение = 'жалоба ушла, спасибо'; return; }
}

/* Снапшот и события. Тело разбирает общий protocol.js — тот же файл, что
   пакует их на сервере. */
function онлайнДвоичное(буфер) {
  const П = typeof SurvivorProtocol === 'object' ? SurvivorProtocol : null;
  if (!П) return;
  let вид;
  try { вид = new DataView(буфер).getUint8(0); } catch (e) { return; }
  if (вид === П.ТИП.СНАПШОТ) {
    let с;
    try { с = П.разобратьСнапшот(буфер); } catch (e) { онлайнЗапись('битый снапшот'); return; }
    ОНЛАЙН.снапшот = с;
    ОНЛАЙН.снапшотов++;
    ОНЛАЙН.подтверждённыйВвод = с.подтверждённыйВвод;
    if (typeof онлайнПринятьСнапшот === 'function') онлайнПринятьСнапшот(с);
    return;
  }
  if (вид === П.ТИП.СОБЫТИЯ) {
    ОНЛАЙН.событий++;
    if (!ОНЛАЙН.снапшот) return;
    let список;
    try { список = П.разобратьСобытия(буфер, ОНЛАЙН.снапшот.центр); } catch (e) { return; }
    if (typeof онлайнПринятьСобытия === 'function') онлайнПринятьСобытия(список);
  }
}

/* Ввод уходит 20 раз в секунду восемью байтами. Чаще незачем: сервер считает
   мир на тех же двадцати герцах и лишние пакеты просто выбросит. */
let онлайнПоследнийВвод = 0;
function онлайнОтправитьВвод(сейчас, ввод) {
  if (ОНЛАЙН.состояние !== 'бой') return;
  const с = ОНЛАЙН.сокет;
  if (!с || с.readyState !== 1) return;
  if (сейчас - онлайнПоследнийВвод < 50) return;
  онлайнПоследнийВвод = сейчас;
  const П = typeof SurvivorProtocol === 'object' ? SurvivorProtocol : null;
  if (!П) return;
  ОНЛАЙН.номерВвода++;
  try {
    с.send(П.собратьВвод({
      номер: ОНЛАЙН.номерВвода,
      x: ввод.x, y: ввод.y, dash: !!ввод.dash
    }));
  } catch (e) { /* закрылось между проверкой и отправкой */ }
  return ОНЛАЙН.номерВвода;
}

/* Задержка мерится своим пингом, а не сетевым: игроку важно время до мира,
   а не до сетевой карты. Раз в две секунды — этого хватает, чтобы заметить
   деградацию, и не хватает, чтобы самому её создать. */
function онлайнПинг() {
  if (!ОНЛАЙН.сокет || ОНЛАЙН.сокет.readyState !== 1) return;
  онлайнПослать({ т: 'пинг', время: performance.now() });
  setTimeout(онлайнПинг, 2000);
}

function онлайнСтарт() {
  if (ОНЛАЙН.состояние !== 'лобби') return;
  if (ОНЛАЙН.слот !== ОНЛАЙН.хост) { ОНЛАЙН.ошибка = 'Забег запускает хост комнаты'; return; }
  онлайнПослать({ т: 'старт' });
}

function онлайнВыбрать(индекс) {
  if (!ОНЛАЙН.выбор) return;
  онлайнПослать({ т: 'выбор', индекс });
}

function онлайнВыйти() {
  онлайнПослать({ т: 'выход' });
  онлайнОтключиться('');
}

/* Кнопка «сломалось». Одна кнопка превращает жалобу в отчёт: комната, тик,
   задержка, сборка и последние события клиента. Без неё разбор бага в
   реальном времени выглядит как переписка «а что именно?» — «ну лагает». */
function онлайнЖалоба(текст) {
  онлайнПослать({
    т: 'жалоба',
    ник: (typeof прочитатьНик === 'function' ? прочитатьНик() : '') || 'аноним',
    текст: String(текст || 'сломалось'),
    задержка: ОНЛАЙН.задержка,
    сборка: (typeof ВЕРСИЯ === 'string' ? ВЕРСИЯ : '') + (ОНЛАЙН.снапшот ? ' тик ' + ОНЛАЙН.снапшот.тик : ''),
    события: ОНЛАЙН.журнал.slice(-40).map(з => з.т + ' ' + з.текст)
  });
  ОНЛАЙН.сообщение = 'жалоба ушла';
}

/* Расхождение предсказания с авторитетной позицией. Копится молча и уходит
   пачкой: сообщать о каждом кадре — это самому себе устроить нагрузку.
   Заполняется на шаге 5, здесь только точка входа. */
let онлайнПодрядРасхождений = 0;
function онлайнРасхождение(пиксели) {
  ОНЛАЙН.расхождения++;
  онлайнПодрядРасхождений++;
  if (онлайнПодрядРасхождений % 30 !== 0) return;
  онлайнПослать({ т: 'расхождение', пиксели: Math.round(пиксели), подряд: онлайнПодрядРасхождений });
}
function онлайнСошлось() { онлайнПодрядРасхождений = 0; }
