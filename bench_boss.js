/* Замер времени жизни боссов автопилотом. Браузер не нужен.
   Запуск: node bench_boss.js  [имя_босса ...]

   Зачем: у босса ориентир не «столько-то hp», а СКОЛЬКО ОН ЖИВЁТ при
   среднем билде своей минуты. 20–35 секунд: меньше — не ощущается боссом,
   больше — становится скучным. Абсолютные hp ничего не говорят, потому что
   урон игрока к шестой минуте отличается от третьей в разы.

   Как считает: играет забег автопилотом до минуты выхода босса, набирая
   карты случайно (это и есть «средний билд»), потом вызывает босса и
   замеряет, сколько секунд он прожил. Игрок бессмертен: замеряем урон
   игрока по боссу, а не выживание.

   Прогонов несколько, потому что билд случаен — смотреть надо на медиану
   и на разброс. Если разброс шире 20 секунд, дело не в hp, а в том, что
   босс слишком чувствителен к одной конкретной карте.
*/

const { поднять } = require('./test_env.js');

const ШАГ = 1 / 60;
const дистанция = (ax, ay, bx, by) => Math.hypot(ax - bx, ay - by);

/* Направление в градусах -> зажатые WASD. Игра читает только клавиши,
   поэтому автопилот обязан говорить с ней на том же языке. */
function жать(S, угол) {
  const дx = Math.cos(угол), дy = Math.sin(угол);
  S.клавиши.KeyW = дy < -0.35;
  S.клавиши.KeyS = дy > 0.35;
  S.клавиши.KeyA = дx < -0.35;
  S.клавиши.KeyD = дx > 0.35;
}
const ПРОГОНОВ = Number(process.env.ПРОГОНОВ || 5);
const ПРЕДЕЛ = 90;            // сек: дольше не ждём, считаем «не убит»

// какие боссы мерить и на какой минуте они выходят по ВОЛНАМ
function расписание(S) {
  const план = [];
  for (const в of S.ВОЛНЫ || []) if (в.босс) план.push({ имя: в.босс, t: в.t, множитель: в.множитель_hp });
  return план;
}

function прогон(имя, доВремени, множитель) {
  const { S, ИГРА } = поднять({ адресРейтинга: '' });
  S.начатьЗабег();
  const и = ИГРА.игрок;
  let угол = 0;

  // --- разгон до минуты босса: обычный забег, карты берутся случайно ---
  const кадровРазгона = Math.round(доВремени * 60);
  for (let к = 0; к < кадровРазгона; к++) {
    угол += 0.02;
    и.hp = и.максHp; и.неуязвим = 999;
    S.клавиши.KeyW = Math.sin(угол) < -0.3;
    S.клавиши.KeyS = Math.sin(угол) > 0.3;
    S.клавиши.KeyA = Math.cos(угол) < -0.3;
    S.клавиши.KeyD = Math.cos(угол) > 0.3;
    S.шагЛогики(ШАГ);
    if (ИГРА.экран === 'левелап' && ИГРА.карточки.length) {
      S.взятьКарточку(Math.floor(Math.random() * ИГРА.карточки.length));
      if (ИГРА.экран === 'замена') S.заменитьСоюзника(0);
      if (ИГРА.экран !== 'бой') ИГРА.экран = 'бой';
    }
    if (ИГРА.экран !== 'бой') ИГРА.экран = 'бой';
  }

  const билд = Object.keys(и.апгрейды).map(к => к + ' ' + и.апгрейды[к]).join(', ');
  const уровень = ИГРА.уровень;

  /* Уже вызванного по расписанию босса убираем: мерим ровно одного и с нуля,
     иначе на шестой минуте в замер попадает недобитая ТОЛПА. */
  for (const в of ИГРА.враги.slice()) if (в.шаблон.уникальный) в.hp = 0;
  ИГРА.босс = null;

  S.вызватьБосса(имя, множитель);
  const босс = ИГРА.босс;
  if (!босс) return { ошибка: 'босс ' + имя + ' не вызвался' };
  const hp0 = босс.максHp;

  // --- замер: сколько живёт ---
  let секунд = 0, фаза2Через = null, атак = 0, попаданийВИгрока = 0;
  const hpИгрока = и.максHp;
  while (секунд < ПРЕДЕЛ && !босс.мёртв && ИГРА.враги.indexOf(босс) >= 0) {
    угол += 0.02;
    /* В бою с боссом игрок КРУЖИТ вокруг него, а не убегает по прямой.
       Первая версия замера гоняла игрока по кругу вне зависимости от босса,
       и медленный Шварц просто отставал на километры: замер показывал не
       время жизни босса, а скорость игрока. Держим дистанцию орбиты и
       обходим босса — так же, как это делает человек. */
    const орбита = 150;
    const кБоссу = Math.atan2(босс.y - и.y, босс.x - и.x);
    const дистБосс = дистанция(и.x, и.y, босс.x, босс.y);
    // тангенциально плюс поправка к нужному радиусу
    const направление = кБоссу + Math.PI / 2 + (дистБосс > орбита ? -0.7 : 0.7);
    жать(S, направление);
    /* Игрок бессмертен, но попадания считаем: босс, который за тридцать
       секунд не задел игрока ни разу, живёт долго не потому, что крепкий,
       а потому что беспомощный — это другой диагноз и другая правка. */
    if (и.hp < hpИгрока) { попаданийВИгрока++; и.hp = hpИгрока; }
    и.неуязвим = 999;
    const телеграфовДо = ИГРА.телеграфы.length;
    S.шагЛогики(ШАГ);
    if (ИГРА.телеграфы.length > телеграфовДо) атак++;
    if (босс.фаза2 && фаза2Через === null) фаза2Через = секунд;
    if (ИГРА.экран === 'левелап' && ИГРА.карточки.length) {
      S.взятьКарточку(Math.floor(Math.random() * ИГРА.карточки.length));
      if (ИГРА.экран === 'замена') S.заменитьСоюзника(0);
    }
    if (ИГРА.экран !== 'бой') ИГРА.экран = 'бой';
    секунд += ШАГ;
  }

  return {
    секунд: Math.round(секунд * 10) / 10,
    убит: босс.мёртв || ИГРА.враги.indexOf(босс) < 0,
    hp: Math.round(hp0),
    дпс: Math.round(hp0 / Math.max(секунд, 0.1)),
    фаза2Через: фаза2Через === null ? null : Math.round(фаза2Через * 10) / 10,
    атак, попаданийВИгрока, уровень, билд
  };
}

const { S } = поднять({ адресРейтинга: '' });
const план = расписание(S);
const только = process.argv.slice(2);

console.log('Замер боссов: ' + ПРОГОНОВ + ' прогонов на каждого.');
console.log('Ориентир: 20-35 секунд жизни при среднем билде своей минуты.\n');

for (const п of план) {
  if (только.length && !только.includes(п.имя)) continue;
  const метка = п.имя + ' на ' + Math.floor(п.t / 60) + ':' +
                String(п.t % 60).padStart(2, '0') +
                (п.множитель ? ' (hp x' + п.множитель + ')' : '');
  console.log('=== ' + метка);
  const времена = [];
  for (let n = 0; n < ПРОГОНОВ; n++) {
    const р = прогон(п.имя, п.t, п.множитель);
    if (р.ошибка) { console.log('  ' + р.ошибка); break; }
    времена.push(р.секунд);
    console.log('  ' + String(р.секунд).padStart(5) + ' сек   ' +
                (р.убит ? 'убит  ' : 'НЕ УБИТ') +
                '  hp ' + р.hp + '  урон/сек ' + р.дпс +
                '  фаза2 через ' + (р.фаза2Через === null ? '—' : р.фаза2Через + ' сек') +
                '  атак ' + р.атак + '  попал в игрока ' + р.попаданийВИгрока +
                '  ур ' + р.уровень);
  }
  if (времена.length) {
    const с = времена.slice().sort((a, b) => a - b);
    const мед = с[Math.floor(с.length / 2)];
    const вердикт = мед < 20 ? 'КОРОТКО, поднять hp'
                  : мед > 35 ? 'ДОЛГО, снизить hp'
                  : 'в норме';
    console.log('  медиана ' + мед + ' сек, разброс ' + с[0] + '-' + с[с.length - 1] +
                ' -> ' + вердикт + '\n');
  }
}
