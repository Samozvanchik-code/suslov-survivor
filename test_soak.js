/* Headless-прогон забега без браузера.
   Подменяем канвас и DOM заглушками, грузим боевые файлы как есть и крутим
   игровой шаг вручную. Ловим исключения и проверяем, что новая механика
   действительно срабатывает, а не просто компилируется.
   Запуск: node test_soak.js */

const { поднять } = require('./test_env.js');
const { песочница, S, ИГРА } = поднять();

const ШАГ = 1 / 60;
const МИНУТ = 8;
const кадров = Math.round(МИНУТ * 60 * 60);

S.начатьЗабег();
const и = ИГРА.игрок;

const ст = {
  выложено: 0, белуг: 0, черепов: 0, максНаКарте: 0,
  максHp: и.максHp, левелапов: 0, ошибок: 0, перваяОшибка: null,
  первыйЛут: null, взятыеКарты: {}, перезапусков: 0
};

/* Функции объявлены через const, обернуть их снаружи нельзя, поэтому
   считаем по наблюдаемым эффектам: появлению и исчезновению предметов. */
let подобрано = 0, истекло = 0;
let угол = 0;

for (let к = 0; к < кадров; к++) {
  угол += 0.02;
  const до = ИГРА.предметы.length;
  const доБлижний = ИГРА.предметы.map(п => ({
    вид: п.вид,
    близко: Math.hypot(п.x - и.x, п.y - (и.y - и.в * 0.4)) < 52
  }));
  try {
    и.hp = и.максHp;                      // бессмертный: нам нужны 8 минут волн
    и.неуязвим = 999;                     // иначе босс убивает и забег стартует заново
    // бежим по кругу, имитируя WASD
    S.клавиши.KeyW = Math.sin(угол) < -0.3;
    S.клавиши.KeyS = Math.sin(угол) > 0.3;
    S.клавиши.KeyA = Math.cos(угол) < -0.3;
    S.клавиши.KeyD = Math.cos(угол) > 0.3;

    S.шагЛогики(ШАГ);

    if (ИГРА.экран === 'левелап' && ИГРА.карточки.length) {
      ст.левелапов++;
      const и2 = Math.floor(Math.random() * ИГРА.карточки.length);
      const имя = ИГРА.карточки[и2].апгрейд.имя;
      ст.взятыеКарты[имя] = (ст.взятыеКарты[имя] || 0) + 1;
      S.взятьКарточку(и2);
      if (ИГРА.экран === 'замена') S.заменитьСоюзника(0);
      if (ИГРА.экран !== 'бой') ИГРА.экран = 'бой';
    }
    if (ИГРА.экран === 'итоги' || ИГРА.экран === 'смерть') { ст.перезапусков++; S.начатьЗабег(); }

    S.нарисоватьМир();
    S.нарисоватьИнтерфейс();
  } catch (e) {
    ст.ошибок++;
    if (!ст.перваяОшибка) {
      ст.перваяОшибка = 'кадр ' + к + ' (' + Math.round(ИГРА.время) + ' сек): ' + e.message +
                        '\n  ' + (e.stack || '').split('\n').slice(1, 3).join('\n  ');
    }
    if (ст.ошибок > 3) break;
  }

  const после = ИГРА.предметы.length;
  if (после > до) {
    ст.выложено += после - до;
    if (ст.первыйЛут === null) ст.первыйЛут = Math.round(ИГРА.время);
  }
  if (после < до) {
    for (const п of доБлижний) {
      if (п.близко) { подобрано++; if (п.вид === 'beluga') ст.белуг++; else ст.черепов++; }
    }
    if (подобрано === 0) истекло += до - после;
  }
  ст.максНаКарте = Math.max(ст.максНаКарте, после);
  ст.максHp = Math.max(ст.максHp, и.максHp);
}

const ок = (у) => у ? 'ОК  ' : 'ПЛОХО';
console.log('=== ПРОГОН ' + МИНУТ + ' МИНУТ (' + кадров + ' кадров) ===');
console.log(ок(ст.ошибок === 0) + ' ошибок за прогон:      ' + ст.ошибок);
if (ст.перваяОшибка) console.log('    первая: ' + ст.перваяОшибка);
console.log(ок(ст.первыйЛут !== null && ст.первыйЛут <= 32) +
            ' первый лут на секунде: ' + ст.первыйЛут + ' (ждём ~30)');
console.log(ок(ст.выложено >= 5) + ' предметов выложено:   ' + ст.выложено +
            ' (лимит 3 на карте тормозит выкладку, если лут не подбирают)');
/* Лимит держит только выкладка по таймеру. Череп с босса падает всегда:
   он заработан боем, и молча съесть его из-за лимита нельзя. Поэтому
   допустимо ровно на один больше. */
console.log(ок(ст.максНаКарте <= S.ЛУТ.максНаКарте + 1) +
            ' максимум на карте:    ' + ст.максНаКарте +
            ' (выкладка ' + S.ЛУТ.максНаКарте + ' + череп с босса сверх лимита)');
console.log('     подобрано белуг:      ' + ст.белуг);
console.log('     подобрано черепов:    ' + ст.черепов);
console.log(ок(ст.максHp >= 3) + ' максHp вырос до:      ' + ст.максHp + ' (старт 3)');
console.log('     уровень к концу:      ' + ИГРА.уровень + ', левелапов ' + ст.левелапов);
console.log(ок(ст.перезапусков === 0) + ' перезапусков забега:  ' + ст.перезапусков);
console.log('     убито анонов:         ' + ИГРА.убито);
console.log('     время в конце:        ' + Math.round(ИГРА.время) + ' сек');
console.log('     отряд:                ' +
  (ИГРА.союзники.map(с => с.ключ + ' r=' + с.конфиг.орбита + ' угол=' +
    (с.уголОрбиты % 6.283).toFixed(2)).join(' | ') || 'пусто'));
console.log('     карты за прогон:      ' + Object.keys(ст.взятыеКарты).join(', '));
/* ==========================================================================
   ВТОРОЙ СЦЕНАРИЙ: ТРУС

   Первый прогон гоняет игрока по кругу — он всё время убивает, и толпа
   не набирается. Этот сценарий делает наоборот: игрок бежит без остановки
   и НЕ БЕРЁТ КАРТ. Толпа копится за спиной, каминг-ауты детонируют
   цепочкой, и врагов гибнет пачками за один кадр.

   Именно так нашлось падение обновитьВрагов: массив врагов укорачивался
   внутри цикла обхода, и обход с конца читал за границу. Круговой прогон
   этого не давал ни разу за восемь минут. Настоящие игроки убегают
   постоянно — сценарий обязателен.
   ========================================================================== */
const { поднять: поднять2 } = require('./test_env.js');
const вт = поднять2({ адресРейтинга: '' });
const S2 = вт.S, ИГРА2 = вт.ИГРА;

S2.начатьЗабег();
const и2 = ИГРА2.игрок;
let ошибокТруса = 0, перваяОшибкаТруса = null, курс = 0, отказовОтКарт = 0;

for (let к = 0; к < кадров; к++) {
  try {
    и2.hp = и2.максHp; и2.неуязвим = 999;
    // курс меняется раз в пять секунд: максимальный отрыв от толпы
    if (к % 300 === 0) курс = Math.random() * Math.PI * 2;
    S2.клавиши.KeyW = Math.sin(курс) < -0.35;
    S2.клавиши.KeyS = Math.sin(курс) > 0.35;
    S2.клавиши.KeyA = Math.cos(курс) < -0.35;
    S2.клавиши.KeyD = Math.cos(курс) > 0.35;

    S2.шагЛогики(ШАГ);
    /* Карт не берём намеренно: у труса нет билда, и толпа не редеет.
       Экран левелапа просто закрываем. */
    if (ИГРА2.экран === 'левелап') { отказовОтКарт++; ИГРА2.экран = 'бой'; }
    if (ИГРА2.экран !== 'бой') ИГРА2.экран = 'бой';

    S2.нарисоватьМир();
    S2.нарисоватьИнтерфейс();
  } catch (e) {
    ошибокТруса++;
    if (!перваяОшибкаТруса) {
      перваяОшибкаТруса = 'кадр ' + к + ' (' + Math.round(ИГРА2.время) + ' сек): ' + e.message +
                          '\n  ' + (e.stack || '').split('\n').slice(1, 3).join('\n  ');
    }
    if (ошибокТруса > 3) break;
  }
}

console.log('\n=== ПРОГОН ТРУСА: БЕЖИТ, КАРТ НЕ БЕРЁТ ===');
console.log(ок(ошибокТруса === 0) + ' ошибок за прогон:      ' + ошибокТруса);
if (перваяОшибкаТруса) console.log('    первая: ' + перваяОшибкаТруса);
console.log('     врагов на экране:     ' + ИГРА2.враги.length + ' (потолок ' + S2.БАЛАНС.потолокВрагов + ')');
console.log('     отказов от карточки:  ' + отказовОтКарт);
/* Даже без единой карты гантеля бьёт сама, и толпа набегает на неё. Это
   число — основание нижней границы правдоподобия в воркере: отсидеться
   без убийств в игре нельзя. */
console.log(ок(ИГРА2.убито > 1500) + ' убито без билда:      ' + ИГРА2.убито +
            ' (в воркере порог 0.5 в секунду, замер даёт около 4)');
console.log('     время в конце:        ' + Math.round(ИГРА2.время) + ' сек');

/* ==========================================================================
   ТРЕТИЙ СЦЕНАРИЙ: ФИНАЛ И ДОПОЛНИТЕЛЬНОЕ ВРЕМЯ

   Первые два сценария заканчиваются на восьмой минуте и финала не видят
   вообще. А в финале сходится всё сразу: ДВОЙНИК с копией билда, выводок
   ДЕЛИТЕЛЯ-ПАПЫ, боссы цикла поверх живого финалиста и остановленные часы.
   Это самое плотное место в игре по числу объектов на кадр, и проверять
   его надо именно прогоном, а не точечным тестом.

   Игрок бессмертен, а двойнику на время прогона раздувается hp: нам нужно
   удержать финал ОТКРЫТЫМ и просидеть в нём два цикла боссов. Одного
   ослабленного урона для этого не хватило — в первой версии сценария игрок
   всё равно добивал двойника, забег закрывался победой, и цикл боссов
   вставал на первом же круге. Проверка «боссов цикла позвано» это и
   поймала.
   ========================================================================== */
const тр = require('./test_env.js').поднять({ адресРейтинга: '' });
const S3 = тр.S, ИГРА3 = тр.ИГРА;

S3.начатьЗабег();
const и3 = ИГРА3.игрок;
// стартуем сразу перед девятой минутой: до неё волны уже проверены дважды
ИГРА3.время = 530;
и3.множительУрона = 0.02;             // финал должен продержаться, а не схлопнуться

let ошибокФинала = 0, перваяОшибкаФинала = null, курс3 = 0;
let максВрагов = 0, максДелителей = 0, максТелеграфов = 0, максСнарядов = 0;
const боссыФинала = new Set();
const кадровФинала = Math.round((70 + S3.ФИНАЛ.интервалЦикла * 2) * 60);

for (let к = 0; к < кадровФинала; к++) {
  try {
    и3.hp = и3.максHp; и3.неуязвим = 999;
    if (к % 240 === 0) курс3 = Math.random() * Math.PI * 2;
    S3.клавиши.KeyW = Math.sin(курс3) < -0.35;
    S3.клавиши.KeyS = Math.sin(курс3) > 0.35;
    S3.клавиши.KeyA = Math.cos(курс3) < -0.35;
    S3.клавиши.KeyD = Math.cos(курс3) > 0.35;

    S3.шагЛогики(ШАГ);
    if (ИГРА3.экран === 'левелап' && ИГРА3.карточки.length) {
      S3.взятьКарточку(Math.floor(Math.random() * ИГРА3.карточки.length));
      if (ИГРА3.экран === 'замена') S3.заменитьСоюзника(0);
    }
    if (ИГРА3.экран !== 'бой') ИГРА3.экран = 'бой';

    S3.нарисоватьМир();
    S3.нарисоватьИнтерфейс();

    /* Раздуваем hp финалиста один раз, как только он вышел: иначе бой
       кончается победой раньше, чем приходит второй босс цикла. */
    for (const в of ИГРА3.враги) {
      if (в.шаблон.уникальный) боссыФинала.add(в.тип);
      if (в.шаблон.финал && !в._раздут) {
        в._раздут = true; в.максHp *= 20; в.hp = в.максHp;
      }
    }
    максВрагов = Math.max(максВрагов, ИГРА3.враги.length);
    // считаем именно РОЖДЁННЫХ: рядовые делители идут ещё и из волн
    максДелителей = Math.max(максДелителей,
      ИГРА3.враги.filter(в => в.родитель).length);
    максТелеграфов = Math.max(максТелеграфов, ИГРА3.телеграфы.length);
    максСнарядов = Math.max(максСнарядов, ИГРА3.снаряды.length);
  } catch (e) {
    ошибокФинала++;
    if (!перваяОшибкаФинала) {
      перваяОшибкаФинала = 'кадр ' + к + ' (' + Math.round(ИГРА3.время) + ' сек, доп ' +
                           Math.round(ИГРА3.дополнительное) + '): ' + e.message +
                           '\n  ' + (e.stack || '').split('\n').slice(1, 3).join('\n  ');
    }
    if (ошибокФинала > 3) break;
  }
}

console.log('\n=== ПРОГОН ФИНАЛА: ДВОЙНИК И ДОПОЛНИТЕЛЬНОЕ ВРЕМЯ ===');
console.log(ок(ошибокФинала === 0) + ' ошибок за прогон:      ' + ошибокФинала);
if (перваяОшибкаФинала) console.log('    первая: ' + перваяОшибкаФинала);
console.log(ок(ИГРА3.время === S3.БАЛАНС.длинаЗабега) +
            ' часы встали на:       ' + ИГРА3.время + ' сек');
console.log(ок(ИГРА3.дополнительное > S3.ФИНАЛ.интервалЦикла * 2) +
            ' дополнительное:       ' + Math.round(ИГРА3.дополнительное) + ' сек');
console.log(ок(боссыФинала.has('ДЕЛИТЕЛЬ-ПАПА') && боссыФинала.has('ДВОЙНИК')) +
            ' боссы за прогон:      ' + [...боссыФинала].join(', '));
console.log(ок(ИГРА3.боссовЦикла >= 2) + ' боссов цикла позвано: ' + ИГРА3.боссовЦикла);
console.log(ок(максДелителей <= S3.РОДЫ.максВыводка + S3.ДЕЛИТЕЛЬ.сколько * 2) +
            ' рождённых на экране:  ' + максДелителей + ' (потолок выводка ' +
            S3.РОДЫ.максВыводка + ' плюс прощальная пачка)');
/* Потолок технический, и через него намеренно проходят двое: сами БОССЫ
   (в финале уникальных на поле до пяти сразу) и ГАРНИЗОН двойника. Обоих
   вытеснять нельзя — это содержание момента, а не поток мяса, поэтому
   найтиЖертву их и пропускает. Допуск считаем ровно по ним, а не «примерно». */
const допускНевытесняемых = 5 + S3.ДВОЙНИК_КОПИЯ.максСвиты;
console.log(ок(максВрагов <= S3.БАЛАНС.потолокВрагов + допускНевытесняемых) +
            ' врагов на экране:     ' + максВрагов + ' (потолок ' +
            S3.БАЛАНС.потолокВрагов + ' плюс до ' + допускНевытесняемых +
            ' невытесняемых: боссы и гарнизон)');
console.log('     телеграфов зараз:     ' + максТелеграфов);
console.log('     снарядов зараз:       ' + максСнарядов);
console.log('     уровень к концу:      ' + ИГРА3.уровень);
console.log(ок(ИГРА3.победа === false) +
            ' финал не закрылся:    победа ' + ИГРА3.победа);

process.exit((ст.ошибок || ошибокТруса || ошибокФинала) ? 1 : 0);
