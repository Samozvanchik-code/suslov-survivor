/* Headless-прогон забега без браузера.
   Подменяем канвас и DOM заглушками, грузим боевые файлы как есть и крутим
   игровой шаг вручную. Ловим исключения и проверяем, что новая механика
   действительно срабатывает, а не просто компилируется.
   Запуск: node test_soak.js */

const { поднять } = require('./test_env.js');
const { песочница, S, ИГРА } = поднять();

const ШАГ = 1 / 60;
const МИНУТ = 8;
const кадров = Math.round(МИНУТ * 60 * 60);

S.начатьЗабег();
const и = ИГРА.игрок;

const ст = {
  выложено: 0, белуг: 0, черепов: 0, максНаКарте: 0,
  максHp: и.максHp, левелапов: 0, ошибок: 0, перваяОшибка: null,
  первыйЛут: null, взятыеКарты: {}, перезапусков: 0
};

/* Функции объявлены через const, обернуть их снаружи нельзя, поэтому
   считаем по наблюдаемым эффектам: появлению и исчезновению предметов. */
let подобрано = 0, истекло = 0;
let угол = 0;

for (let к = 0; к < кадров; к++) {
  угол += 0.02;
  const до = ИГРА.предметы.length;
  const доБлижний = ИГРА.предметы.map(п => ({
    вид: п.вид,
    близко: Math.hypot(п.x - и.x, п.y - (и.y - и.в * 0.4)) < 52
  }));
  try {
    и.hp = и.максHp;                      // бессмертный: нам нужны 8 минут волн
    и.неуязвим = 999;                     // иначе босс убивает и забег стартует заново
    // бежим по кругу, имитируя WASD
    S.клавиши.KeyW = Math.sin(угол) < -0.3;
    S.клавиши.KeyS = Math.sin(угол) > 0.3;
    S.клавиши.KeyA = Math.cos(угол) < -0.3;
    S.клавиши.KeyD = Math.cos(угол) > 0.3;

    S.шагЛогики(ШАГ);

    if (ИГРА.экран === 'левелап' && ИГРА.карточки.length) {
      ст.левелапов++;
      const и2 = Math.floor(Math.random() * ИГРА.карточки.length);
      const имя = ИГРА.карточки[и2].апгрейд.имя;
      ст.взятыеКарты[имя] = (ст.взятыеКарты[имя] || 0) + 1;
      S.взятьКарточку(и2);
      if (ИГРА.экран === 'замена') S.заменитьСоюзника(0);
      if (ИГРА.экран !== 'бой') ИГРА.экран = 'бой';
    }
    if (ИГРА.экран === 'итоги' || ИГРА.экран === 'смерть') { ст.перезапусков++; S.начатьЗабег(); }

    S.нарисоватьМир();
    S.нарисоватьИнтерфейс();
  } catch (e) {
    ст.ошибок++;
    if (!ст.перваяОшибка) {
      ст.перваяОшибка = 'кадр ' + к + ' (' + Math.round(ИГРА.время) + ' сек): ' + e.message +
                        '\n  ' + (e.stack || '').split('\n').slice(1, 3).join('\n  ');
    }
    if (ст.ошибок > 3) break;
  }

  const после = ИГРА.предметы.length;
  if (после > до) {
    ст.выложено += после - до;
    if (ст.первыйЛут === null) ст.первыйЛут = Math.round(ИГРА.время);
  }
  if (после < до) {
    for (const п of доБлижний) {
      if (п.близко) { подобрано++; if (п.вид === 'beluga') ст.белуг++; else ст.черепов++; }
    }
    if (подобрано === 0) истекло += до - после;
  }
  ст.максНаКарте = Math.max(ст.максНаКарте, после);
  ст.максHp = Math.max(ст.максHp, и.максHp);
}

const ок = (у) => у ? 'ОК  ' : 'ПЛОХО';
console.log('=== ПРОГОН ' + МИНУТ + ' МИНУТ (' + кадров + ' кадров) ===');
console.log(ок(ст.ошибок === 0) + ' ошибок за прогон:      ' + ст.ошибок);
if (ст.перваяОшибка) console.log('    первая: ' + ст.перваяОшибка);
console.log(ок(ст.первыйЛут !== null && ст.первыйЛут <= 32) +
            ' первый лут на секунде: ' + ст.первыйЛут + ' (ждём ~30)');
console.log(ок(ст.выложено >= 5) + ' предметов выложено:   ' + ст.выложено +
            ' (лимит 3 на карте тормозит выкладку, если лут не подбирают)');
/* Лимит держит только выкладка по таймеру. Череп с босса падает всегда:
   он заработан боем, и молча съесть его из-за лимита нельзя. Поэтому
   допустимо ровно на один больше. */
console.log(ок(ст.максНаКарте <= S.ЛУТ.максНаКарте + 1) +
            ' максимум на карте:    ' + ст.максНаКарте +
            ' (выкладка ' + S.ЛУТ.максНаКарте + ' + череп с босса сверх лимита)');
console.log('     подобрано белуг:      ' + ст.белуг);
console.log('     подобрано черепов:    ' + ст.черепов);
console.log(ок(ст.максHp >= 3) + ' максHp вырос до:      ' + ст.максHp + ' (старт 3)');
console.log('     уровень к концу:      ' + ИГРА.уровень + ', левелапов ' + ст.левелапов);
console.log(ок(ст.перезапусков === 0) + ' перезапусков забега:  ' + ст.перезапусков);
console.log('     убито анонов:         ' + ИГРА.убито);
console.log('     время в конце:        ' + Math.round(ИГРА.время) + ' сек');
console.log('     отряд:                ' +
  (ИГРА.союзники.map(с => с.ключ + ' r=' + с.конфиг.орбита + ' угол=' +
    (с.уголОрбиты % 6.283).toFixed(2)).join(' | ') || 'пусто'));
console.log('     карты за прогон:      ' + Object.keys(ст.взятыеКарты).join(', '));
process.exit(ст.ошибок ? 1 : 0);
