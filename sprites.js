/* ==========================================================================
   БЛОК 2. ЗАГРУЗКА СПРАЙТОВ
   ========================================================================== */

const СПРАЙТ = {};                 // ключ -> { картинка, ш, в }
let загружено = 0, всегоЗагрузить = 0, ошибкиЗагрузки = [];

function загрузитьСпрайты(готово) {
  const ключи = Object.keys(МАНИФЕСТ);
  всегоЗагрузить = ключи.length;
  if (всегоЗагрузить === 0) { готово(); return; }

  for (const ключ of ключи) {
    const запись = МАНИФЕСТ[ключ];
    const карт = new Image();
    СПРАЙТ[ключ] = { картинка: карт, ш: запись.ш, в: запись.в, готов: false };
    карт.onload = () => {
      СПРАЙТ[ключ].готов = true;
      // Реальные размеры важнее записанных в манифесте.
      СПРАЙТ[ключ].ш = карт.naturalWidth  || запись.ш;
      СПРАЙТ[ключ].в = карт.naturalHeight || запись.в;
      if (++загружено >= всегоЗагрузить) готово();
    };
    карт.onerror = () => {
      /* НЕОБЯЗАТЕЛЬНЫЕ спрайты (скины) в список ошибок не идут. Порядок
         выкладки в этом проекте жёсткий: сначала PNG кладутся руками в
         репозиторий, и только потом заливается код, — потому что бинарники
         через гитхаб-интеграцию не проходят. Но скины по своей природе
         опциональны: пока файла нет, скин просто недоступен (скинГотов вернёт
         false, колесо его не выдаст, в шкафу он будет «скоро»). Считать это
         поломкой и пугать игрока плашкой «не нашлись спрайты» — неверно. */
      if (!запись.необязательный) ошибкиЗагрузки.push(запись.файл);
      if (++загружено >= всегоЗагрузить) готово();
    };
    карт.src = запись.файл;
  }
}


/* ==========================================================================
   БЛОК 7. ОТРИСОВКА СПРАЙТА С ПРОЦЕДУРНОЙ АНИМАЦИЕЙ
   Отдельных кадров ходьбы нет. Живость даётся математикой поверх
   одного спрайта: подпрыгивание, наклон, squash/stretch, дыхание.
   ========================================================================== */

// Размер спрайта на экране в мировых единицах.
function габариты(ключ, масштаб = 1, ширинаX = 1) {
  return симуляция.legacy.габариты(ключ, масштаб, ширинаX);
}

/* Спрайты в исходниках нарочно крупные, а на экране мелкие. Пересэмплировать
   176-пиксельный PNG под 97 пикселей каждый кадр для каждого из 250 врагов —
   это весь бюджет кадра. Поэтому масштабируем один раз и складываем в кэш,
   дальше идёт дешёвый блит один-к-одному.
   Заодно печём цветные силуэты: вспышку урона нельзя рисовать через
   source-atop по непрозрачному полу — зальётся весь прямоугольник, а не фигура. */
const кэшСпрайтов = new Map();

function готовыйСпрайт(ключ, масштаб, ширинаX, цвет) {
  const с = СПРАЙТ[ключ];
  if (!с || !с.готов) return null;
  const идент = ключ + '|' + масштаб.toFixed(2) + '|' + ширинаX.toFixed(2) + '|' + (цвет || '');
  let запись = кэшСпрайтов.get(идент);
  if (запись) return запись;

  const ш = Math.max(1, Math.round(с.ш * МАСШТАБ_МИРА * масштаб * ширинаX));
  const в = Math.max(1, Math.round(с.в * МАСШТАБ_МИРА * масштаб));
  const холст = document.createElement('canvas');
  холст.width = ш; холст.height = в;
  const к = холст.getContext('2d');
  к.imageSmoothingEnabled = true;
  к.imageSmoothingQuality = 'high';
  к.drawImage(с.картинка, 0, 0, ш, в);
  if (цвет) {                        // здесь альфа только у самой фигуры — силуэт выйдет чистым
    к.globalCompositeOperation = 'source-atop';
    к.fillStyle = цвет;
    к.fillRect(0, 0, ш, в);
  }
  запись = { холст, ш, в };
  кэшСпрайтов.set(идент, запись);
  return запись;
}

/* Наклон и сжатие — это поворот со скейлом, то есть пересэмплирование спрайта
   на каждом кадре для каждого врага. Анимация периодическая, поэтому печём
   восемь фаз в готовые позы и дальше кладём их обычным блитом без трансформа.
   Картинка получается ровно та же, только считается один раз.
   поза = -1 — стойка без наклона и сжатия. */
const ПОЗ = 8;
const кэшПоз = new Map();

/* В канвас позы запекаем СРАЗУ И ТЕНЬ, и подпрыгивание. Подпрыг зависит только
   от фазы, то есть от номера позы, — значит и ширина тени тоже. Поэтому враг
   рисуется одним drawImage один-к-одному: ни масштабирования, ни поворота,
   ни отдельного вызова под тень. Зеркальная сторона — отдельная копия. */
function готоваяПоза(ключ, масштаб, ширинаX, сторона, поза, цвет) {
  const с = СПРАЙТ[ключ];
  if (!с || !с.готов) return null;
  const идент = ключ + '|' + масштаб.toFixed(2) + '|' + ширинаX.toFixed(2) +
                '|' + сторона + '|' + поза + '|' + (цвет || '');
  let з = кэшПоз.get(идент);
  if (з) return з;

  const ш = Math.max(1, Math.round(с.ш * МАСШТАБ_МИРА * масштаб * ширинаX));
  const в = Math.max(1, Math.round(с.в * МАСШТАБ_МИРА * масштаб));

  const фаза   = (поза / ПОЗ) * Math.PI * 2;
  const наклон = поза < 0 ? 0 : Math.sin(фаза) * 0.05;
  const сжатие = поза < 0 ? 1 : 1 + Math.sin(фаза * 2) * 0.03;
  const подпрыг = поза < 0 ? 0 : Math.abs(Math.sin(фаза)) * 3 * масштаб;
  // тень пульсирует в противофазе с подпрыгиванием
  const шТени = Math.max(4, ш * 0.6 * (1 - Math.abs(поза < 0 ? 0 : Math.sin(фаза)) / 6));
  const вТени = шТени * 0.4;

  const полеX    = Math.ceil(в * 0.09) + 3;                 // запас под наклон
  const полеВерх = полеX + Math.ceil(подпрыг) + 2;
  const полеНиз  = Math.ceil(вТени / 2) + 2;

  const холст = document.createElement('canvas');
  холст.width  = ш + полеX * 2;
  холст.height = в + полеВерх + полеНиз;
  const к = холст.getContext('2d');
  к.imageSmoothingEnabled = true;
  к.imageSmoothingQuality = 'high';

  const якорьX = ш / 2 + полеX;
  const якорьY = в + полеВерх;
  к.translate(якорьX, якорьY);

  if (!цвет) {                       // тень только в базовой позе, не в силуэте
    к.globalAlpha = 0.32;
    к.fillStyle = '#000000';
    к.beginPath();
    к.ellipse(0, 0, шТени / 2, вТени / 2, 0, 0, Math.PI * 2);
    к.fill();
    к.globalAlpha = 1;
  }

  к.translate(0, -подпрыг);
  к.rotate(наклон * (сторона === -1 ? -1 : 1));
  к.scale(сторона === -1 ? -1 : 1, сжатие);
  к.drawImage(с.картинка, -ш / 2, -в, ш, в);
  if (цвет) {
    к.globalCompositeOperation = 'source-atop';
    к.fillStyle = цвет;
    к.fillRect(-ш * 2, -в * 2, ш * 4, в * 4);
  }

  з = { холст, якорьX, якорьY };
  кэшПоз.set(идент, з);
  return з;
}

/* Таблица поз: два массива готовых канвасов, вправо и влево.
   Индексы 0..ПОЗ-1 — фазы ходьбы, индекс ПОЗ — стойка.
   Нужна, чтобы в бою доставать позу прямым индексом массива. Сборка ключа
   строкой с toFixed на каждого из трёхсот врагов каждый кадр стоила дороже,
   чем сама отрисовка. */
function построитьТаблицу(ключ, масштаб, ширинаX, цвет) {
  const прав = [], лев = [];
  for (let п = 0; п < ПОЗ; п++) {
    прав.push(готоваяПоза(ключ, масштаб, ширинаX, 1, п, цвет));
    лев.push(готоваяПоза(ключ, масштаб, ширинаX, -1, п, цвет));
  }
  прав.push(готоваяПоза(ключ, масштаб, ширинаX, 1, -1, цвет));
  лев.push(готоваяПоза(ключ, масштаб, ширинаX, -1, -1, цвет));
  return { прав, лев };
}

/* Прогрев на загрузке. Иначе первые секунды забега подтормаживают:
   каждая новая пара «спрайт + поза» печётся прямо в кадре. */
const позыВрагов = new WeakMap();
function прогретьПозы() {
  for (const ид in ВРАГИ) {
    const ш = ВРАГИ[ид];
    if (ш.уникальный) continue;        // боссы рисуются масштабированием, им предрендер не нужен
    const позы = {};
    позы._база  = построитьТаблицу(ш.спрайт, ш.масштаб, ш.ширинаX, null);
    позы._белые = построитьТаблицу(ш.спрайт, ш.масштаб, ш.ширинаX, '#ffffff');
    позы._оттенок = ш.примета === 'пульсация'
      ? построитьТаблицу(ш.спрайт, ш.масштаб, ш.ширинаX, '#ff4040')
      : null;
    позыВрагов.set(ш, позы);
  }
  /* Позы печём и для базового Ильи, и для НАДЕТОГО скина: без этого первый
     кадр после смены скина считает восемь поз прямо в бою. */
  построитьТаблицу('ilya_idle', 1, 1, null);
  построитьТаблицу('ilya_idle', 1, 1, '#ffffff');
  const скинИгрока = (typeof спрайтИгрока === 'function') ? спрайтИгрока() : 'ilya_idle';
  if (скинИгрока !== 'ilya_idle' && СПРАЙТ[скинИгрока] && СПРАЙТ[скинИгрока].готов) {
    построитьТаблицу(скинИгрока, 1, 1, null);
    построитьТаблицу(скинИгрока, 1, 1, '#ffffff');
  }
  построитьТаблицу('shvarts', 1, 1, null);
  построитьТаблицу('shvarts', 1, 1, '#ffffff');
  for (const к of ['pet_tarakan', 'pet_tarakanische', 'pet_schenok',
                   'ally_leva2k', 'ally_d1pro4', 'ally_jaguarn1',
                   'ally_bondarenk01', 'ally_zzord']) {
    построитьТаблицу(к, 1, 1, null);
  }
  готовыйСпрайт('item_cherep', 1, 1, null);
  готовыйСпрайт('item_beluga', 1, 1, null);
  готовыйСпрайт('obj_kletka', 1.7, 1, null);
  готовыйСпрайт('item_xp', 1, 1, null);
  готовыйСпрайт('weapon_gantelya', 1, 1, null);
  if (typeof спрайтОружия === 'function') готовыйСпрайт(спрайтОружия(), 1, 1, null);
  готовыйСпрайт('anon', 0.5, 1, null);      // куски ТОЛПЫ в полёте
  готовыйКристалл();
}

/* x, y — точка НОГ в мировых координатах (низ спрайта).
   о.фаза — счётчик шагов, о.идёт, о.сторона, о.вспышка, о.масштаб, о.ширинаX,
   о.оттенок — цвет наложения, о.альфа. */
const ДВА_ПИ = Math.PI * 2;

function drawSprite(ключ, x, y, о = {}) {
  const с = СПРАЙТ[ключ];
  const масштаб = о.масштаб || 1;
  const ширинаX = о.ширинаX || 1;

  if (!с || !с.готов) {          // спрайт не догрузился — рисуем заглушку, но играем дальше
    const г = габариты(ключ, масштаб, ширинаX);
    кт.fillStyle = '#7a7a8c';
    кт.fillRect(x - г.ш / 2, y - г.в, г.ш, г.в);
    return;
  }

  const фаза = о.фаза || 0;
  const идёт = !!о.идёт;
  const сторона = о.сторона === -1 ? -1 : 1;
  // подпрыгивание, наклон, сжатие и тень уже внутри канваса позы
  const позаИндекс = идёт
    ? Math.floor((((фаза % ДВА_ПИ) + ДВА_ПИ) % ДВА_ПИ) / ДВА_ПИ * ПОЗ) % ПОЗ
    : -1;
  const дыхание = идёт ? 0 : Math.sin(ИГРА.времяВсего * 2);   // только для стоящих

  const поза = готоваяПоза(ключ, масштаб, ширинаX, сторона, позаИндекс, null);
  if (!поза) return;

  const пx = (x - поза.якорьX) | 0;
  const пy = (y + дыхание - поза.якорьY) | 0;

  // Без save/restore: на 300 врагов это 600 лишних операций со стеком состояния.
  const альфа = о.альфа !== undefined ? о.альфа : 1;
  if (альфа !== 1) кт.globalAlpha = альфа;
  кт.drawImage(поза.холст, пx, пy);

  // Вспышка урона и оттенок — та же поза, только запечённая в цвет.
  if (о.вспышка > 0) {
    const силуэт = готоваяПоза(ключ, масштаб, ширинаX, сторона, позаИндекс, '#ffffff');
    if (силуэт) {
      кт.globalAlpha = зажать(о.вспышка * 8, 0, 0.85) * альфа;
      кт.drawImage(силуэт.холст, пx, пy);
      кт.globalAlpha = 1;
      return;
    }
  } else if (о.оттенок) {
    const силуэт = готоваяПоза(ключ, масштаб, ширинаX, сторона, позаИндекс, о.оттенок);
    if (силуэт) {
      кт.globalAlpha = (о.силаОттенка !== undefined ? о.силаОттенка : 0.4) * альфа;
      кт.drawImage(силуэт.холст, пx, пy);
      кт.globalAlpha = 1;
      return;
    }
  }
  if (альфа !== 1) кт.globalAlpha = 1;
}
