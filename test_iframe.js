/* Проверки встраивания игры в iframe на чужом сайте.
   Запуск: node test_iframe.js

   Здесь важно не «как выглядит», а два контракта, которые ломаются молча:
   полный экран (браузер разрешает его только из жеста, а на iPhone не даёт
   вообще) и фокус клавиатуры (без него стрелки скроллят чужую страницу).
*/

const { поднять } = require('./test_env.js');

let всего = 0, провалов = 0;
function проверка(имя, условие, факт) {
  всего++;
  if (условие) console.log('  ОК     ' + имя);
  else { провалов++; console.log('  ПРОВАЛ ' + имя + (факт !== undefined ? '  -> ' + факт : '')); }
}
const раздел = (и) => console.log('\n' + и);

раздел('1. ОПРЕДЕЛЕНИЕ ВСТРАИВАНИЯ');
let о = поднять({ адресРейтинга: '' });
проверка('отдельная страница не считается встроенной', о.S.ВСТРОЕНО === false, о.S.ВСТРОЕНО);
о = поднять({ адресРейтинга: '', встроено: true });
проверка('игра в рамке считается встроенной', о.S.ВСТРОЕНО === true, о.S.ВСТРОЕНО);

раздел('2. КНОПКА ПОЛНОГО ЭКРАНА');
о = поднять({ адресРейтинга: '' });
let кнопка = о.окно._элементы['fs'];
проверка('кнопка найдена в разметке', !!кнопка);
проверка('на кнопку повешен обработчик клика',
         кнопка._слушатели.click && кнопка._слушатели.click.length === 1,
         кнопка._слушатели.click && кнопка._слушатели.click.length);

о.ИГРА.экран = 'старт';  о.S.обновитьКнопкуФС();
проверка('в меню кнопка видна', кнопка.style.display === 'block', кнопка.style.display);
о.ИГРА.экран = 'итоги';  о.S.обновитьКнопкуФС();
проверка('на итогах кнопка видна', кнопка.style.display === 'block', кнопка.style.display);
о.ИГРА.экран = 'бой';    о.S.обновитьКнопкуФС();
/* В бою кнопки нет намеренно: на телефоне угол экрана это зона джойстика,
   а случайный выход в полный экран посреди забега хуже её отсутствия. */
проверка('в бою кнопка спрятана', кнопка.style.display === 'none', кнопка.style.display);
о.ИГРА.экран = 'левелап'; о.S.обновитьКнопкуФС();
проверка('на выборе карточки кнопки тоже нет', кнопка.style.display === 'none', кнопка.style.display);

раздел('3. ПЕРЕКЛЮЧЕНИЕ ПОЛНОГО ЭКРАНА');
о = поднять({ адресРейтинга: '', встроено: true });
кнопка = о.окно._элементы['fs'];
проверка('до нажатия мы не в полном экране', о.S.вПолномЭкране() === false);

// нажимаем ровно так, как это делает браузер: событием click по кнопке
let упал = null;
try { кнопка._событие('click'); } catch (e) { упал = e.message; }
проверка('клик по кнопке не падает', !упал, упал);
проверка('после клика игра в полном экране', о.S.вПолномЭкране() === true);
проверка('наверх ушло сообщение о полном экране',
         о.окно._сообщения.length === 1 &&
         о.окно._сообщения[0].type === 'suslov-fullscreen' &&
         о.окно._сообщения[0].on === true,
         JSON.stringify(о.окно._сообщения));

кнопка._событие('click');
проверка('повторный клик выходит из полного экрана', о.S.вПолномЭкране() === false);
проверка('наверх ушло сообщение о выходе',
         о.окно._сообщения.length === 2 && о.окно._сообщения[1].on === false,
         JSON.stringify(о.окно._сообщения));

раздел('4. IPHONE: ПОЛНОГО ЭКРАНА НЕТ, ОСТАЁТСЯ СООБЩЕНИЕ');
/* На iPhone Fullscreen API не работает ни для чего, кроме видео. Ловим это
   отсутствием метода, а не разбором userAgent: строка врёт и меняется. */
о = поднять({ адресРейтинга: '', встроено: true, безПолногоЭкрана: true });
кнопка = о.окно._элементы['fs'];
проверка('игра видит, что полный экран недоступен',
         о.S.полныйЭкранДоступен() === false);
упал = null;
try { кнопка._событие('click'); } catch (e) { упал = e.message; }
проверка('клик без поддержки не падает', !упал, упал);
проверка('вместо полного экрана ушло сообщение наверх',
         о.окно._сообщения.length === 1 && о.окно._сообщения[0].on === true,
         JSON.stringify(о.окно._сообщения));
о.ИГРА.экран = 'старт'; о.S.обновитьКнопкуФС();
проверка('во встроенной игре кнопка нужна и без API',
         кнопка.style.display === 'block', кнопка.style.display);

// отдельная страница без API: кнопка бесполезна, её незачем показывать
о = поднять({ адресРейтинга: '', безПолногоЭкрана: true });
о.ИГРА.экран = 'старт'; о.S.обновитьКнопкуФС();
проверка('на отдельной странице без API кнопка спрятана',
         о.окно._элементы['fs'].style.display === 'none',
         о.окно._элементы['fs'].style.display);

раздел('5. ЗУМ ПОСЛЕ СМЕНЫ РАЗМЕРА');
/* Главная ловушка: после входа в полный экран размеры экрана другие, а зум
   камеры выводится из них. Без пересчёта мир остаётся в масштабе маленькой
   рамки. */
о = поднять({ адресРейтинга: '', встроено: true });
о.окно.innerWidth = 480; о.окно.innerHeight = 320;
о.S.пересчитатьРазмер();
const зумВРамке = о.S.ЭКР.зум, шВРамке = о.S.ЭКР.ш;
о.окно.innerWidth = 1920; о.окно.innerHeight = 1080;
о.S.послеСменыЭкрана();
проверка('размеры экрана обновились', о.S.ЭКР.ш === 1920, шВРамке + ' -> ' + о.S.ЭКР.ш);
проверка('зум пересчитан под новый размер', о.S.ЭКР.зум !== зумВРамке,
         зумВРамке + ' -> ' + о.S.ЭКР.зум);
const обзор = о.S.обзорВокругИгрока();
проверка('обзор в полном экране не меньше требуемого',
         обзор.поГоризонтали >= о.S.ЗУМ.обзор && обзор.поВертикали >= о.S.ЗУМ.обзор,
         Math.round(обзор.поГоризонтали) + 'x' + Math.round(обзор.поВертикали));

раздел('6. ФОКУС КЛАВИАТУРЫ');
о = поднять({ адресРейтинга: '' });
const канвас = о.окно._элементы['экран'];
/* Фокус ставится в запустить(), а он висит на событии load: файлы
   подключены по порядку, но картинки грузятся асинхронно. Поэтому событие
   надо честно отправить, а не ждать, что оно случится само. */
о.окно._событие('load', {});
проверка('канвас получает фокус при загрузке', канвас._фокусов > 0, канвас._фокусов);

const былоФокусов = канвас._фокусов;
канвас._событие('mousedown', { preventDefault(){}, stopPropagation(){},
                               clientX: 10, clientY: 10 });
проверка('клик по канвасу возвращает фокус игре',
         канвас._фокусов > былоФокусов, канвас._фокусов);

// касание отдаём полноценным событием: игра на touchstart гасит скролл
канвас._событие('touchstart', {
  preventDefault(){},
  changedTouches: [{ clientX: 20, clientY: 20, identifier: 1 }],
  touches: [{ clientX: 20, clientY: 20, identifier: 1 }]
});
проверка('касание тоже возвращает фокус', канвас._фокусов > былоФокусов + 1, канвас._фокусов);

раздел('7. ПЛАШКА «КЛИКНИ, ЧТОБЫ ИГРАТЬ»');
о = поднять({ адресРейтинга: '', встроено: true, фокус: false });
проверка('встроенная игра без фокуса просит кликнуть',
         о.S.нуженПризывКликнуть() === true);
о = поднять({ адресРейтинга: '', встроено: true, фокус: true });
проверка('с фокусом плашки нет', о.S.нуженПризывКликнуть() === false);
о = поднять({ адресРейтинга: '', фокус: false });
/* На отдельной странице фокус и так на игре, а плашка была бы ложной
   тревогой поверх собственной игры. */
проверка('на отдельной странице плашки нет даже без фокуса',
         о.S.нуженПризывКликнуть() === false);

о = поднять({ адресРейтинга: '', встроено: true, фокус: false });
о.S.начатьЗабег();
упал = null;
try { о.S.нарисоватьМир(); о.S.нарисоватьИнтерфейс(); } catch (e) { упал = e.message; }
проверка('кадр с плашкой рисуется без ошибок', !упал, упал);
о.ИГРА.экран = 'старт';
упал = null;
try { о.S.экранСтарта(); о.S.нарисоватьПризывКликнуть(); } catch (e) { упал = e.message; }
проверка('плашка поверх меню тоже цела', !упал, упал);

раздел('8. КЛАВИШИ НЕ УХОДЯТ НА РОДИТЕЛЬСКУЮ СТРАНИЦУ');
/* Стрелки и пробел обязаны получать preventDefault: иначе они прокручивают
   страницу, на которой стоит рамка. */
о = поднять({ адресРейтинга: '', встроено: true });
function нажать(код) {
  let отменено = false;
  о.окно._событие('keydown', { code: код, preventDefault(){ отменено = true; } });
  return отменено;
}
for (const код of ['ArrowUp', 'ArrowDown', 'ArrowLeft', 'ArrowRight', 'Space']) {
  проверка(код + ' не уходит наверх', нажать(код) === true);
}
проверка('обычная клавиша страницу не блокирует', нажать('KeyW') === false);
проверка('нажатие всё равно доходит до игры', о.S.клавиши.KeyW === true);

раздел('9. МЕТКА ВСТРОЕННОСТИ В АНАЛИТИКЕ');
/* Без метки после выкладки на чужой сайт в отчётах будет каша из двух
   площадок, и понять, где просело, станет невозможно. */
о = поднять({ адресРейтинга: '', встроено: true });
const события = [];
о.окно.ym = (номер, вид, имя, данные) => события.push({ имя, данные });
о.S.отправитьСобытие('проверка', { своё: 1 });
проверка('событие ушло', события.length === 1, события.length);
проверка('в событии есть метка встроенности',
         события[0] && события[0].данные.встроено === 1,
         JSON.stringify(события[0] && события[0].данные));
проверка('свои поля события не потерялись',
         события[0] && события[0].данные.своё === 1);

о = поднять({ адресРейтинга: '' });
const события2 = [];
о.окно.ym = (н, в, имя, данные) => события2.push({ имя, данные });
о.S.отправитьСобытие('проверка', {});
проверка('на отдельной странице метка равна нулю',
         события2[0] && события2[0].данные.встроено === 0,
         JSON.stringify(события2[0] && события2[0].данные));

console.log('\n=== ' + (всего - провалов) + ' из ' + всего + ' проверок пройдено ===');
process.exit(провалов ? 1 : 0);
