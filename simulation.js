function открытьЛевелап() {
  const и = ИГРА.игрок;

  // За один подбор кристалла можно перескочить сразу через два уровня.
  // Тогда карточки не перезаписываем, а ставим второй выбор в очередь.
  if (ИГРА.экран === 'левелап') { ИГРА.очередьЛевелапов++; return; }

  /* Кадр спасения карточками не перебиваем: веер кристаллов от донатера
     почти всегда даёт уровень, и меню закрыло бы собой ровно тот момент,
     ради которого весь ивент и затевался. */
  if (ИГРА.взлетающийНик) {
    ИГРА.очередьЛевелапов++;
    ИГРА.отложенныйЛевелап = Math.max(ИГРА.отложенныйЛевелап, 1.3);
    return;
  }

  const пул = доступныеАпгрейды();
  if (пул.length === 0) return;

  /* На первых уровнях у игрока нет ответа на быстрые цели, поэтому КРИК
     подсовываем принудительно: без него ранний дрищ и мелочь безнаказанны. */
  const выбранные = [];
  const копия = пул.slice();
  if (ИГРА.уровень <= 3 && !и.апгрейды.krik) {
    const инд = копия.findIndex(а => а.ид === 'krik');
    if (инд >= 0 && random() < 0.75) выбранные.push(копия.splice(инд, 1)[0]);
  }
  while (выбранные.length < 3 && копия.length > 0) {
    let индекс;
    const хочуРедкую = random() < зажать(0.2 + и.шансРедкой, 0, 0.9);
    const редкие = копия.map((а, n) => а.редкая ? n : -1).filter(n => n >= 0);
    if (хочуРедкую && редкие.length > 0) индекс = изМассива(редкие);
    else индекс = Math.floor(random() * копия.length);
    выбранные.push(копия.splice(индекс, 1)[0]);
  }

  ИГРА.карточки = выбранные.map(а => ({
    апгрейд: а,
    новыйУровень: (и.апгрейды[а.ид] || 0) + 1
  }));
  ИГРА.экран = 'левелап';
  звук('левелап');
}

function взятьКарточку(индекс) {
  const карта = ИГРА.карточки[индекс];
  if (!карта) return;
  const и = ИГРА.игрок;
  const а = карта.апгрейд;
  и.апгрейды[а.ид] = (и.апгрейды[а.ид] || 0) + 1;
  отправитьСобытие('апгрейд_взят', { название: а.имя, уровень: и.апгрейды[а.ид] });
  if (а.применить) а.применить(и);
  // у пары карт есть своя реплика Суслова — см. ГОЛОС_КАРТЫ в config.js
  if (ГОЛОС_КАРТЫ[а.ид]) звук(ГОЛОС_КАРТЫ[а.ид]);

  // только что открытое оружие должно сработать быстро, а не через полный откат
  if (а.ид === 'krik'   && и.апгрейды.krik   === 1) и.таймерКрика  = 0.6;
  if (а.ид === 'otchet' && и.апгрейды.otchet === 1) и.таймерОтчёта = 2.0;
  if (а.ид === 'praim'  && и.апгрейды.praim  === 1) и.таймерПрайма = 8.0;
  if (а.ид === 'zdravo') и.таймерРегена = и.регенИнтервал;
  if (а.ид === 'beztresha' && !и.щитЗаряжен) { и.щитЗаряжен = true; и.таймерЩита = и.щитИнтервал; }

  ИГРА.карточки = [];
  всплывашка(и.x, и.y - и.в - 40, а.имя, ЦВЕТ.золото, 26);

  // взяли четвёртого пацана — сперва надо кого-то отпустить
  if (ИГРА.заменаНа) { ИГРА.экран = 'замена'; return; }

  ИГРА.экран = 'бой';
  продолжитьОчередьЛевелапов();
}

// остались невыбранные уровни — сразу показываем следующую раздачу
function продолжитьОчередьЛевелапов() {
  if (ИГРА.очередьЛевелапов > 0) {
    ИГРА.очередьЛевелапов--;
    открытьЛевелап();
  }
}

