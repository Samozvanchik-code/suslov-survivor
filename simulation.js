/* ==========================================================================
   ЛУТ НА КАРТЕ
   Предметы приходят из трёх источников: выкладка по таймеру (основной,
   работает с 30-й секунды), дроп черепа с босса и дроп белуги с врагов.
   Все три зовут уронитьПредмет, поэтому подбор и отрисовка едины.
   ========================================================================== */

function уронитьПредмет(вид, x, y) {
  ИГРА.предметы.push({ вид, x, y, фаза: visualRange(0, ДВА_ПИ), жизнь: ЛУТ.жизнь });
}

/* Точка для выкладки: кольцо вокруг игрока, но не под носом у босса —
   иначе предмет превращается в приманку под удар и его просто не берут. */
function точкаДляЛута() {
  const и = ИГРА.игрок;
  const босс = ИГРА.босс && !ИГРА.босс.мёртв ? ИГРА.босс : null;
  for (let попытка = 0; попытка < 14; попытка++) {
    const угол = случ(0, ДВА_ПИ);
    const д = случ(ЛУТ.дистОт, ЛУТ.дистДо);
    /* Направление сплющиваем по Y — мир нарисован в лёгкой изометрии, и без
       этого предметы над и под игроком кажутся дальше боковых. Но потом
       вектор нормируем обратно на д, иначе фактическое расстояние падало
       до 0.7д и предмет иногда лежал заметно ближе обещанных 250 px. */
    const нx = Math.cos(угол), нy = Math.sin(угол) * 0.7;
    const длина = Math.hypot(нx, нy) || 1;
    const x = и.x + (нx / длина) * д;
    const y = и.y + (нy / длина) * д;
    if (босс && дистанция(x, y, босс.x, босс.y) < ЛУТ.отБосса) continue;
    return { x, y };
  }
  return null;                                  // не нашли — пропускаем тик
}

function выложитьЛут() {
  if (ИГРА.предметы.length >= ЛУТ.максНаКарте) return;
  const т = точкаДляЛута();
  if (!т) return;
  уронитьПредмет(random() < ЛУТ.шансБелуги ? 'beluga' : 'cherep', т.x, т.y);
}

/* Дроп белуги с убитого врага. Общий кулдаун на весь забег: без него
   на поздних волнах, где за секунду умирает десяток анонов, пол заливает
   хилом и смерть перестаёт быть возможной. */
function попробоватьДропБелуги(в) {
  if (ИГРА.кулдаунБелуги > 0) return;
  const шанс = в.шаблон.лутШанс || 0;
  if (шанс <= 0 || random() >= шанс) return;
  if (ИГРА.предметы.length >= ЛУТ.максНаКарте) return;
  ИГРА.кулдаунБелуги = БЕЛУГА.кулдаунДропа;
  уронитьПредмет('beluga', в.x, в.y);
}

function обновитьПредметы(дт) {
  if (ИГРА.кулдаунБелуги > 0) ИГРА.кулдаунБелуги -= дт;

  // выкладка по таймеру
  ИГРА.таймерЛута -= дт;
  if (ИГРА.таймерЛута <= 0) {
    ИГРА.таймерЛута = случ(ЛУТ.интервалОт, ЛУТ.интервалДо);
    выложитьЛут();
  }

  for (let i = ИГРА.предметы.length - 1; i >= 0; i--) {
    const п = ИГРА.предметы[i];
    п.фаза += дт * 2.5;
    п.жизнь -= дт;
    if (п.жизнь <= 0) { ИГРА.предметы.splice(i, 1); continue; }
    /* Подбирает тот, кто дотронулся. Не «нулевой игрок» и не весь отряд:
       череп и белуга — предмет на одного, иначе один череп в коопе выдаёт
       четыре режима Шварца разом. */
    let взял = null;
    for (const и of живыеИгроки()) {
      if (дистанция(п.x, п.y, и.x, и.y - и.в * 0.4) < 52) { взял = и; break; }
    }
    if (взял) {
      ИГРА.предметы.splice(i, 1);
      if (п.вид === 'cherep') включитьРежимШварца(взял);
      else подобратьБелугу(взял);
    }
  }
}

/* Белуга. На неполном hp лечит процентом от максимума, на полном — даёт
   короткий бафф урона. Предмет, который может оказаться бесполезным,
   игрок перестаёт подбирать вообще, и вся механика лута умирает. */
function подобратьБелугу(кому) {
  const и = кому || ИГРА.игрок;
  const полное = и.hp >= и.максHp - 0.001;

  if (полное) {
    и.баффБелуги = БЕЛУГА.баффДлительность;
    всплывашка(и.x, и.y - и.в - 10,
               '+' + Math.round(БЕЛУГА.баффУрона * 100) + '% УРОНА', ЦВЕТ.золото, 24);
  } else {
    const лечение = Math.max(БЕЛУГА.минЛечение, и.максHp * БЕЛУГА.доляЛечения);
    const было = и.hp;
    и.hp = Math.min(и.максHp, и.hp + лечение);
    const факт = Math.round((и.hp - было) * 10) / 10;
    всплывашка(и.x, и.y - и.в - 10, '+' + факт + ' хп', ЦВЕТ.зелёный, 26);
  }

  звук('бульк');
  звук('голос_белуга');       // не каждый раз: шансГолоса в МАНИФЕСТЕ_ЗВУКОВ
  presentation.качка = 0.4;
  отправитьСобытие('белуга_подобрана', {
    время: Math.round(ИГРА.время),
    полное_хп: полное ? 1 : 0
  });
}

/* Режим Шварца. Механика черепа тянется сюда из этапа 6: награда,
   которая ничего не делает, наградой не является. Сам босс ШВАРЦ придёт позже. */
