/* Общий множитель урона: очки, ПРАЙМ и режим Шварца. */
function боевойМножитель(и) {
  return и.множительУрона
       * (и.уронЗаУровни || 1)
       * (и.праймОсталось > 0 ? 2 : 1)
       * (и.шварц > 0 ? ЧЕРЕП.урон : 1)
       * (и.баффБелуги > 0 ? 1 + БЕЛУГА.баффУрона : 1);
}

function ближайшийВраг(x, y, максД) {
  let лучший = null, лучшаяД = максД !== undefined ? максД : Infinity;
  for (const в of ИГРА.враги) {
    if (в.гаснет > 0) continue;               // вытесняемого не берём в прицел
    const д = дистанция(x, y, в.x, в.y);
    if (д < лучшаяД) { лучшаяД = д; лучший = в; }
  }
  return лучший;
}

// --- ГАНТЕЛЯ ---
function бросокГантели(кто) {
  const и = кто || ИГРА.игрок;
  const ур = и.апгрейды.gantelya || 1;
  const к = ГАНТЕЛЯ.уровни[ур - 1];

  const цель = ближайшийВраг(и.x, и.y - и.в * 0.4);
  const дальность = к.дальность * и.множительДальности;
  const сy = и.y - и.в * 0.55;

  /* Целимся в точку перехвата, а не в текущее положение врага.
     Дрищ на скорости 320 успевал уйти из точки броска, и гантеля
     пролетала мимо — он выглядел неубиваемым. */
  let угол;
  if (цель) угол = уголПерехвата(и.x, сy, цель, дальность);
  else угол = Math.atan2(и.напрY, и.напрX);
  const разлёт = (к.разлёт * Math.PI) / 180;
  const старт = -(к.штук - 1) / 2;

  for (let n = 0; n < к.штук; n++) {
    const а = угол + (старт + n) * разлёт;
    ИГРА.гантели.push({
      /* Чей бросок. Индексом, а не ссылкой: гантеля уезжает в снапшот
         комнаты, и ссылка на объект игрока там неотправляема. По этому же
         номеру гантеля знает, к кому возвращаться и чьи множители урона
         и крита применять. */
      владелец: и.индекс || 0,
      x: и.x, y: сy,
      углX: Math.cos(а), углY: Math.sin(а),
      скорость: ГАНТЕЛЯ.скоростьБроска,
      // равномерное торможение до нуля ровно на заданной дальности
      замедление: (ГАНТЕЛЯ.скоростьБроска * ГАНТЕЛЯ.скоростьБроска) / (2 * дальность),
      возвратX: к.возвратX,
      урон: к.урон,
      поворот: visualRange(0, 6.28),
      фаза: 'вперёд',
      задетые: new Map(),        // ид врага -> сколько ждать до следующего урона
      жизнь: 6
    });
  }
  и.сторона = Math.cos(угол) < 0 ? -1 : 1;
  звук('бросок', visualRange(0.95, 1.08));
}

/* Сколько летит гантеля до расстояния d. Она тормозит равномерно
   от скоростиБроска до нуля ровно на дальности D, значит
   d = v0*t - a*t^2/2 при a = v0^2/(2D). Обращаем и берём меньший корень. */
function времяПолёта(d, дальность) {
  const v0 = ГАНТЕЛЯ.скоростьБроска;
  const a = (v0 * v0) / (2 * дальность);
  const под = v0 * v0 - 2 * a * d;
  if (под <= 0) return v0 / a;                 // дальше не достаёт — берём полный разгон
  return (v0 - Math.sqrt(под)) / a;
}

function уголПерехвата(отX, отY, цель, дальность) {
  const цy = цель.y - цель.высотаСпрайта * 0.45;
  let тx = цель.x, тy = цy;
  const vx = цель.скорX || 0, vy = цель.скорY || 0;
  // две итерации хватает: сходится быстро, а цель всё равно виляет
  for (let i = 0; i < 2; i++) {
    const t = времяПолёта(дистанция(отX, отY, тx, тy), дальность);
    тx = цель.x + vx * t;
    тy = цy + vy * t;
  }
  return Math.atan2(тy - отY, тx - отX);
}

function обновитьГантели(дт) {
  const г = габариты('weapon_gantelya');
  const радиусГантели = Math.max(г.ш, г.в) * 0.42;

  for (let i = ИГРА.гантели.length - 1; i >= 0; i--) {
    const гн = ИГРА.гантели[i];
    const и = ИГРА.игроки[гн.владелец || 0] || ИГРА.игрок;
    if (!и) { ИГРА.гантели.splice(i, 1); continue; }
    гн.поворот += дт * ГАНТЕЛЯ.вращение;
    гн.жизнь -= дт;

    if (гн.фаза === 'вперёд') {
      гн.скорость -= гн.замедление * дт;
      if (гн.скорость <= 0) { гн.скорость = 0; гн.фаза = 'назад'; }
      гн.x += гн.углX * гн.скорость * дт;
      гн.y += гн.углY * гн.скорость * дт;
    } else {
      // догоняет игрока по его ТЕКУЩЕЙ позиции, разгоняясь
      const цx = и.x, цy = и.y - и.в * 0.55;
      const д = дистанция(гн.x, гн.y, цx, цy) || 1;
      гн.скорость = Math.min(гн.скорость + 1400 * дт,
                             ГАНТЕЛЯ.скоростьВозврата * гн.возвратX);
      гн.x += ((цx - гн.x) / д) * гн.скорость * дт;
      гн.y += ((цy - гн.y) / д) * гн.скорость * дт;
      if (д < 34) { ИГРА.гантели.splice(i, 1); continue; }
    }

    if (гн.жизнь <= 0) { ИГРА.гантели.splice(i, 1); continue; }

    // остывание по каждому задетому врагу
    for (const [ид, т] of гн.задетые) {
      const н = т - дт;
      if (н <= 0) гн.задетые.delete(ид); else гн.задетые.set(ид, н);
    }

    // попадания: гантеля пробивает насквозь и врагов не толкает
    for (let j = ИГРА.враги.length - 1; j >= 0; j--) {
      const в = ИГРА.враги[j];
      if (в.гаснет > 0 || гн.задетые.has(в.ид)) continue;
      const вцy = в.y - в.высотаСпрайта * 0.45;
      if (Math.abs(гн.x - в.x) < (радиусГантели + в.ш * 0.5) &&
          Math.abs(гн.y - вцy) < (радиусГантели + в.в * 0.6)) {

        let урон = гн.урон * боевойМножитель(и);
        if (гн.фаза === 'назад' && гн.возвратX > 1) урон *= 2;
        const крит = и.шансКрита > 0 && random() < и.шансКрита;
        if (крит) урон *= и.множительКрита;

        const былЖирный = в.шаблон.hp >= 40;
        уронВрагу(в, урон, гн.x, гн.y);
        /* Кулдаун ставим ПОСЛЕ удара. Раньше он взводился до вызова и
           поэтому съедался заблокированным попаданием в лоб: возвратный
           заход гантели по спине маски приходился ровно на этот кулдаун
           и пропадал. Из-за этого маска и была неубиваемой. */
        гн.задетые.set(в.ид, ГАНТЕЛЯ.кулдаунПоВрагу);
        if (крит) всплывашка(в.x, вцy - 26, 'КРИТ', ЦВЕТ.золото, 18);
        // бросок должен быть весомым: по жирному экран вздрагивает
        if (былЖирный) presentation.тряска = Math.max(presentation.тряска, 5);
      }
    }
  }
}

