function обновитьКамеру(дт) {
  const и = центрОтряда();
  const целx = и.x - ЭКР.ш / 2;
  const целy = (и.y - и.в * 0.4) - ЭКР.в / 2;
  const к = 1 - Math.pow(0.0005, дт);       // кадронезависимое сглаживание
  ИГРА.камера.x += (целx - ИГРА.камера.x) * к;
  ИГРА.камера.y += (целy - ИГРА.камера.y) * к;
  if (presentation.тряска > 0) {
    presentation.тряска -= дт * 26;
    if (presentation.тряска < 0) presentation.тряска = 0;
  }
  /* Качка от белуги. Отдельно от тряски: тряска дёргает камеру случайно,
     а тут нужен плавный пьяный крен, иначе глоток читается как удар. */
  if (presentation.качка > 0) {
    presentation.качка -= дт;
    if (presentation.качка < 0) presentation.качка = 0;
  }
}

function шагЛогики(дт) {
  ИГРА.времяВсего += дт;
  if (ИГРА.экран !== 'бой') return;
  /* ЧАСЫ ЗАБЕГА И ДОПОЛНИТЕЛЬНОЕ ВРЕМЯ.

     Раньше здесь стояла победа по таймеру: добежал до 600 — забег выигран.
     Теперь на 600 выходит ДВОЙНИК (ВОЛНЫ), и победа — его смерть; часы при
     этом ВСТАЮТ, а бой идёт в дополнительное время.

     Часы остановлены не ради красоты. Сервер рейтинга принимает время
     строго не больше 600: игрок уже находил щель с 601 и вставал в таблице
     выше всех честных десяток. Пусти часы дальше — и каждый, кто дошёл до
     финала, получит от сервера отказ вместо записи. Замороженные часы дают
     ровно 600 всем, кто добрался, а спорят они уровнем и убитыми, то есть
     теми же ключами сортировки, что и раньше. */
  if (ИГРА.время + дт >= БАЛАНС.длинаЗабега) {
    ИГРА.время = БАЛАНС.длинаЗабега;
    ИГРА.дополнительное += дт;
  } else {
    ИГРА.время += дт;
  }
  /* Время после победы считается ОТДЕЛЬНО и вне ветки про 600 — это зачёт
     бесконечки. Раньше слагаемое стояло внутри ветки, и это было верно, пока
     победа могла случиться только после 600. С досрочным финалом победа
     наступает и до остановки часов: игрок, добивший двойника на 560-й
     секунде, терял бы первые сорок секунд бесконечки просто потому, что
     часы ещё шли. */
  if (ИГРА.победаОдержана) ИГРА.бесконечное += дт;
  обновитьИгрока(дт);
  обновитьСпавн(дт);
  обновитьВрагов(дт);
  обновитьОружие(дт);
  обновитьГантели(дт);
  обновитьСвиту(дт);
  обновитьФинал(дт);
  обновитьУвольнения(дт);
  обновитьРасписаниеИвентов(дт);
  обновитьКлетку(дт);
  обновитьОбъяву(дт);
  обновитьУбегающих(дт);
  обновитьПризрака(дт);
  обновитьПредметы(дт);
  обновитьКольца(дт);
  обновитьТелеграфы(дт);
  обновитьСнаряды(дт);
  обновитьКуски(дт);
  обновитьКристаллы(дт);
  emit("effects-step", { dt: дт });
  обновитьКамеру(дт);
}

