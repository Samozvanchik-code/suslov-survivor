/* ==========================================================================
   ДВОЙНИК: БИЛД ИГРОКА, НАПРАВЛЕННЫЙ В ИГРОКА

   Ближний удар (полоса ГАНТЕЛЯ) двойник делает общим механизмом боссов.
   Здесь — то, чего у общего механизма нет: бросок гантелей на дистанции,
   КРИК вокруг себя, ОТЧЁТ по свите и ПРАЙМ.

   Бросок нужен именно НА ДИСТАНЦИИ: без него от двойника решает бег, а
   двойник — это проверка билда, а не забега на скорость.
   ========================================================================== */
function обновитьДвойника(в, дт) {
  const и = ИГРА.игрок;
  const к = ДВОЙНИК_КОПИЯ;
  const копия = в.копия;
  if (!и || и.мёртв) return;

  // --- ПРАЙМ: у игрока ульта повторяется, значит и у двойника ---
  if (в.праймОсталось > 0) {
    в.праймОсталось -= дт;
    if (в.праймОсталось <= 0 && копия.прайм) в.таймерПрайма = к.праймПовтор;
  } else if (копия.прайм && в.фаза2) {
    в.таймерПрайма -= дт;
    if (в.таймерПрайма <= 0) {
      в.праймОсталось = к.праймДлительность;
      всплывашка(в.x, в.y - в.высотаСпрайта - 20, 'ПРАЙМ', ЦВЕТ.золото, 26);
      presentation.вспышкаЭкрана = Math.max(presentation.вспышкаЭкрана, 0.25);
      звук('босс');
      звук('голос_прайм');        // копия билда — значит и реплика та же
    }
  }

  const темп = в.праймОсталось > 0 ? к.праймТемп : 1;
  const дист = дистанция(в.x, в.y, и.x, и.y);

  /* --- БРОСОК ГАНТЕЛЬ. Штук — по уровню гантели в копии, как у игрока
     веером. Урон одного снаряда 1: три снаряда в упор дают 3, и это уже
     потолок читаемой смерти, а не «прилетело в ебло». --- */
  в.таймерГантели -= дт;
  if (в.таймерГантели <= 0 && дист > 240) {
    в.таймерГантели = к.интервалГантели * темп;
    const центр = Math.atan2(и.y - в.y, и.x - в.x);
    const штук = копия.гантеля;
    const цy = в.y - в.высотаСпрайта * 0.55;
    for (let n = 0; n < штук; n++) {
      const смещение = штук === 1 ? 0
        : (n / (штук - 1) - 0.5) * 2 * к.разлётГантели;
      запуститьСнаряд(в.x, цy, центр + смещение, {
        источник: в, урон: к.уронГантели,
        скорость: к.скоростьГантели, вид: 'гантеля'
      });
    }
    звук('бросок', 0.8);
  }

  /* --- КРИК. Круг вокруг себя, радиус берётся из уровня игрока: тот же
     ответ на «меня обступили», только теперь обступил он. Заводится, когда
     игрок в радиусе — то есть наказывает за привычку стоять в упор. --- */
  if (копия.крик) {
    в.таймерКрика -= дт;
    const радиус = КРИК.уровни[копия.крик - 1].радиус;
    if (в.таймерКрика <= 0 && дист < радиус * 1.15) {
      в.таймерКрика = к.интервалКрика * темп;
      в.замахБосса = Math.max(ТЕЛЕГРАФ.минЗамах, к.замахКрика);
      завестиТелеграф({
        вид: 'круг', x: в.x, y: в.y, радиус,
        замах: в.замахБосса, урон: к.уронКрика, источник: в, подпись: 'КРИК'
      });
      звук('крик', 0.9);
    }
  }

  /* --- ОТЧЁТ ОТПРАВЛЕН. У игрока он стирает анона насмерть, у двойника —
     УВОЛЬНЯЕТ спутника на время. Навсегда нельзя: отобранный за прокачку
     таракан — это наказание за билд, а не за игру. Нет свиты — нет и
     атаки: зеркалу нечего отражать. --- */
  if (копия.отчёт) {
    в.таймерОтчёта -= дт;
    if (в.таймерОтчёта <= 0) {
      в.таймерОтчёта = к.интервалОтчёта * темп;
      уволитьСпутника();
    }
  }
}

/* Увольнение: спутник исчезает на время и возвращается сам. Возврат идёт
   пересборкой из уровня карты, а не сохранённой копией объекта — уровень
   и есть источник истины, и так спутник не приходит с чужим hp. */
function уволитьСпутника() {
  const вид = ИГРА.тараканы.length >= ИГРА.щенки.length && ИГРА.тараканы.length > 0
    ? 'тараканы'
    : (ИГРА.щенки.length > 0 ? 'щенки' : null);
  if (!вид) return false;

  const список = вид === 'тараканы' ? ИГРА.тараканы : ИГРА.щенки;
  const ушедший = список.pop();
  ИГРА.увольнения.push({ вид, осталось: ДВОЙНИК_КОПИЯ.увольнение });
  const и = ИГРА.игрок;
  const x = ушедший ? ушедший.x : и.x, y = ушедший ? ушедший.y : и.y;
  всплывашка(x, y - 40, 'ОТЧЁТ ОТПРАВЛЕН', ЦВЕТ.золото, 22);
  брызги(x, y, '#ffcc44', 10);
  звук('крик', 1.6);
  звук('голос_отчёт');
  отправитьСобытие('двойник_уволил', { вид });
  return true;
}

function обновитьУвольнения(дт) {
  for (let i = ИГРА.увольнения.length - 1; i >= 0; i--) {
    const у = ИГРА.увольнения[i];
    у.осталось -= дт;
    if (у.осталось > 0) continue;
    ИГРА.увольнения.splice(i, 1);
    if (у.вид === 'тараканы') пересобратьТараканов();
    else пересобратьЩенков();
  }
}

/* ==========================================================================
   ФИНАЛ И ДОПОЛНИТЕЛЬНОЕ ВРЕМЯ

   Часы забега встали на 600 (см. шагЛогики в engine.js), и дальше идёт
   дополнительное время. Пока двойник жив, каждые ФИНАЛ.интервалЦикла секунд
   приходит босс из пула — иначе финал можно было бы не выигрывать, а
   пересиживать, набивая уровни на последней волне.

   Каждый следующий круг цикла крепче предыдущего: множитель растёт в
   степень, а не складывается, — как и ступени сложности.
   ========================================================================== */
function обновитьФинал(дт) {
  if (!(ИГРА.дополнительное > 0)) return;
  /* Боссы цикла идут в двух случаях: пока жив двойник (чтобы финал нельзя
     было пересидеть) и в бесконечке после победы — там они и есть всё
     содержание режима. */
  const финалЖив = ИГРА.босс && ИГРА.босс.шаблон.финал && !ИГРА.босс.мёртв;
  if (!финалЖив && !ИГРА.бесконечка) return;

  ИГРА.таймерЦикла -= дт;
  if (ИГРА.таймерЦикла > 0) return;
  ИГРА.таймерЦикла = ФИНАЛ.интервалЦикла;

  const имя = ФИНАЛ.пул[ИГРА.боссовЦикла % ФИНАЛ.пул.length];
  const круг = Math.floor(ИГРА.боссовЦикла / ФИНАЛ.пул.length);
  ИГРА.боссовЦикла++;
  вызватьБосса(имя, Math.pow(ФИНАЛ.ростHp, круг + 1));
  const и = ИГРА.игрок;
  if (и) всплывашка(и.x, и.y - 200, 'ОНИ НЕ КОНЧАЮТСЯ', ЦВЕТ.хп, 30);
}

function естьСвоиГантели(и) {
  for (const гн of ИГРА.гантели) if ((гн.владелец || 0) === (и.индекс || 0)) return true;
  return false;
}

// --- ОТЧЁТ ОТПРАВЛЕН ---
function отправитьОтчёт(кто) {
  const и = кто || ИГРА.игрок;
  const к = ОТЧЁТ.уровни[и.апгрейды.otchet - 1];
  const кандидаты = ИГРА.враги.filter(в => в.гаснет <= 0 && дистанция(в.x, в.y, и.x, и.y) < к.радиус);
  if (кандидаты.length === 0) { и.таймерОтчёта = 0.5; return; }   // некому — пробуем скоро снова

  for (let n = 0; n < к.целей && кандидаты.length > 0; n++) {
    const инд = Math.floor(random() * кандидаты.length);
    const в = кандидаты.splice(инд, 1)[0];
    const цy = в.y - в.высотаСпрайта * 0.5;
    всплывашка(в.x, цy, 'отчёт отправлен', ЦВЕТ.золото, 18);
    брызги(в.x, цy, ЦВЕТ.золото, 14);
    убитьВрага(в);
  }
}

/* Оружие всего отряда. Каждый стреляет своим: таймеры, множители и билд
   лежат на самом игроке, общего оружейного состояния нет. Свита (тараканы,
   щенки, пацаны) пока остаётся у нулевого — она собирается из карточек, а
   своя раздача карточек у каждого появляется на этапе 2. */
function обновитьОружие(дт) {
  for (const и of живыеИгроки()) шагОружия(и, дт);
}

function шагОружия(и, дт) {
  const мп = и.множительПерезарядки * (и.праймОсталось > 0 ? 0.5 : 1);

  /* Гантеля: новый бросок, когда откатилась перезарядка и вернулись СВОИ.
     Условие именно про свои: с общим списком четвёртый игрок в комнате
     блокировал бы броски остальным трём, и чем больше отряд, тем реже
     стреляет каждый. */
  и.таймерГантели -= дт;
  if (и.таймерГантели <= 0 && !естьСвоиГантели(и)) {
    бросокГантели(и);
    и.таймерГантели = ГАНТЕЛЯ.перезарядка * мп;
  }

  if (и.апгрейды.krik) {
    и.таймерКрика -= дт;
    if (и.таймерКрика <= 0) { крикнуть(и); и.таймерКрика = КРИК.перезарядка * мп; }
  }
  if (и.апгрейды.otchet) {
    и.таймерОтчёта -= дт;
    if (и.таймерОтчёта <= 0) {
      отправитьОтчёт(и);
      if (и.таймерОтчёта <= 0) и.таймерОтчёта = ОТЧЁТ.уровни[и.апгрейды.otchet - 1].перезарядка * мп;
    }
  }
  if (и.апгрейды.praim) {
    const к = ПРАЙМ.уровни[и.апгрейды.praim - 1];
    и.таймерПрайма -= дт;
    if (и.таймерПрайма <= 0) {
      и.праймОсталось = к.длительность;
      и.таймерПрайма = к.перезарядка;
      всплывашка(и.x, и.y - и.в - 30, 'ПРАЙМ', ЦВЕТ.золото, 26);
      звук('левелап');
      звук('голос_прайм');
    }
  }
  if (и.праймОсталось > 0) и.праймОсталось -= дт;

  if (и.баффБелуги > 0) и.баффБелуги -= дт;

  // пассивки по таймеру
  if (и.регенИнтервал > 0) {
    и.таймерРегена -= дт;
    if (и.таймерРегена <= 0) {
      и.таймерРегена = и.регенИнтервал;
      if (и.hp < и.максHp) {
        // hp дробное, поэтому обязательно подрезаем: иначе 2.6 + 1 = 3.6
        и.hp = Math.min(и.максHp, и.hp + 1);
        всплывашка(и.x, и.y - и.в - 10, '+1', ЦВЕТ.зелёный, 20);
      }
    }
  }
  if (и.щитИнтервал > 0 && !и.щитЗаряжен) {
    и.таймерЩита -= дт;
    if (и.таймерЩита <= 0) { и.щитЗаряжен = true; и.таймерЩита = и.щитИнтервал; }
  }
}


/* ==========================================================================
   БЛОК 11б. СВИТА: тараканы, щенки, пацаны из Пензы
   Свита не сталкивается с игроком и не толкает его — только с врагами.
   У каждого поводок: отбежал дальше ПОВОДОК — бросает цель и возвращается.
   ========================================================================== */

function уровеньСвиты(ид) { return ИГРА.игрок.апгрейды[ид] || 0; }

function пересобратьТараканов() {
  const ур = уровеньСвиты('tarakany');
  const к = ТАРАКАНЫ.уровни[ур - 1];
  const и = ИГРА.игрок;
  ИГРА.тараканы.length = 0;
  if (!к) return;

  /* Параметры лежат В САМОЙ ОСОБИ, а не берутся из уровня общим блоком.
     Иначе смешанная свита невозможна, а она нужна: на максимуме к шестерым
     добавляется тараканище со своим уроном и радиусом укуса. */
  const состав = [];
  for (let n = 0; n < к.штук; n++) {
    состав.push({ спрайт: 'pet_tarakan', урон: к.урон, интервал: к.интервал,
                  взрыв: к.взрыв, радиусУкуса: к.радиусУкуса });
  }
  if (к.тараканище) {
    const б = к.тараканище;
    состав.push({ спрайт: 'pet_tarakanische', урон: б.урон, интервал: б.интервал,
                  взрыв: б.взрыв || 0, радиусУкуса: б.радиусУкуса });
  }

  const всего = состав.length;
  for (let n = 0; n < всего; n++) {
    const о = состав[n];
    ИГРА.тараканы.push({
      x: и.x + случ(-40, 40), y: и.y + случ(-40, 40),
      // свой сдвиг фазы бега и своё место в свите: иначе шесть штук
      // двигаются как одна клякса
      фаза: (n / всего) * ДВА_ПИ + visualRange(-0.4, 0.4),
      уголОрбиты: (n / всего) * ДВА_ПИ,
      местоВСвите: n, всегоВСвите: всего,
      разбросСкорости: случ(0.85, 1.15),      // задаётся один раз при появлении
      кулдаун: случ(0, о.интервал), цель: null, сторона: 1,
      спрайт: о.спрайт, урон: о.урон, интервал: о.интервал,
      взрыв: о.взрыв, радиусУкуса: о.радиусУкуса
    });
  }
}

function пересобратьЩенков() {
  const ур = уровеньСвиты('schenki');
  const к = ЩЕНКИ.уровни[ур - 1];
  const и = ИГРА.игрок;
  const было = ИГРА.щенки.slice();
  ИГРА.щенки.length = 0;
  if (!к) return;
  const штук = к.штук + (и.бонусЩенков || 0);      // Aartll даёт щенка навсегда
  for (let n = 0; n < штук; n++) {
    const старый = было[n];
    ИГРА.щенки.push(старый ? Object.assign(старый, { максHp: к.hp, hp: Math.min(старый.hp, к.hp) }) : {
      x: и.x + случ(-50, 50), y: и.y + случ(-50, 50),
      фаза: visualRange(0, ДВА_ПИ), уголОрбиты: (n / штук) * ДВА_ПИ,
      кулдаун: 0, hp: к.hp, максHp: к.hp, выбыл: 0, сторона: 1
    });
  }
}

/* Взятие пацана. Одновременно активны максимум трое: четвёртый предлагает
   замену, потому что пятеро сразу — это каша и мгновенный автобой. */
function взятьСоюзника(ключ) {
  const уже = ИГРА.союзники.find(с => с.ключ === ключ);
  if (уже) { уже.уровень = ИГРА.игрок.апгрейды['ally_' + ключ]; return; }

  if (ИГРА.союзники.length >= МАКС_СОЮЗНИКОВ) {
    ИГРА.заменаНа = ключ;          // экран замены поднимется из взятьКарточку
    return;
  }
  добавитьСоюзника(ключ);
}

function добавитьСоюзника(ключ) {
  const к = СОЮЗНИКИ[ключ];
  const и = ИГРА.игрок;
  const с = {
    ключ, конфиг: к,
    уровень: и.апгрейды['ally_' + ключ] || 1,
    x: и.x + случ(-60, 60), y: и.y + случ(-60, 60),
    уголОрбиты: 0,                    // проставит переразнестиУглы
    фаза: visualRange(0, ДВА_ПИ), сторона: 1,
    кулдаун: случ(0, 1),
    hp: 0, максHp: 0,
    рывокОсталось: 0, рывокX: 0, рывокY: 0,
    охота: null                       // цель охотника
  };
  if (к.роль === 'танк') {
    const п = к.уровни[с.уровень - 1];
    с.hp = п.hp; с.максHp = п.hp;
  }
  ИГРА.союзники.push(с);
  переразнестиУглы();
}

/* Стартовые углы раскладываем равномерно по кругу и пересчитываем при каждом
   изменении состава. Раньше угол считался от длины массива на момент взятия,
   и после замены пацана двое могли оказаться в одной точке. */
function переразнестиУглы() {
  const всего = ИГРА.союзники.length;
  for (let i = 0; i < всего; i++) {
    ИГРА.союзники[i].уголОрбиты = (i / всего) * ДВА_ПИ;
  }
}

function заменитьСоюзника(индекс) {
  const новый = ИГРА.заменаНа;
  ИГРА.заменаНа = null;
  if (индекс >= 0 && индекс < ИГРА.союзники.length) {
    const ушёл = ИГРА.союзники[индекс];
    ИГРА.союзники.splice(индекс, 1);
    переразнестиУглы();
    всплывашка(ИГРА.игрок.x, ИГРА.игрок.y - 150, ушёл.ключ + ' ушёл', ЦВЕТ.текстТускл, 22);
  }
  if (новый) добавитьСоюзника(новый);
  ИГРА.экран = 'бой';
  продолжитьОчередьЛевелапов();
}

// --- общая механика: держаться у игрока, поводок, поиск цели ---
function держатьсяУИгрока(с, дт, орбита, скорость) {
  const и = ИГРА.игрок;
  с.уголОрбиты += (с.конфиг ? с.конфиг.скоростьОрбиты : 1.4) * дт;
  const цx = и.x + Math.cos(с.уголОрбиты) * орбита;
  const цy = и.y + Math.sin(с.уголОрбиты) * орбита * 0.6;
  const д = дистанция(с.x, с.y, цx, цy) || 1;
  if (д > 4) {
    const ш = Math.min(скорость * дт, д);
    с.x += ((цx - с.x) / д) * ш;
    с.y += ((цy - с.y) / д) * ш;
    if (Math.abs(цx - с.x) > 1) с.сторона = цx > с.x ? 1 : -1;
  }
}

function ближайшийВрагК(x, y, максД, фильтр) {
  let лучший = null, лучшаяД = максД;
  for (const в of ИГРА.враги) {
    if (в.гаснет > 0 || в.мёртв) continue;
    if (фильтр && !фильтр(в)) continue;
    const д = дистанция(x, y, в.x, в.y);
    if (д < лучшаяД) { лучшаяД = д; лучший = в; }
  }
  return лучший;
}

/* Ближайший враг, которого ещё не взял другой таракан.
   Раньше вся стая била одного анона с 10 хп: пять укусов из шести уходили
   в труп. Разведение по целям поднимает урон стаи без правки цифр. */
function свободнаяЦельДляТаракана(отX, отY, занятые) {
  let лучший = null, лучшаяД = ПОВОДОК;
  for (const в of ИГРА.враги) {
    if (в.гаснет > 0 || в.мёртв || занятые.has(в)) continue;
    const д = дистанция(отX, отY, в.x, в.y);
    if (д < лучшаяД) { лучшаяД = д; лучший = в; }
  }
  return лучший;
}

function обновитьТараканов(дт) {
  const ур = уровеньСвиты('tarakany');
  if (!ур) return;
  const к = ТАРАКАНЫ.уровни[ур - 1];
  const и = ИГРА.игрок;

  // кто уже занят: цель держится за тараканом, пока жива и в пределах поводка
  const занятые = new Set();
  for (const т of ИГРА.тараканы) {
    if (т.цель && (т.цель.мёртв || т.цель.гаснет > 0 ||
        дистанция(и.x, и.y, т.цель.x, т.цель.y) > ПОВОДОК)) т.цель = null;
    if (т.цель) занятые.add(т.цель);
  }

  for (const т of ИГРА.тараканы) {
    const скорость = ТАРАКАНЫ.скорость * (т.разбросСкорости || 1);
    т.фаза += дт * 9;
    if (т.кулдаун > 0) т.кулдаун -= дт;

    const доИгрока = дистанция(т.x, т.y, и.x, и.y);
    if (доИгрока > ПОВОДОК) { if (т.цель) занятые.delete(т.цель); т.цель = null; }
    if (!т.цель) {
      const н = свободнаяЦельДляТаракана(т.x, т.y, занятые);
      // все цели заняты — добиваем ближайшую, лишь бы не стоять
      т.цель = н || ближайшийВрагК(и.x, и.y, ПОВОДОК);
      if (н) занятые.add(н);
    }

    if (т.цель && доИгрока < ПОВОДОК) {
      const д = дистанция(т.x, т.y, т.цель.x, т.цель.y) || 1;
      const ш = Math.min(скорость * дт, д);
      т.x += ((т.цель.x - т.x) / д) * ш;
      т.y += ((т.цель.y - т.y) / д) * ш;
      т.сторона = т.цель.x > т.x ? 1 : -1;
      // параметры берём у самой особи: свита на максимуме смешанная
      if (д < (т.радиусУкуса || к.радиусУкуса) && т.кулдаун <= 0) {
        т.кулдаун = т.интервал || к.интервал;
        const цель = т.цель;
        const уронОсоби = т.урон !== undefined ? т.урон : к.урон;
        const взрывОсоби = т.взрыв !== undefined ? т.взрыв : к.взрыв;
        уронВрагу(цель, уронОсоби * боевойМножитель(и), т.x, т.y);
        ИГРА.уронСвиты += уронОсоби;
        if (взрывОсоби && цель.мёртв) взрывТаракана(т, взрывОсоби);
        if (цель.мёртв) { занятые.delete(цель); т.цель = null; }
      }
    } else {
      // возвращаются веером: у каждого своя точка в свите, а не общая куча
      const всего = т.всегоВСвите || ИГРА.тараканы.length || 1;
      const своё = (т.местоВСвите || 0) / всего * ДВА_ПИ;
      т.уголОрбиты += 1.1 * дт;
      const цx = и.x + Math.cos(т.уголОрбиты + своё) * 62;
      const цy = и.y + Math.sin(т.уголОрбиты + своё) * 38;
      const д = дистанция(т.x, т.y, цx, цy) || 1;
      if (д > 3) {
        const ш = Math.min(скорость * дт, д);
        т.x += ((цx - т.x) / д) * ш;
        т.y += ((цy - т.y) / д) * ш;
        т.сторона = цx > т.x ? 1 : -1;
      }
    }
  }

  // слабое расталкивание между собой: радиус в полтора своих размера
  const г = габариты('pet_tarakan', 1, 1);
  const минимум = г.ш * 1.5;
  for (let i = 0; i < ИГРА.тараканы.length; i++) {
    for (let j = i + 1; j < ИГРА.тараканы.length; j++) {
      const a = ИГРА.тараканы[i], b = ИГРА.тараканы[j];
      const рx = a.x - b.x, рy = a.y - b.y;
      const рд = Math.hypot(рx, рy);
      if (рд > 0.001 && рд < минимум) {
        const сила = (минимум - рд) / минимум * 40 * дт;
        a.x += (рx / рд) * сила; a.y += (рy / рд) * сила;
        b.x -= (рx / рд) * сила; b.y -= (рy / рд) * сила;
      }
    }
  }
}

function взрывТаракана(т, урон) {
  ИГРА.кольца.push({ x: т.x, y: т.y, r: 10, макс: ТАРАКАНЫ.радиусВзрыва,
                     жизнь: 0.25, всего: 0.25, цвет: '#e08a3a' });
  брызги(т.x, т.y, '#c9762f', 10);
  for (const в of ИГРА.враги) {
    if (в.гаснет > 0 || в.мёртв) continue;
    if (дистанция(в.x, в.y, т.x, т.y) > ТАРАКАНЫ.радиусВзрыва) continue;
    уронВрагу(в, урон, т.x, т.y, true);
    ИГРА.уронСвиты += урон;
  }
}

function обновитьЩенков(дт) {
  const ур = уровеньСвиты('schenki');
  if (!ур) return;
  const к = ЩЕНКИ.уровни[ур - 1];
  const и = ИГРА.игрок;

  for (const щ of ИГРА.щенки) {
    if (щ.выбыл > 0) {
      щ.выбыл -= дт;
      if (щ.выбыл <= 0) { щ.hp = к.hp; щ.x = и.x; щ.y = и.y; }
      continue;
    }
    щ.фаза += дт * 7;
    if (щ.кулдаун > 0) щ.кулдаун -= дт;

    const доИгрока = дистанция(щ.x, щ.y, и.x, и.y);
    let цель = null;
    if (доИгрока < ПОВОДОК) цель = ближайшийВрагК(и.x, и.y, ПОВОДОК);

    if (цель) {
      const д = дистанция(щ.x, щ.y, цель.x, цель.y) || 1;
      const ш = Math.min(ЩЕНКИ.скорость * дт, д);
      щ.x += ((цель.x - щ.x) / д) * ш;
      щ.y += ((цель.y - щ.y) / д) * ш;
      щ.сторона = цель.x > щ.x ? 1 : -1;
      if (д < ЩЕНКИ.радиусУкуса && щ.кулдаун <= 0) {
        щ.кулдаун = к.интервал;
        уронВрагу(цель, к.урон * боевойМножитель(и), щ.x, щ.y);
        ИГРА.уронСвиты += к.урон;
      }
    } else {
      const цx = и.x + Math.cos(щ.уголОрбиты) * 85;
      const цy = и.y + Math.sin(щ.уголОрбиты) * 50;
      щ.уголОрбиты += 1.1 * дт;
      const д = дистанция(щ.x, щ.y, цx, цy) || 1;
      if (д > 4) {
        const ш = Math.min(ЩЕНКИ.скорость * дт, д);
        щ.x += ((цx - щ.x) / д) * ш; щ.y += ((цy - щ.y) / д) * ш;
        щ.сторона = цx > щ.x ? 1 : -1;
      }
    }

    // «приносят XP»: подбирают кристаллы и отдают опыт хозяину
    for (let i = ИГРА.кристаллы.length - 1; i >= 0; i--) {
      const кр = ИГРА.кристаллы[i];
      if (дистанция(кр.x, кр.y, щ.x, щ.y) < ЩЕНКИ.радиусСбора * 0.35) {
        добавитьОпыт(кр.ценность);
        ИГРА.кристаллы.splice(i, 1);
      }
    }
  }
}

