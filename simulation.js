function обновитьКристаллы(дт) {
  for (let i = ИГРА.кристаллы.length - 1; i >= 0; i--) {
    const к = ИГРА.кристаллы[i];
    к.фаза += дт * 3;

    /* Кристалл тянется к ближайшему живому. Радиус сбора берётся у него же:
       карта на магнит — личная, и в коопе она не должна работать чужим
       радиусом. Прокачка и опыт пока общие на отряд — своя у каждого
       появится вместе с карточками на этапе 2. */
    const и = ближайшийИгрок(к.x, к.y);
    if (!и) continue;
    const радиус = и.радиусСбора;

    const д = дистанция(к.x, к.y, и.x, и.y - и.в * 0.4);
    if (д < радиус) к.притянут = true;

    if (к.притянут) {
      // магнит: чем ближе, тем быстрее — кристалл «всасывается»
      const скорость = 320 + (1 - зажать(д / Math.max(радиус, 1), 0, 1)) * 700;
      к.x += ((и.x - к.x) / (д || 1)) * скорость * дт;
      к.y += ((и.y - и.в * 0.4 - к.y) / (д || 1)) * скорость * дт;
      if (д < 26) {
        добавитьОпыт(к.ценность, и);
        ИГРА.кристаллы.splice(i, 1);
        continue;
      }
    } else {
      // разлетелся при выпадении и затормозил
      к.x += к.вx * дт; к.y += к.вy * дт;
      const затух = Math.pow(0.002, дт);
      к.вx *= затух; к.вy *= затух;
    }
  }
}

function добавитьОпыт(сколько, кому) {
  const и = кому || ИГРА.игрок;
  const итог = сколько * и.множительОпыта;
  ИГРА.опыт += итог;
  ИГРА.опытВсего += итог;
  звук('подборОпыта', visualRange(0.95, 1.15));

  let порог = БАЛАНС.порогУровня(ИГРА.уровень);
  while (ИГРА.опыт >= порог) {
    ИГРА.опыт -= порог;
    ИГРА.уровень++;
    порог = БАЛАНС.порогУровня(ИГРА.уровень);
    применитьРостУровня();
    открытьЛевелап();
  }
}


