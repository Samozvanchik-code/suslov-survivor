/* Расстановка отряда на старте. Один игрок встаёт ровно в ноль, как раньше;
   четверо расходятся по кругу, иначе они стартуют внутри друг друга и первая
   же волна бьёт всех одним контактом. */
const РАЗНОС_СТАРТА = 90;

function собратьОтряд() {
  ИГРА.игроки.length = 0;
  for (let i = 0; i < размерОтряда; i++) {
    const и = создатьИгрока(i);
    if (размерОтряда > 1) {
      const угол = (i / размерОтряда) * ДВА_ПИ;
      и.x = Math.cos(угол) * РАЗНОС_СТАРТА;
      и.y = Math.sin(угол) * РАЗНОС_СТАРТА;
    }
    ИГРА.игроки.push(и);
  }
}

function живыеИгроки() {
  const живые = [];
  for (const и of ИГРА.игроки) if (и && и.жив) живые.push(и);
  return живые;
}

/* Кого враг считает целью. Живого нет ни одного — возвращаем нулевого, чтобы
   вызывающий код не разбирался с null: забег в этот момент уже кончился. */
function ближайшийИгрок(x, y) {
  let цель = null, лучшая = Infinity;
  for (const и of ИГРА.игроки) {
    if (!и || !и.жив) continue;
    const д = дистанция(x, y, и.x, и.y);
    if (д < лучшая) { лучшая = д; цель = и; }
  }
  return цель || ИГРА.игрок;
}

/* Центр отряда — точка, за которой едет камера и от которой считаются спавн
   и вытеснение. В сингле это сам игрок, число в число. */
function центрОтряда() {
  const живые = живыеИгроки();
  const список = живые.length > 0 ? живые : ИГРА.игроки;
  if (список.length === 0) return { x: 0, y: 0, в: ГЕРОЙ.хитбоксВ };
  if (список.length === 1) return список[0];
  let x = 0, y = 0, в = 0;
  for (const и of список) { x += и.x; y += и.y; в += и.в; }
  return { x: x / список.length, y: y / список.length, в: в / список.length };
}

/* Куда в среднем движется отряд. Нужен спавну наперерез: в сингле это
   направление самого игрока, в коопе — общее направление живых. Отряд
   разбежался в разные стороны — сумма гасится, и спавн становится
   равномерным, что как раз верно: перерезать некого. */
function ходОтряда() {
  const живые = живыеИгроки();
  if (живые.length === 0) return { идёт: false, напрX: 1, напрY: 0 };
  if (живые.length === 1) return живые[0];
  let x = 0, y = 0, идёт = false;
  for (const и of живые) {
    if (!и.идёт) continue;
    идёт = true;
    x += и.напрX; y += и.напрY;
  }
  const д = Math.hypot(x, y);
  if (!идёт || д < 0.001) return { идёт: false, напрX: 1, напрY: 0 };
  return { идёт: true, напрX: x / д, напрY: y / д };
}

