function обновитьСоюзников(дт) {
  const и = ИГРА.игрок;
  ИГРА.аураЗамедления = null;

  for (const с of ИГРА.союзники) {
    const к = с.конфиг;
    const п = к.уровни[Math.min(с.уровень, к.уровни.length) - 1];
    с.фаза += дт * 6;
    if (с.кулдаун > 0) с.кулдаун -= дт;

    if (к.роль === 'таран' && с.рывокОсталось > 0) {
      с.рывокОсталось -= дт;
      с.x += с.рывокX * дт; с.y += с.рывокY * дт;
      с.задетоЗаПроход = с.задетоЗаПроход || 0;
      for (const в of ИГРА.враги) {
        if (с.задетоЗаПроход >= п.целей) break;
        if (в.гаснет > 0 || в.мёртв || в._таранен === с.метка) continue;
        if (дистанция(в.x, в.y, с.x, с.y) > 55) continue;
        в._таранен = с.метка;
        с.задетоЗаПроход++;
        уронВрагу(в, п.урон * боевойМножитель(и), с.x, с.y);
        ИГРА.уронСвиты += п.урон;
      }
      continue;
    }

    /* ОХОТНИК (leva2k). Не висит на орбите, а сам бегает по врагам.
       Цель ищем в радиусе от ИГРОКА, а не от левы: если считать от него,
       он будет перескакивать с цели на цель и уйдёт за горизонт. */
    if (к.роль === 'охотник') {
      const держит = с.охота && !с.охота.мёртв && с.охота.гаснет <= 0 &&
                     дистанция(с.охота.x, с.охота.y, и.x, и.y) < ОХОТНИК.радиусПоиска;
      if (!держит) с.охота = ближайшийВрагК(и.x, и.y, ОХОТНИК.радиусПоиска);

      // ушёл слишком далеко от игрока — бросает всё и возвращается
      if (с.охота && дистанция(с.x, с.y, и.x, и.y) > ОХОТНИК.поводок) с.охота = null;

      if (с.охота) {
        const ц = с.охота;
        const д = дистанция(с.x, с.y, ц.x, ц.y) || 1;
        if (д > ОХОТНИК.радиусУдара * 0.7) {
          const ш = Math.min(ОХОТНИК.скоростьОхоты * дт, д);
          с.x += ((ц.x - с.x) / д) * ш;
          с.y += ((ц.y - с.y) / д) * ш;
          с.сторона = ц.x > с.x ? 1 : -1;
        }
        if (с.кулдаун <= 0 && д <= ОХОТНИК.радиусУдара + ц.ш * 0.5) {
          с.кулдаун = ОХОТНИК.интервал;
          let задето = 0;
          for (const в of ИГРА.враги) {
            if (задето >= п.целей) break;
            if (в.гаснет > 0 || в.мёртв) continue;
            if (дистанция(в.x, в.y, с.x, с.y) > ОХОТНИК.радиусУдара) continue;
            уронВрагу(в, п.урон * боевойМножитель(и), с.x, с.y);
            /* Отбрасываем ОТ левы, а не от игрока: иначе он своими же
               ударами сгоняет толпу Илье на голову. */
            const у = Math.atan2(в.y - с.y, в.x - с.x);
            в.оттолкX += Math.cos(у) * ОХОТНИК.отброс;
            в.оттолкY += Math.sin(у) * ОХОТНИК.отброс;
            ИГРА.уронСвиты += п.урон;
            задето++;
          }
          if (задето) {
            ИГРА.кольца.push({ x: с.x, y: с.y - 30, r: 6, макс: ОХОТНИК.радиусУдара,
                               жизнь: 0.16, всего: 0.16, цвет: '#ffd08a' });
          }
        }
      } else {
        держатьсяУИгрока(с, дт, к.орбита, ОХОТНИК.скоростьВозврата);
      }
      continue;
    }

    держатьсяУИгрока(с, дт, к.орбита, 420);

    if (к.роль === 'ближний') {
      if (с.кулдаун <= 0) {
        let попал = false, задето = 0;
        for (const в of ИГРА.враги) {
          if (задето >= п.целей) break;
          if (в.гаснет > 0 || в.мёртв) continue;
          if (дистанция(в.x, в.y, с.x, с.y) > п.радиус) continue;
          уронВрагу(в, п.урон * боевойМножитель(и), с.x, с.y);
          ИГРА.уронСвиты += п.урон;
          попал = true; задето++;
        }
        if (попал) {
          с.кулдаун = п.интервал;
          ИГРА.кольца.push({ x: с.x, y: с.y - 30, r: 8, макс: п.радиус,
                             жизнь: 0.18, всего: 0.18, цвет: '#ffd08a' });
        }
      }
    } else if (к.роль === 'снайпер') {
      if (с.кулдаун <= 0) {
        // бьёт самых дальних: ближних и так есть кому месить
        let цель = null, лучшая = -1;
        for (const в of ИГРА.враги) {
          if (в.гаснет > 0 || в.мёртв) continue;
          const д = дистанция(в.x, в.y, и.x, и.y);
          if (д <= п.дальность && д > лучшая) { лучшая = д; цель = в; }
        }
        if (цель) {
          с.кулдаун = п.интервал;
          ИГРА.выстрелы.push({
            x: с.x, y: с.y - 40, цель,
            урон: п.урон * боевойМножитель(и), жизнь: 2.5
          });
        }
      }
    } else if (к.роль === 'танк') {
      if (с.максHp !== п.hp) { с.максHp = п.hp; с.hp = п.hp; }
      с.агро = п.агро; с.толчок = п.толчок;
      if (с.hp < с.максHp) с.hp = Math.min(с.максHp, с.hp + дт * 3);   // отдышивается
    } else if (к.роль === 'таран') {
      if (с.кулдаун <= 0) {
        const цель = ближайшийВрагК(и.x, и.y, п.дальность);
        if (цель) {
          с.кулдаун = п.интервал;
          const у = Math.atan2(цель.y - с.y, цель.x - с.x);
          с.рывокX = Math.cos(у) * 900; с.рывокY = Math.sin(у) * 900;
          с.рывокОсталось = 0.35;
          с.метка = (с.метка || 0) + 1;
          с.задетоЗаПроход = 0;
          с.сторона = Math.cos(у) < 0 ? -1 : 1;
        }
      }
    } else if (к.роль === 'аура') {
      ИГРА.аураЗамедления = { x: и.x, y: и.y, радиус: п.радиус, коэф: п.замедление };
    }
  }
}

function обновитьВыстрелы(дт) {
  for (let i = ИГРА.выстрелы.length - 1; i >= 0; i--) {
    const в = ИГРА.выстрелы[i];
    в.жизнь -= дт;
    const ц = в.цель;
    if (в.жизнь <= 0 || !ц || ц.мёртв) { ИГРА.выстрелы.splice(i, 1); continue; }
    const цy = ц.y - ц.высотаСпрайта * 0.5;
    const д = дистанция(в.x, в.y, ц.x, цy) || 1;
    const ш = Math.min(1300 * дт, д);
    в.x += ((ц.x - в.x) / д) * ш; в.y += ((цy - в.y) / д) * ш;
    if (д < 20) {
      уронВрагу(ц, в.урон, в.x, в.y);
      ИГРА.уронСвиты += в.урон;
      брызги(в.x, в.y, '#cfe6ff', 4);
      ИГРА.выстрелы.splice(i, 1);
    }
  }
}

function обновитьСвиту(дт) {
  обновитьТараканов(дт);
  обновитьЩенков(дт);
  обновитьСоюзников(дт);
  обновитьВыстрелы(дт);
}

/* Кого враг считает целью. Щенки и танк перетягивают агро на себя —
   в этом весь их смысл. Остальные идут на игрока. */
function цельВрага(в, свой) {
  const и = свой || ближайшийИгрок(в.x, в.y);
  let цель = null, лучшая = Infinity;

  for (const щ of ИГРА.щенки) {
    if (щ.выбыл > 0) continue;
    const д = дистанция(в.x, в.y, щ.x, щ.y);
    if (д < ЩЕНКИ.радиусАгро && д < лучшая) { лучшая = д; цель = щ; }
  }
  for (const с of ИГРА.союзники) {
    if (с.конфиг.роль !== 'танк' || !с.агро) continue;
    const д = дистанция(в.x, в.y, с.x, с.y);
    if (д < с.агро && д < лучшая) { лучшая = д; цель = с; }
  }
  return цель || и;
}


